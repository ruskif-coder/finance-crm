/**
 * Одно объяснение ошибки загрузки на все экраны.
 *
 * ЗАЧЕМ. На финансовых экранах `catch` ловил только 401, а остальное проглатывал. Из-за
 * этого сбой сервера выглядел не сбоем: P&L, план-факт и баланс отдавали **белый экран
 * без меню** (`if (!data) return null`), финотчёт — вечную «Загрузку», а кэшфлоу писал
 * зелёным «кассовых разрывов в периоде нет» поверх нулей. Последнее — утверждение о
 * деньгах, и оно было неверным (внешний аудит 11.09.2026, F5-03).
 *
 * ГЛАВНОЕ ПРАВИЛО, ради которого файл существует: **пустой ответ и неслучившийся ответ —
 * разные вещи**. «Нет движений» и «не смогли спросить» человек обязан различать, иначе
 * он принимает решение по картине, которой нет. Тот же принцип, что у прочерка против
 * нуля в реестрах.
 *
 * Текст пишется ДЛЯ ЧЕЛОВЕКА: что случилось и что делать, без кода состояния в качестве
 * объяснения.
 */

/** Отказ в доступе — отдельный случай: это не поломка, а «вам сюда нельзя». */
export const isDenied = (e) => e?.response?.status === 403

/** Не разлогинивает: 401 уже перехвачен глобально в `lib/http`. */
export const isAuth = (e) => e?.response?.status === 401

export function errText(e) {
  const status = e?.response?.status
  const detail = e?.response?.data?.detail

  // Ответа не было вовсе: сеть, упавший контейнер, прокси. Самый частый случай, и
  // именно он раньше выглядел как «данных нет».
  if (!status) return 'Сервер не ответил. Данные не загружены — обновите страницу'

  if (status === 403) return 'Нет доступа к этим данным'
  if (status === 404) return 'Данные не найдены'
  if (status >= 500) {
    return 'Сервер ответил ошибкой. Это сбой загрузки, а не отсутствие данных — '
         + 'показанным цифрам верить нельзя, обновите страницу'
  }
  return detail ? String(detail) : 'Запрос отклонён. Данные не загружены'
}

/** Текст отказа сервера для показа человеку. `detail` у FastAPI — строка, а на ошибке проверки (422) —
 *  СПИСОК объектов `{type, loc, msg, input}`. Положенный в JSX как есть, такой список роняет страницу
 *  (React #31: карточка сделки при назначении трафика, 13.11.2026). Здесь он становится строкой. */
export function detailText(e, fallback) {
  const d = e?.response?.data?.detail
  if (typeof d === 'string' && d) return d
  if (Array.isArray(d) && d.length) {
    return d.map(x => (x && typeof x === 'object' ? x.msg : String(x))).filter(Boolean).join('; ') || fallback
  }
  return fallback
}
