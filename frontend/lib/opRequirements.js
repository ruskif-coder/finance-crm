// Обязательные поля операции — ОДНО правило на подсветку контуром и на проверку сохранения.

// Владелец 27.11.2026: «при создании новой операции по умолчанию статус не выбран и подсвечивается по контуру; если
// статус оплачено — подсвечиваются банк, статья, контрагент; если план оплат/поступлений — статья и контрагент».
//
// Почему библиотекой, а не внутри страницы: правило уже было записано дважды — в подсветке и в alert перед
// сохранением (§2.2 «одно правило в одном месте»). Разъедутся — человек увидит подсвеченное поле, которое
// пропускают, либо «заполните обязательные» без единой подсветки.
//
// Статуса ещё нет — спрашиваем только его: остальное зависит от выбора (у «Оплачено» появляются дата и банк).

export const FIELD_LABEL = {
  status: 'статус', period: 'период', article_id: 'статья',
  counterparty_id: 'контрагент', date: 'дата', bank: 'банк',
}

/** Какие поля операция обязана нести при таком статусе. Пустой статус — только он сам. */
export function requiredKeys(status) {
  if (!status) return ['status']
  const keys = ['period', 'article_id', 'counterparty_id']
  if (status === 'ОПЛАЧЕНО') keys.push('date', 'bank')
  return keys
}

/** Пусто ли значение поля: null/undefined/0, пустая строка и одни пробелы. 0 у id — «не выбрано», а не значение. */
export function isBlank(v) {
  return v === null || v === undefined || v === 0 || (typeof v === 'string' ? !v.trim() : false)
}

/** Пустые из обязательных: [{key, label}]. Форма красит их по контуру, сохранение называет словами. */
export function missingFields(form) {
  return requiredKeys(form.status)
    .filter((k) => isBlank(form[k]))
    .map((k) => ({ key: k, label: FIELD_LABEL[k] || k }))
}
