/* Ссылка из ДАННЫХ — только с безопасной схемой (аудит 23.09.2026, 7.M1).

   Поля «чат площадки», «макет», «мессенджер», «посадочная» заполняют люди, в том числе
   сама площадка. Ссылка вида `javascript:…` в `<a href>` исполняет код у того, кто
   кликнул, — а токен лежит в localStorage, то есть это захват сессии. React 18 на такую
   схему только предупреждает. Сервер новые такие значения уже не принимает; здесь —
   второй рубеж для того, что успело сохраниться раньше.

   Разрешены http, https и tg. Адрес без схемы, похожий на домен («figma.com/…» — так
   на проде лежит), дополняется https://; всё прочее ссылкой не становится (null). */
const OK = /^(https?:\/\/|tg:\/\/)/i
const DOMAIN_LIKE = /^[a-z0-9-]+(\.[a-z0-9-]+)+(\/|$)/i

export default function safeHref(value) {
  const s = String(value ?? '').trim()
  if (!s) return null
  if (OK.test(s)) return s
  if (DOMAIN_LIKE.test(s)) return `https://${s}`
  return null
}
