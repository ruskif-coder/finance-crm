// ── Признак «в колокольчике есть непоказанное» ───────────────────────────────
//
// Отдельным модулем, а не строчкой внутри Nav.js, по одной причине: это ПРАВИЛО,
// у которого есть неочевидный край, и его надо уметь проверить без браузера
// (гейт сборки `scripts/check-notify.mjs` импортирует этот файл, Nav.js — нет: он тянет React).
// Расширение `.mjs` — по образцу `lib/legacy.mjs`: модуль без зависимостей, который
// одинаково читают и сборка Next, и голый node.
//
// Владелец 15.09.2026: «колокольчик уведомлений пусть мигает при новых уведомлениях».

/** Метка свежести списка: самое позднее время среди НЕПРОЧИТАННЫХ строк, '' — нечему.
 *
 *  Не по `id`, хотя так проще и первым приходит в голову. Повторная сработка сканера
 *  не заводит вторую строку: при УХУДШЕНИИ тона она обновляет существующую — двигает
 *  `created_at` и снова делает её непрочитанной (`app/notify/bus.py::_upsert_app_row`).
 *  Id при этом остаётся прежним, и признак «появился больший id» пропустил бы ровно
 *  тот случай, ради которого мигание и нужно: «на неделе» стало «просрочено».
 *
 *  Прочитанные не считаются вовсе: человек их уже разобрал, и звать его к ним снова
 *  незачем — иначе колокольчик мигает всегда и перестаёт что-либо значить.
 */
export const freshMark = (items) => (items || [])
  .filter(n => n && !n.is_read)
  .reduce((m, n) => (String(n.created_at || '') > m ? String(n.created_at || '') : m), '')

/** Мигать ли: есть непоказанное позже того, что человек уже видел.
 *
 *  Строки сравниваются как есть, без разбора дат: обе стороны — одно и то же значение
 *  от одного сервера, а ISO-строки сравниваются лексикографически в том же порядке,
 *  что и моменты времени. Приводить их к часовому поясу здесь незачем и опасно —
 *  наивную дату без «Z» браузер читает как местную (см. lib/dates.js).
 *
 *  Пустая отметка «видел» (первый вход, очищенное хранилище) означает «не видел
 *  ничего»: непрочитанное в панели тогда мигает, и это верно — его не показывали.
 */
export const hasFresh = (mark, seen) => !!mark && mark > (seen || '')
