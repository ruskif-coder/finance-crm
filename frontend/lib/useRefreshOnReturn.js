import { useEffect, useRef } from 'react'
import { hasUnsaved } from '@/lib/unsaved'

/**
 * Перечитать данные, когда человек ВЕРНУЛСЯ на экран.
 *
 * ЗАЧЕМ. В приложении нет механизма актуальности: каждый из сорока экранов грузит
 * данные один раз в `useEffect` при монтировании и больше никогда не перепроверяет
 * (замер 13.09.2026 — перечитывающих при возврате было 0). Вкладка, открытая с утра,
 * показывает утренние данные весь день; правка, сделанная на другом экране или другим
 * человеком, не появляется никогда.
 *
 * Со стороны это выглядит как «кеш»: аккаунт переименовал медиаплан, в реестре осталось
 * старое имя, и человек идёт править второй раз, решив, что не сохранилось.
 *
 * ДВА СОБЫТИЯ, И ОНИ РАЗНЫЕ:
 *
 *   · `visibilitychange` — вернулись на вкладку. Экран всё это время был жив, состояние
 *     компонента никуда не девалось, запросов не было;
 *   · `pageshow` с `event.persisted` — страницу достали из bfcache браузера. Это НЕ
 *     монтирование: React-состояние восстановлено целиком, `useEffect` не сработает, и
 *     без этого слушателя узнать о возврате нечем. Именно так «Назад» после сохранения
 *     возвращает экран со старыми данными.
 *
 * ПОЧЕМУ КОЛБЭК ЧЕРЕЗ REF. Положить `reload` в зависимости эффекта значит
 * переподписываться на каждый рендер, а если `reload` объявлен стрелкой в теле
 * компонента — получить бесконечный цикл запросов. В этом проекте так уже стреляло
 * (память: «Стрелка в пропе = цикл запросов»), поэтому подписка ставится ОДИН раз, а
 * свежая функция берётся из ref в момент вызова.
 *
 * Применение — одна строка рядом с существующей загрузкой:
 *
 *     const load = useCallback(() => { ... }, [])
 *     useEffect(() => { load() }, [load])
 *     useRefreshOnReturn(load)
 *
 * НЕСОХРАНЁННЫЙ ВВОД ВАЖНЕЕ СВЕЖЕСТИ (23.09.2026). Перечитка пишет данные сервера
 * поверх экрана, а многие экраны на время загрузки меняют содержимое на «Загрузка…» и
 * размонтируют всё открытое для правки. Аккаунты собирают материал для годового плана в
 * соседних вкладках — и каждый возврат стирал заполненное. Поэтому, пока на экране есть
 * несохранённый ввод (`lib/unsaved`), возврат его не трогает: устаревшее число —
 * неудобство, стёртая работа — потеря. После сохранения перечитка снова работает.
 */
export default function useRefreshOnReturn(reload, { enabled = true } = {}) {
  const fn = useRef(reload)
  fn.current = reload

  useEffect(() => {
    if (!enabled || typeof window === 'undefined') return undefined
    // Скрытая вкладка не перечитывает: смысл в возврате, а не в каждом переключении.
    const onVisible = () => {
      if (document.visibilityState === 'visible' && typeof fn.current === 'function'
          && !hasUnsaved()) {
        fn.current()
      }
    }
    // `persisted` обязателен: обычный `pageshow` приходит и при первой загрузке, где
    // данные уже грузит монтирование, и без проверки каждый вход стоил бы двух запросов.
    const onShow = (e) => {
      if (e.persisted && typeof fn.current === 'function' && !hasUnsaved()) fn.current()
    }
    document.addEventListener('visibilitychange', onVisible)
    window.addEventListener('pageshow', onShow)
    return () => {
      document.removeEventListener('visibilitychange', onVisible)
      window.removeEventListener('pageshow', onShow)
    }
  }, [enabled])
}
