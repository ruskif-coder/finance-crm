/**
 * Состояние кабинета площадки — один словарь на все экраны.
 *
 * ## Зачем отдельный файл
 *
 * Состояний три, и они значат РАЗНОЕ, хотя два из них одинаково «не работает»:
 *
 * * `черновик` — площадки прикрепили, людей ещё не завели. Вход невозможен, потому
 *   что входить некому;
 * * `приостановлен` — доступ был и его отобрали;
 * * `активен` — работает.
 *
 * Слить первые два в один цвет заманчиво и нельзя: вопрос «почему он не может
 * войти» становится неотвечаемым с экрана.
 *
 * ## Что произошло 21.09.2026
 *
 * Карта «состояние → цвет» оказалась записана дважды: `STATE_TONE` на экране
 * кабинетов и новая `CABINET_TONE` в реестре площадок. Они уже разошлись —
 * `приостановлен` был красным на одном экране и оранжевым на другом, `активен`
 * брал разные токены зелёного. Ни один тест этого не ловит: обе карты «работают».
 *
 * Тот же случай, что с `lib/tone.js` 14.09.2026, и лечится так же — одним словарём.
 *
 * ## Две роли, одно описание
 *
 * `plashka` — заливка и текст для метки на экране кабинетов. `dot` — цвет кружка в
 * реестре площадок, где места на текст нет. Это РАЗНЫЕ роли одного смысла, а не две
 * копии правила: каждое состояние описано здесь ровно один раз.
 */

export const CABINET_STATES = ['активен', 'приостановлен', 'черновик']

export const CABINET_STATE = {
  'активен': {
    plashka: ['var(--income-tint)', 'var(--income-fg)'],
    dot: 'var(--success)',
    hint: 'кабинет активен',
  },
  'приостановлен': {
    plashka: ['var(--danger-tint)', 'var(--danger-fg)'],
    dot: 'var(--warning)',
    hint: 'кабинет приостановлен — вход закрыт',
  },
  'черновик': {
    plashka: ['var(--bg-subtle)', 'var(--text-muted)'],
    dot: 'var(--text-faint)',
    hint: 'кабинет заведён, людей ещё нет',
  },
}

/** Описание состояния. Неизвестное — как черновик: незаведённое, а не сломанное. */
export const cabinetState = (state) => CABINET_STATE[state] || CABINET_STATE['черновик']
