/**
 * Есть ли на экране несохранённый ввод — одна точка на весь фронт.
 *
 * ЗАЧЕМ. С 13.09.2026 экраны перечитывают данные, когда человек возвращается на
 * вкладку (`lib/useRefreshOnReturn`). Перечитка пишет данные сервера ПОВЕРХ того, что
 * лежит в экране, а многие экраны на время загрузки ещё и меняют содержимое на
 * «Загрузка…» — и всё открытое для правки размонтируется. Итог (жалоба 23.09.2026):
 * аккаунт заполняет годовой план, уходит в соседнюю вкладку за материалом, возвращается
 * — заполненного нет. Выглядит как потеря данных, и по сути ею и является.
 *
 * Правило: пока на экране есть несохранённый ввод, возврат на вкладку его НЕ трогает.
 * Устаревшее число на экране — неудобство; стёртая работа — потеря.
 *
 * КАК ОПРЕДЕЛЯЕТСЯ «НЕСОХРАНЁННОЕ». Два источника:
 *
 *   1. Поля, в которые человек что-то ввёл (событие `input`/`change` от него самого, а
 *      не от кода). Поле считается несохранённым, ПОКА ОНО НА ЭКРАНЕ: закрыли окно,
 *      сохранили карточку, ушли со страницы — поле размонтировалось, и учёт снялся сам.
 *      Поэтому здесь не нужно знать, где у каждого экрана кнопка «Сохранить».
 *   2. Явная отметка `markDirty()` — для экранов, где правка идёт щелчками (выбор из
 *      списка, переключатели), а не вводом. Такой экран сам снимает её `markClean()`
 *      после сохранения. Смена страницы снимает всё.
 *
 * ПОЛЯ ПОИСКА НЕ СЧИТАЮТСЯ. Перечитка их не стирает — строка поиска живёт в состоянии
 * экрана, а не в данных сервера, — и засчитай мы их, реестр с набранным поиском
 * перестал бы обновляться вовсе. Отличаем по `type="search"`, по подписи «Поиск…» и по
 * метке `data-no-unsaved` на поле или его предке — её ставят фильтрам, которые не
 * «Поиск», но и не ввод данных.
 */
import Router from 'next/router'

const edited = new Set()   // поля, в которые вводили; живы, пока на экране
let flagged = false        // явная отметка экрана с правкой щелчками
let installed = false

const isFilter = (el) =>
  el.type === 'search'
  || /^\s*Поиск/i.test(el.getAttribute?.('placeholder') || '')
  || !!el.closest?.('[data-no-unsaved]')

const isEditable = (el) =>
  el && (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA' || el.tagName === 'SELECT'
         || el.isContentEditable)

function onUserInput(e) {
  // `isTrusted` — ввёл человек. Программная подстановка значения (автозаполнение из
  // данных сервера) правкой не является и перечитку не блокирует.
  const el = e.target
  if (!e.isTrusted || !isEditable(el) || isFilter(el)) return
  edited.add(el)
}

function install() {
  if (installed || typeof window === 'undefined') return
  installed = true
  // Фаза перехвата: часть полей гасит всплытие своих событий, а учёт должен увидеть все.
  document.addEventListener('input', onUserInput, true)
  document.addEventListener('change', onUserInput, true)
  // Другая страница — другая работа. Несохранённое осталось на прошлой, и держать из-за
  // него обновление новой незачем.
  Router.events.on('routeChangeComplete', markClean)
}

/** Экран с правкой щелчками отмечает, что в нём есть несохранённое. */
export function markDirty() { install(); flagged = true }

/** Сохранено — снять и явную отметку, и учёт полей. */
export function markClean() { flagged = false; edited.clear() }

/** Есть ли на экране несохранённый ввод прямо сейчас. */
export function hasUnsaved() {
  install()
  for (const el of edited) {
    // Поле ушло с экрана — его правка либо сохранена, либо отменена вместе с окном.
    if (!el.isConnected) edited.delete(el)
  }
  return flagged || edited.size > 0
}

install()
