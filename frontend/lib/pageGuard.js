/**
 * Один ответ на вопрос «пускать ли на этот экран» — из карты навигации.
 *
 * ЗАЧЕМ. Сервер права проверяет на каждой ручке, это не обсуждается. Но меню прячет
 * пункт, а прямая ссылка экран ОТКРЫВАЕТ — и дальше каждая страница ведёт себя по-своему:
 * одна показывает 403, вторая пустую таблицу, третья белый лист. Человек видит не «нет
 * доступа», а «сломалось», и идёт спрашивать, что случилось.
 *
 * Так было на пяти финансовых экранах и в системных настройках (F5-04 внешнего аудита
 * 11.09.2026; список самого аудита при этом был неточен в обе стороны — проверено).
 *
 * ПОЧЕМУ ОТ КАРТЫ, А НЕ КОНСТАНТОЙ НА СТРАНИЦЕ. Ключ права у экрана уже записан в
 * `nav.data.json` — там же, откуда строится меню. Продублировать его в странице значит
 * завести вторую правду: поменяют в карте, забудут в странице, и гард начнёт пускать не
 * тех. Ключ права вообще неизменяем (он лежит строкой в `role_permissions` у живых
 * пользователей), и второе место, где он записан, — это будущее расхождение.
 *
 * ПОЧЕМУ НЕ РЕДИРЕКТ. Увести человека на другой экран — значит не ответить на его
 * вопрос: он кликнул по ссылке из письма и оказался неизвестно где. Честнее сказать, куда
 * он попал и почему не пустили.
 */
import { findByPath } from '@/lib/nav'
import { can, getPermissions } from '@/lib/auth'

/**
 * @returns 'loading' | 'ok' | 'denied'
 *
 * `loading` — до монтирования: снимок прав живёт в localStorage, а на сервере его нет.
 * Отдавать 'denied' в этот момент нельзя — экран моргнёт отказом у того, у кого доступ
 * есть.
 */
export function pageAccess(pathname, mounted) {
  if (!mounted) return 'loading'
  const found = findByPath(pathname)
  // Экрана нет в карте — гардить нечем, и выдумывать правило здесь неправильно.
  // `check-nav` в сборке и так не пропускает новый экран мимо карты.
  if (!found || !found.item.perm) return 'ok'
  return can(getPermissions(), found.item.perm, 'view') ? 'ok' : 'denied'
}
