import { useCallback, useRef } from 'react'

/**
 * Пропускать только ПОСЛЕДНИЙ ответ — один механизм на все экраны с фильтрами.
 *
 * ЗАЧЕМ (аудит 23.09.2026, 6.M4 и 7.M4). Сменил фильтр дважды подряд — ушло два запроса,
 * и если первый ответил позже второго, на экране оказывались данные ПЕРВОГО фильтра под
 * подписью второго. Финотчёт при открытии делал это сам: восстановление режима из
 * localStorage и загрузка с умолчаниями шли одним проходом, и подпись «по оплате»
 * стояла над цифрами «по начислению».
 *
 * Применение:
 *
 *     const latest = useLatest()
 *     const load = async () => {
 *       const fresh = latest()
 *       const res = await api.get(...)
 *       if (!fresh()) return          // пока ждали, ушёл запрос новее — этот не нужен
 *       setData(res.data)
 *     }
 *
 * Ошибку устаревшего запроса тоже глотаем через `fresh()`: сбой старого фильтра не
 * должен рисоваться над данными нового.
 */
export default function useLatest() {
  const gen = useRef(0)
  return useCallback(() => {
    const mine = ++gen.current
    return () => mine === gen.current
  }, [])
}
