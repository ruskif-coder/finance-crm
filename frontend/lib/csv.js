// Ячейка CSV для выгрузок в браузере — одна на весь фронт.
//
// Excel исполняет строку, начинающуюся с = + - @ (и таб/перевод строки перед ними),
// как формулу: название контрагента или сделки вида «=HYPERLINK(…)» или «=cmd|…»
// срабатывало у того, кто открыл выгрузку (ревью этапа 9 аудита, 24.09.2026). Такой
// строке ставим ведущий апостроф — Excel покажет текст как есть.
//
// ЧИСЛА не трогаем: отрицательная сумма остаётся числом, а не текстом «'-500».
const RISKY = /^[=+\-@\t\r]/

export function csvCell(v) {
  if (v === null || v === undefined) return '""'
  if (typeof v === 'number') return String(v)
  const s = String(v)
  const safe = RISKY.test(s) ? `'${s}` : s
  return `"${safe.replace(/"/g, '""')}"`
}
