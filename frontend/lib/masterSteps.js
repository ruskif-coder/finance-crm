/** Кнопка следующей отметки: подпись зависит от канала (ЭДО — «Отправлен в ЭДО», бумага — «Отправлен клиенту»). */
export function signAction(next, sign) {
  const paper = sign?.channel === 'бумага'
  if (next === 'выставлен') return sign?.state === 'отклонён' ? 'Выставить снова' : paper ? 'Отправлен клиенту' : 'Отправлен в ЭДО'
  return { 'согласован': 'Согласован клиентом', 'подписан у нас': 'Подписан у нас', 'подписан': 'Подписан клиентом',
    'отклонён': 'Клиент отклонил' }[next] || next
}

/** ДС пакета, которые карточка показывает строкой «ДС пакета созданы» вместо кнопки «В конструктор ДС →».
 * Черновик пакета — ДС закрытия ещё нет: подписанный ДС старта остаётся в пакете после «Отправить в ДО» (и после «Вернуть в
 * раскладку»), но кнопку конструктора не прячет — иначе пакет нечем закрыть (прод 12.11.2026, M-0036). */
export function createdAnnexes(m) {
  return m?.status === 'черновик' ? [] : (m?.annexes || [])
}

/** Подпись кнопки строки: у «Отправить» — сколько документов осталось (реестр v3, `send` с сервера). */
export function stepLabel(step, key, send) {
  if (key !== 'send' || !send) return step.label
  return send.left === send.total ? `${step.label} · ${send.total}` : `${step.label} · ещё ${send.left}`
}
