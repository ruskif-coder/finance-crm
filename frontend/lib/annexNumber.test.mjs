// Правило «ДС № / ПР №» (владелец 09.11 и 18.11.2026). Примеры — ТЕ ЖЕ, что в backend/tests/test_ds_label.py: правило одно на
// экран и сервер. Ломается, если вернуть «Прил. №», если сокращение тронет запись без номера («доплата июль»), или если ручные
// написания («доп.12», «прил 64») снова останутся как есть — до 18.11.2026 так и было, владелец решил вводить правило.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { shortAnnexNumber } from './annexNumber.js'

const CASES = [
  ['Приложение № 17', 'ПР № 17'], ['Дополнительное соглашение № 28', 'ДС № 28'], ['Доп. соглашение №68', 'ДС № 68'],
  ['доп.12', 'ДС № 12'], ['доп 153', 'ДС № 153'], ['доп. 8', 'ДС № 8'], ['доп.согл.4', 'ДС № 4'], ['доп.12-1', 'ДС № 12-1'],
  ['прил 64', 'ПР № 64'], ['прил.15', 'ПР № 15'], ['прилож. 19', 'ПР № 19'], ['Приложение № 5-2', 'ПР № 5-2'],
  ['ДС № 12', 'ДС № 12'], ['ПР № 64', 'ПР № 64'],
  ['доплата июль', 'доплата июль'], ['заявка 3', 'заявка 3'], ['пени', 'пени'], ['95', '95'], ['доп да-1/2', 'доп да-1/2'],
]

test('все написания — к «ДС № N» / «ПР № N», запись без номера — как есть', () => {
  for (const [raw, want] of CASES) assert.equal(shortAnnexNumber(raw), want, raw)
})

test('пустое — как есть', () => {
  assert.equal(shortAnnexNumber(''), '')
  assert.equal(shortAnnexNumber(null), null)
})
