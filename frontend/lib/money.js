// Ввод денег с копейками — одна точка на весь фронт.
//
// Сумму храним СТРОКОЙ, пока человек печатает (курсор не прыгает, копейки набираются), и
// превращаем в число при сохранении. До 23.09.2026 у мобильной формы был свой разбор —
// `replace(/\D/g, '')`, — он выкидывал запятую: «1500,50» становилось 150 050 ₽, а
// правка суммы 100 714,71 сохраняла округлённые 100 715 (аудит 23.09.2026, 6.H5).
//
// Несколько разделителей — это вставка с разрядами: «1,500.50», «1.500,50», «1.000.000».
// До ревью 23.09.2026 копейками считался ПЕРВЫЙ разделитель, и «1,500.50» давало 1,5005 —
// сумма тихо уменьшалась в тысячу раз. Теперь копейки — за ПОСЛЕДНИМ разделителем, если за
// ним не больше двух цифр (в том числе ни одной — человек только что поставил запятую);
// остальные разделители — разряды. Один разделитель — как и раньше, копейки.

/** Оставить цифры и не больше одного разделителя копеек. Пробелы, «₽» и разряды уходят. */
export const sanMoney = (s) => {
  s = String(s ?? '').replace(/[^\d.,]/g, '')
  const seps = [...s.matchAll(/[.,]/g)]
  if (seps.length <= 1) return s
  const last = seps[seps.length - 1].index
  const tail = s.slice(last + 1)
  const digits = (x) => x.replace(/[.,]/g, '')
  return tail.length <= 2 ? digits(s.slice(0, last)) + s[last] + tail : digits(s)
}

/** Строка ввода → число. Пустое и мусор → 0. */
export const moneyNum = (v) => {
  const n = parseFloat(sanMoney(v).replace(',', '.'))
  return Number.isFinite(n) ? n : 0
}
