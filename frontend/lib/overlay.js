/**
 * Закрытие модального окна кликом по подложке — так, чтобы выделение текста мышкой
 * не считалось кликом.
 *
 * ПОЧЕМУ ЭТО НЕ ЛЕЧИТСЯ ПРОВЕРКОЙ `e.target === e.currentTarget`. Событие `click`
 * в DOM рождается не там, где отпустили кнопку, а на ОБЩЕМ ПРЕДКЕ того элемента, где
 * нажали, и того, где отпустили. Человек выделяет текст внутри окна, ведёт мышь и
 * отпускает её на подложке — общий предок это подложка, `e.target` равен
 * `e.currentTarget`, проверка проходит, и окно закрывается вместе с тем, что человек
 * только что набрал или пытался скопировать. `stopPropagation` на самом окне не
 * помогает: событие в окне вообще не возникает.
 *
 * Поэтому смотрим ещё и на то, ГДЕ НАЧАЛОСЬ движение. Закрываем, только если и нажатие,
 * и отпускание пришлись на саму подложку.
 *
 * Цель последнего нажатия хранится в модуле, а не в замыкании и не в состоянии:
 * замыкание пересоздаётся при перерисовке между нажатием и отпусканием, и настоящий
 * клик переставал бы закрывать окно. Мышь одна, жест не бывает параллельным — модульная
 * переменная тут ровно по размеру задачи.
 *
 * Применение: `<div {...overlayClose(onClose)} style={{ position: 'fixed', inset: 0, … }}>`
 */
let lastMouseDownTarget = null

export function overlayClose(onClose) {
  return {
    onMouseDown: (e) => { lastMouseDownTarget = e.target },
    onClick: (e) => {
      if (e.target === e.currentTarget && lastMouseDownTarget === e.currentTarget) {
        // Событие передаётся дальше: обработчики, написанные до этого помощника,
        // сами проверяли `e.target === e.currentTarget`, и без аргумента такой
        // обработчик падал бы на `e.target` — окно переставало закрываться вовсе.
        onClose?.(e)
      }
    },
  }
}
