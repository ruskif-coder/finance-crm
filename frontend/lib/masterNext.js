/**
 * Первые этапы пакета словами процесса и «что сделать, чтобы пойти дальше» (владелец 12.11.2026): итоговая сверка → сборка ДС →
 * согласование ДС. Карточка (`StagePipeline`) и полоса реестра (`masterStepBar`) берут текст отсюда — чтобы не расходились.
 * Данные — карточка пакета: `status`, `sequence`, `todo` (сервер, `status.todo`), `deals[].state` (`service.deal_status`), `annexes`.
 */
const LABEL = { 'черновик': 'сборка ДС', 'согласование': 'согласование ДС', 'ждём закрытия': 'итоговая сверка' }
const RECON = 'итоговая сверка'
const DEAL_WHY = {
  rk: ['РК не завершена', 'дождитесь конца РК и переведите сделку на «Итоговую сверку»'],
  recon: ['сверка не завершена', 'проведите итоговую сверку и подтвердите её'],
  ready: ['сверка подтверждена', 'нажмите на карточке сделки «Отправить в ДО»'],
}

const waitsRecon = (m) => m.status === 'ждём закрытия' || (m.status === 'черновик' && /сверк/.test(m.todo?.text || ''))

/** Сегменты конвейера: у обычного пакета сверка — пройденный шаг перед сборкой (пакет рождается из «Отправить в ДО»). */
export function stagesOf(m) {
  const seq = m.sequence || []
  const start = seq.includes('ждём закрытия')
  const items = [...(start ? [] : [{ key: 'recon', label: RECON }]), ...seq.map(s => ({ key: s, label: LABEL[s] || s }))]
  let current = items.findIndex(x => x.key === m.status)
  if (!start && waitsRecon(m)) current = 0
  return { items, current }
}

function recon(m) {
  const left = (m.deals || []).filter(d => d.state !== 'done')
  const first = left[0]
  const closing = m.status === 'ждём закрытия'
  if (!first) {
    return { text: 'Сверка сделок завершена', hint: closing ? 'Нажмите «Отправить в ДО» на карточке сделки — пакет вернётся в сборку ДС закрытия.' : '', who: 'аккаунт' }
  }
  const [why, todo] = DEAL_WHY[first.state] || DEAL_WHY.recon
  const more = left.length > 1 ? ` и ещё ${left.length - 1}` : ''
  const after = closing ? ' Потом «Отправить в ДО» на карточке сделки — пакет вернётся в сборку ДС закрытия по факту.' : ''
  return { text: `Завершите итоговую сверку сделки ${first.code}${more}`, hint: `${first.code}: ${why} — ${todo}.${after}`, who: 'аккаунт',
    link: { label: `Открыть сделку ${first.code} →`, href: `/sales/deals/${first.code}` } }
}

function assemble(m) {
  const t = m.todo?.text || ''
  if (/номер|№ ДС/.test(t)) {
    return { text: 'Задайте стартовый № ДС', hint: 'Поле «Стартовый номер» в «Раскладке» слева: последний актуальный № по договору — ДС пакета пронумеруются от следующего.', who: 'аккаунт', scroll: 'layout' }
  }
  if (/свести|не сходится/.test(t)) {
    return { text: 'Сведите раскладку с суммой сделок', hint: 'Строки и настройки — в «Раскладке» слева; итог ДС должен совпасть с суммой к закрытию.', who: 'аккаунт', scroll: 'layout' }
  }
  if (/позици/.test(t)) {
    return { text: 'Разложите позиции по ДС', hint: 'В «Раскладке» слева: группировка строк ДС и деление закрывающих.', who: 'аккаунт', scroll: 'layout' }
  }
  if (t && t !== 'создать ДС') return { text: t[0].toUpperCase() + t.slice(1), hint: 'Исправьте в «Раскладке» слева — потом «В конструктор ДС →».', who: 'аккаунт', scroll: 'layout' }
  return { text: 'Раскладка готова — создайте ДС пакета', hint: 'Кнопка «В конструктор ДС →» внизу карточки: ДС соберутся черновиками, дальше — согласование.', who: 'аккаунт', scroll: 'to-annex' }
}

function agree(m) {
  if (m.todo?.who === 'юрист') {
    return { text: 'ДС у юриста — ждём согласования', hint: `${m.todo.text}: от вас ничего не нужно. Правка ДС запустит согласование заново.`, who: 'юрист' }
  }
  if (m.unconfirmed === 0) {        // вернули на «согласование» — ДС уже с номерами (12.11.2026)
    return { text: 'Пересоберите ДС по текущим данным и отправьте в 1С',
      hint: '«Обновить из сделки» пересоберёт ДС и комплекты (номера и даты прежние), проверьте текст — затем «ДС проверены → в 1С» внизу.', who: 'аккаунт', scroll: 'confirm' }
  }
  const left = (m.annexes || []).filter(a => !a.confirmed).map(a => a.number)
  return { text: left.length ? `Подтвердите ДС: ${left.join(', ')}` : 'Подтвердите ДС пакета',
    hint: 'Проверьте текст («Править ДС →») и нажмите «Подтвердить ДС пакета» внизу — номера займутся, пакет уйдёт бухгалтеру в 1С.', who: 'аккаунт', scroll: 'confirm' }
}

/** Куда прокручивает кнопка этапа в карточке: элемент с `data-step-target`. */
export const SCROLL_LABEL = { layout: 'К раскладке ↓', 'to-annex': 'К «В конструктор ДС» ↓', confirm: 'К подтверждению ↓' }

/** Что сделать сейчас: { text, hint, who, link?, scroll? }; null — этап дальше согласования (там свой текст). */
export function nextAction(m) {
  if (waitsRecon(m)) return recon(m)
  if (m.status === 'черновик') return assemble(m)
  if (m.status === 'согласование') return agree(m)
  return null
}

