/**
 * Имя сделки и медиаплана — ОДИН генератор на все экраны.
 *
 * До 03.09.2026 их было пять, и они расходились по-настоящему, а не косметически:
 *
 *   · форма создания сделки резала длинные подписи справочника до « | » (в списках
 *     они приходят как «Название | ИНН»), а три реестра — нет, и в название сделки
 *     уезжал ИНН;
 *   · конструктор медиаплана собирал имя из четырёх частей БЕЗ УСЛУГИ и склеивал их
 *     через « · », а сделки — из пяти через « | »: два имени об одном и том же
 *     размещении выглядели как имена разных вещей;
 *   · дедупликация одинаковых частей (рекламодатель и бренд часто совпадают) была
 *     только в медиаплане.
 *
 * Правило одно: `Рекламодатель | Бренд | Агентство | Услуга | Период`. Пустые части
 * выпадают, повторы схлопываются, разделитель один.
 *
 * Поверхность (WEB/APP) дописывается К УСЛУГЕ и только у услуг с раздельным прайсом
 * (владелец 03.09.2026) — сегодня это еФарм. Признак приходит из справочника услуг
 * (`separate_price`), в код не зашит: услуг с раздельным прайсом станет больше.
 */

export const TITLE_SEP = ' | '

/** Короткая часть подписи справочника: «ООО Ромашка | 7701234567» → «ООО Ромашка». */
export const shortName = (s) => (s ? String(s).split(' | ')[0].trim() : '')

/** Подпись поверхности. 'cross' — обе, поэтому пишется парой, а не третьим словом. */
export const SURFACE_TAG = { web: 'WEB', app: 'APP', cross: 'WEB+APP' }

export const surfaceTag = (inventory) => SURFACE_TAG[String(inventory || '').toLowerCase()] || ''

/**
 * Набор услуг с раздельным прайсом из ответа `/sales/directories/services`.
 * Экран, который справочник не грузит, просто не передаёт набор — тогда метки не будет,
 * и это честнее, чем угадывать по имени услуги.
 */
export const separatePriceSet = (services) =>
  new Set((services || []).filter(s => s.separate_price).map(s => s.name))

/** Услуга с поверхностью: «еФарм WEB». Без раздельного прайса — просто услуга. */
export function serviceLabel(product, inventory, separate) {
  const name = shortName(product)
  if (!name) return ''
  const tag = (separate && separate.has(name)) ? surfaceTag(inventory) : ''
  return tag ? `${name} ${tag}` : name
}

/**
 * Услуга с поверхностью для ВИТРИН, где `inventory` посчитал сервер.
 *
 * Справочник услуг здесь не нужен: `app/sales/row_context.inventory` возвращает
 * поверхность ТОЛЬКО у услуг с раздельным прайсом, поэтому пустое значение означает
 * «метки быть не должно», а не «не смогли определить». Экраны, которые собирают имя
 * из справочника (форма создания, конструктор МП), пользуются `serviceLabel`.
 */
export function productWithSurface(product, inventory) {
  const name = (product || '').trim()
  const tag = surfaceTag(inventory)
  return tag && name ? `${name} ${tag}` : name
}

/**
 * Имя по шаблону. Все части — уже готовые строки или подписи справочника (режутся сами).
 * `separate` — набор из `separatePriceSet`, необязателен.
 */
export function buildTitle({ advertiser, brand, agency, product, inventory, period, separate }) {
  const parts = [
    shortName(advertiser), shortName(brand), shortName(agency),
    serviceLabel(product, inventory, separate),
    (period || '').trim(),
  ].filter(x => x && x.trim())
  // Дедуп: у половины рекламодателей бренд называется так же, и «Виферон | Виферон»
  // читается как ошибка ввода. Порядок первого появления сохраняется.
  return [...new Set(parts)].join(TITLE_SEP)
}

/** Из чего имя не собирается — одной фразой для подсказки пользователю. */
export const TITLE_EMPTY_HINT =
  'Нечего собрать: нет рекламодателя / бренда / агентства / услуги / периода.'
