// Короткий номер ДС / приложения в СИСТЕМЕ: «ДС № 12» / «ПР № 64» — ПРАВИЛО (владелец 18.11.2026: «в документах пишем полностью,
// в системе экономим место»; формат — 09.11.2026). Двойник серверного `backend/app/ds_label.py`: одни и те же примеры в
// lib/annexNumber.test.mjs и backend/tests/test_ds_label.py. В базе операций номер уже хранится коротким (валидатор модели), здесь —
// для номеров ДС из конструктора, которые сервер отдаёт словом документа («Дополнительное соглашение № 68»).
// Сокращается, только если после слова идёт номер: «доплата июль», «заявка 3», голое число — как есть.
const DS = /^\s*(?:дополнительное\s+соглашение|доп\.?\s*соглашение|доп\.?\s*согл\.?|доп\.?|д\/?с)\s*[.№#]*\s*(?=\d)/i
const PR = /^\s*(?:приложение|прилож\.?|прил\.?|пр\.?)\s*[.№#]*\s*(?=\d)/i

export function shortAnnexNumber(number) {
  if (!number) return number
  const s = String(number).trim()
  for (const [re, word] of [[DS, 'ДС № '], [PR, 'ПР № ']]) {
    const m = s.match(re)
    if (m) return word + s.slice(m[0].length).trim()
  }
  return s
}
