// Короткий номер документа для экранов: «ДС № 68» / «ПР № 68» (владелец 04.11.2026, справочник ДС: «не видно номера, можно
// сократить»; 09.11.2026 — «ДС №, ПР №», и в колонке «№ ДС» операций, и в реестре мастер-сделок). Сервер отдаёт номер тем словом, каким он печатается в документе
// (`annex_tpl/doc_kind.number_text`: «Доп. соглашение № 68», раньше и «Дополнительное соглашение №68»); полная форма
// остаётся в документе, сокращение — только на экране. Незнакомое начало возвращается как есть.
const SHORT = [
  [/^\s*(дополнительное|доп\.?)\s*соглашение\s*/i, 'ДС '],
  [/^\s*приложение\s*/i, 'ПР '],
]

export function shortAnnexNumber(number) {
  if (!number) return number
  for (const [re, word] of SHORT) {
    if (re.test(number)) return (word + number.replace(re, '')).replace(/№\s*/, '№ ')
  }
  return number
}
