/**
 * Гейт сборки: экран входа не тянет за собой систему.
 *
 * ЗАЧЕМ. `/login` — единственная страница, которая открывается ДО авторизации. Всё, что
 * в неё импортировано, уезжает в браузер анонимного посетителя и грузится до того, как
 * кто-либо назвал себя. До 13.09.2026 ради одной функции `firstAllowedHref` страница
 * импортировала `components/Navbar` → `Nav` → карту навигации, и вместе с ними в бандл
 * логина попадали названия, адреса и права ВСЕХ экранов системы — отдельный чанк на
 * 28 КБ, который браузер честно скачивал на форме из двух полей.
 *
 * ЧТО ЛОВИМ. Любой импорт в `pages/login.js`, кроме разрешённых ниже: React, next/* и
 * http-клиент. Правило намеренно жёсткое — «мне нужна всего одна функция» и есть тот
 * ход, которым сюда затянули всю навигацию.
 *
 * Если новой форме входа что-то ДЕЙСТВИТЕЛЬНО нужно — выносить это отдельным модулем
 * без зависимостей и добавлять сюда осознанно, а не расширять список по инерции.
 */
import { readFileSync } from 'node:fs'

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const FILE = 'pages/login.js'

// Разрешено: сам React, маршрутизатор и голова страницы, http-клиент.
const ALLOWED = [/^react$/, /^next\//, /^axios$/]

const text = readFileSync(ROOT + FILE, 'utf8')
const bad = []
for (const m of text.matchAll(/^import[^'"]*['"]([^'"]+)['"]/gm)) {
  const src = m[1]
  if (ALLOWED.some(rx => rx.test(src))) continue
  const line = (text.slice(0, m.index).match(/\n/g) || []).length + 1
  bad.push(`${FILE}:${line}  ${src}`)
}

if (bad.length) {
  console.error('\nЭкран входа импортирует части системы. Они попадут в бандл, который')
  console.error('браузер скачивает ДО авторизации — вместе с картой приложения:\n')
  bad.forEach(b => console.error('  ' + b))
  console.error('\nКуда вести человека после входа, решает «/» — там карта уже к месту.\n')
  process.exit(1)
}
console.log('check-login: экран входа держит только форму — порядок')
