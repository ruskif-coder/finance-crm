/**
 * Гейт сборки: признак «в колокольчике есть непоказанное» ведёт себя правильно.
 *
 * ЗАЧЕМ. Владелец 15.09.2026: «колокольчик уведомлений пусть мигает при новых
 * уведомлениях». Правило выглядит однострочным, и у него есть один неочевидный край,
 * на котором оно тихо ломается.
 *
 * КРАЙ. Повторная сработка сканера НЕ заводит вторую строку в панели: при ухудшении
 * тона она обновляет существующую — двигает `created_at` и снова делает её
 * непрочитанной (`backend/app/notify/bus.py::_upsert_app_row`). ID при этом остаётся
 * прежним. Поэтому напрашивающийся признак «появился больший id» пропустил бы ровно
 * тот случай, ради которого мигание и заводили: «на неделе» стало «просрочено».
 *
 * Молча: колокольчик просто не мигнёт, и никто не узнает, что он должен был.
 * Экранного теста у фронта нет, поэтому правило проверяется здесь — прямым вызовом.
 *
 * ЧТО ПРОВЕРЯЕМ. Шесть утверждений про `lib/notify.mjs`, включая край выше и обратный
 * ему: прочитанное не зовёт обратно, а открытие панели мигание снимает.
 */
import { freshMark, hasFresh } from '../lib/notify.mjs'

const fails = []
const ok = (cond, what) => { if (!cond) fails.push(what) }

// Пустой список и прочитанные — мигать нечему.
ok(freshMark([]) === '', 'пустой список даёт непустую метку')
ok(!hasFresh(freshMark([{ id: 5, is_read: true, created_at: '2026-09-15T10:00:00' }]), ''),
   'прочитанное зовёт обратно')

// Непрочитанное без отметки «видел» — мигаем; после открытия панели — нет.
const one = [{ id: 5, is_read: false, created_at: '2026-09-15T10:00:00' }]
const seen = freshMark(one)
ok(hasFresh(seen, ''), 'непоказанное не мигает')
ok(!hasFresh(freshMark(one), seen), 'мигает после того, как панель открыли')

// КРАЙ: та же строка, тот же id, но время сдвинуто и она снова непрочитана.
const worse = [{ id: 5, is_read: false, created_at: '2026-09-15T11:30:00' }]
ok(hasFresh(freshMark(worse), seen),
   'ухудшение тона той же строки не поднимает мигание — признак съехал на id?')

// Соседняя новая строка при уже прочитанной старой.
ok(hasFresh(freshMark([{ id: 5, is_read: true, created_at: '2026-09-15T10:00:00' },
                       { id: 9, is_read: false, created_at: '2026-09-15T12:00:00' }]), seen),
   'новая строка не поднимает мигание')

if (fails.length) {
  console.error('check-notify: колокольчик мигает неверно\n  · ' + fails.join('\n  · '))
  process.exit(1)
}
console.log('check-notify: ok')
