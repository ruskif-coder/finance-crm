# -*- coding: utf-8 -*-
"""Каждый коннектор к внешней системе виден на экране состояния.

ЗАЧЕМ. Модуль `app/system/status.py` заведён после случая, когда база DSP лежала три часа
и об этом никто не узнал. Его обещание — «тихий отказ становится видимым». Обещание
держится ровно до тех пор, пока СПИСОК наблюдаемых связей совпадает со списком связей,
которые у нас есть.

11.09.2026 он не совпадал. Наблюдались четыре: Битрикс, ОРД, DSP, Телеграм. Weborama —
пятая, полностью настроенная и рабочая, на которой держится заведение пикселей, — не
наблюдалась вовсе. Пропади у неё доступ, экран остался бы зелёным, а заведение молча
перестало бы работать: ровно тот сценарий, против которого весь модуль и написан.

Найдено не прибором, а руками — потому что прибора не было. Теперь есть.

ПОЧЕМУ СО СПИСКОМ В ТЕСТЕ. Список ниже — не дубль кода, а ТОЧКА ПРИНЯТИЯ РЕШЕНИЯ. Новый
коннектор роняет тест до тех пор, пока кто-то не ответит на вопрос «а видно ли его, когда
он отвалится». Тот же приём, что у `test_permissions_groups` с ключами прав: список
пинится строгим равенством именно чтобы изменение нельзя было внести молча.
"""
import pathlib

import pytest

from app.system.status import check_external_config

APP = pathlib.Path(__file__).resolve().parent.parent / "app"

# Пакет коннектора → ключ проверки на экране состояния.
#
# Пакетом считаем каталог с `client.py`: так устроены все три наших клиента к чужим API.
# Битрикс ходит через `sales/bitrix/transport.py` и клиентом в этом смысле не является,
# поэтому в обходе не находится, но наблюдается наравне с остальными.
EXPECTED = {
    "ord": "ext_ord",
    "dsp": "ext_dsp",
    "weborama": "ext_wcm",
    # Почтовый гейт (13.09.2026). Связь наружу такая же, как у остальных: молчит она
    # ровно так же тихо — письма просто перестают уходить, а очередь копится.
    "mail": "ext_mail",
}

# Наблюдаемые связи без своего пакета-клиента. Каждая — осознанное решение, а не остаток.
WATCHED_WITHOUT_CLIENT = {
    "ext_bitrix",   # ходит через sales/bitrix/transport.py
    "ext_tg",       # ходит через notify/, отдельного клиента нет
}


def _connector_packages() -> set:
    """Каталоги под `app/`, в которых лежит `client.py`."""
    return {p.parent.name for p in APP.glob("*/client.py")}


def _watched_keys() -> set:
    """Ключи связей, которые РЕАЛЬНО отдаёт проверка конфигурации.

    Зовём саму функцию, а не разбираем её текст: так проверяется результат, а не
    намерение. Строки таблицы внутри неё могут переехать куда угодно — важно, что
    на экране появится.
    """
    return {c["key"] for c in check_external_config()}


def test_every_connector_package_is_decided_about():
    """Новый коннектор обязан попасть в список выше — с ответом, наблюдаем его или нет."""
    undecided = sorted(_connector_packages() - set(EXPECTED))
    assert not undecided, (
        f"Появился коннектор, про который никто не решил, видно ли его отказ: {undecided}. "
        "Впишите его в EXPECTED и добавьте проверку в app/system/status.py — иначе он "
        "отвалится молча.")


def test_no_stale_names_in_the_list():
    """Обратная сторона: пакет удалили, строка осталась — список врёт про охват."""
    gone = sorted(set(EXPECTED) - _connector_packages())
    assert not gone, (
        f"В списке значатся коннекторы, которых больше нет: {gone}. Уберите их отсюда и "
        "из app/system/status.py.")


@pytest.mark.parametrize("package,key", sorted(EXPECTED.items()))
def test_connector_is_watched_on_the_status_screen(package, key):
    assert key in _watched_keys(), (
        f"Коннектор «{package}» настроен и работает, а на экране состояния его нет "
        f"(ждали ключ {key!r}). Пропади у него доступ — экран останется зелёным, а "
        "функция молча перестанет работать. Ровно это и случилось с Weborama 11.09.2026.")


def test_watched_list_has_no_surprises():
    """Строгое равенство: всё, что показано, либо коннектор из списка, либо явно
    объяснённая связь без клиента. Третьего не бывает."""
    assert _watched_keys() == set(EXPECTED.values()) | WATCHED_WITHOUT_CLIENT


def test_every_watched_connector_names_its_credentials():
    """Проверка без переменных не проверяет ничего.

    Строка вида «настроено» без единого имени переменной была бы зелёной всегда — такой
    прибор хуже отсутствующего, потому что создаёт спокойствие.
    """
    silent = [c["key"] for c in check_external_config()
              if not c.get("value")]
    assert not silent, f"Эти связи не говорят о своём состоянии ничего: {silent}"
