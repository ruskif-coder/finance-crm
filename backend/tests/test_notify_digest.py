# -*- coding: utf-8 -*-
"""Дайджест сотрудникам: пачка вместо потока.

Прибор стоит на трёх утверждениях, каждое из которых уже ломалось или могло сломаться
молча:

1. канал «дайджест» ДОХОДИТ — до 16.09.2026 он не доходил вовсе (`LIVE_CHANNELS` без
   него), и поломка выглядела как исправно работающая система;
2. событие уходит в СЛЕДУЮЩУЮ пачку, а не ближайшим прогоном — иначе «дайджест»
   вырождается в «письмо с задержкой», и человек получает столько же писем;
3. час считается по МОСКВЕ — ошибка на три часа правдоподобна и потому незаметна.
"""
from datetime import datetime

from app.notify.digest import DEFAULT_HOUR, DEFAULT_MINUTE, due_at, plural


def test_событие_до_часа_пачки_уходит_в_тот_же_день():
    """Ночное уведомление ждёт утра — того же, а не завтрашнего."""
    assert due_at(datetime(2026, 9, 16, 3, 12), 9, 30) == datetime(2026, 9, 16, 9, 30)


def test_событие_после_часа_пачки_ждёт_следующего_дня():
    """Главное правило дайджеста. Без него письмо уходит ближайшим прогоном, и пачка
    перестаёт быть пачкой."""
    assert due_at(datetime(2026, 9, 16, 14, 0), 9, 30) == datetime(2026, 9, 17, 9, 30)


def test_событие_ровно_в_час_пачки_ждёт_следующего_дня():
    """Граница взята СТРОГО: событие, случившееся в 09:30:00, в уходящее прямо сейчас
    письмо не попадает — иначе оно попало бы в него наполовину собранным."""
    assert due_at(datetime(2026, 9, 16, 9, 30), 9, 30) == datetime(2026, 9, 17, 9, 30)


def test_умолчание_часа_совпадает_с_тем_что_отдаёт_экран():
    """`/me` отдаёт 9:30 при отсутствии строки настроек. Разойдись эти два умолчания —
    человек видел бы на экране один час, а письмо приходило бы в другой."""
    assert (DEFAULT_HOUR, DEFAULT_MINUTE) == (9, 30)


def test_тема_письма_согласована_по_числу():
    """Тема — первое, что видит человек; «1 уведомлений» читается как машинная рассылка."""
    assert plural(1) == "уведомление"
    assert plural(2) == "уведомления"
    assert plural(5) == "уведомлений"
    assert plural(11) == "уведомлений"      # 11, а не «11 уведомление»
    assert plural(21) == "уведомление"
    assert plural(112) == "уведомлений"


def test_у_канала_дайджест_есть_сборщик():
    """Тот самый разрыв: канал есть на экране и в подписках, а забрать его очередь
    некому. Дайджест НАМЕРЕННО не входит в `LIVE_CHANNELS` — он и должен ложиться в
    `queued`, — поэтому прибор проверяет не список каналов, а наличие того, кто эту
    очередь разгребает.
    """
    from app.notify import bus, digest, registry
    assert "digest" in registry.CHANNELS
    assert "digest" not in bus.LIVE_CHANNELS      # копится, а не уходит в момент события
    assert callable(digest.run)
