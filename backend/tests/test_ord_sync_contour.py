# -*- coding: utf-8 -*-
"""Смена контура ОРД не оставляет чужих идентификаторов.

Демо и прод — РАЗНЫЕ кабинеты МедиаСкаута с разными `id` у одного и того же юрлица.
На 17.09.2026 демо-кабинет ушёл дальше прода: в нём 142 юрлица, у нас в зеркале ноль,
и размечать мы начинаем именно с демо.

Опасность не в самой разметке, а в ПЕРЕХОДЕ. Фильтр прогона смотрел только на пустоту
(`ord_client_id IS NULL`), то есть прогон по проду молча пропустил бы всех, кого до
этого разметили демо-идентификаторами. Юрлицо выглядело бы сопоставленным, а
`clientId` внутри договора уехал бы в ЕРИР чужим — и не отозвался.

Два правила, оба проверяются ниже:
  · запись, размеченная ДРУГИМ контуром, снова попадает в очередь сверки;
  · если на новом контуре её не нашли (или нашли неоднозначно) — чужой идентификатор
    СНИМАЕТСЯ. Пустое поле честно говорит «не сопоставлено»; чужое число выглядит как
    сопоставленное.
"""
import io
import re
from pathlib import Path

from app.ord import sync


def _src() -> str:
    return io.open(Path(sync.__file__), encoding='utf-8').read()


def test_the_queue_includes_rows_stamped_by_another_contour():
    """Отбор смотрит не только на пустоту, но и на несовпадение контура."""
    src = _src()
    block = src[src.index('def sync_clients'):src.index('for cp in rows')]
    assert 'ord_env' in block and '!= env' in block, (
        'отбор юрлиц не учитывает смену контура: прогон по проду пропустит всех, '
        'кого разметили на демо')


def test_a_foreign_id_is_cleared_when_the_new_contour_does_not_confirm_it():
    """Не нашли на новом контуре — снимаем id, а не оставляем демо-значение."""
    src = _src()
    body = src[src.index('def sync_clients'):src.index('# ── Вторая половина')]
    # Обе ветки «не подтвердилось» обязаны гасить идентификатор.
    clears = re.findall(r"cp\.ord_client_id, cp\.ord_env, cp\.ord_synced_at = None, None", body)
    assert len(clears) >= 2, (
        'чужой идентификатор снимается не во всех ветках: он должен гаснуть и когда '
        f'юрлица нет на новом контуре, и когда оно неоднозначно (найдено {len(clears)})')


def test_the_report_names_what_the_contour_change_cost():
    """Числа «перепроверено» и «снято» объясняют, почему вчерашний прогон снова нашёл
    работу. Без них повторный прогон выглядит как поломка идемпотентности."""
    src = _src()
    assert "'requeued'" in src and "'cleared'" in src


def test_sync_still_writes_nothing_to_ord():
    """Фаза 1 обязана остаться читающей: в ОРД уходит только GET.

    Прибор на источник — единственный способ поймать день, когда в сверку добавят
    «заодно и зарегистрируем»: запись в ЕРИР необратима, и отделена она правом
    `ord_submit`, а сверка ходит под `ord.edit`.
    """
    src = _src()
    assert 'client.post' not in src and 'client.put' not in src, (
        'в фазе 1 появилась запись в ОРД — она обязана только читать')
