"""Разовая правка шаблонов ДС (владелец 07.11.2026): слово «Приложение…», вписанное текстом, — в подстановку вида документа
в своём падеже («по умолчанию — переменная»). «Соглашение», вписанное аккаунтами, не трогаем; со строчной — это услуга
(«мобильное приложение»), не документ; множественное число («отдельными Приложениями к Договору») — ссылка на другие
документы договора, подстановки для него нет, остаётся текстом."""
from scripts.annex_word_to_tags_2026_11_07 import to_tags


def test_each_singular_case_becomes_its_tag():
    s = ("Настоящее Приложение составлено; настоящего Приложения; по настоящему Приложению; "
         "настоящим Приложением; в настоящем Приложении")
    assert to_tags(s) == ("Настоящее {вид_документа} составлено; настоящего {вид_документа_род}; по настоящему "
                          "{вид_документа_дат}; настоящим {вид_документа_твор}; в настоящем {вид_документа_пред}")


def test_agreement_lowercase_and_plural_stay():
    s = "по настоящему Соглашению; в мобильном приложении; отдельными Приложениями к Договору"
    assert to_tags(s) == s


def test_existing_tags_are_untouched():
    s = "{вид_документа} {номер_дс} к Договору"
    assert to_tags(s) == s
