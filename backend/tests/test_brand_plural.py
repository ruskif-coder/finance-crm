# -*- coding: utf-8 -*-
"""«бренда «A, B, C»» → «брендов «A, B, C»» (владелец 03.11.2026): несколько брендов в одной подстановке — множественное число.

Поломка, которую ловит: УПД без деления по брендам и пункт 1 ДС пакета печатали «бренда «Налгезин, Райтбуфен, …»» —
слово шаблона стоит до подстановки и не знает, сколько брендов в неё придёт. Один бренд — слово шаблона не трогаем.
"""
from app.annex_tpl.assemble import closing_resolve


def _t(tpl, **v):
    return closing_resolve(tpl, v, False)["text"]


def test_several_brands_make_the_word_plural():
    assert _t("Размещение материалов бренда «{бренд_название}», в сети", бренд_название="Налгезин, Райтбуфен") == \
        "Размещение материалов брендов «Налгезин, Райтбуфен», в сети"
    assert _t("услуг для бренда «{бренд_название}»", бренд_название="A, B") == "услуг для брендов «A, B»"
    assert _t("материалов бренда: «{бренд}», (далее", бренд="Berlin-Chemie / Эспумизан, KRKA / Налгезин") == \
        "материалов брендов: «Berlin-Chemie / Эспумизан, KRKA / Налгезин», (далее"


def test_one_brand_keeps_the_template_word():
    assert _t("для бренда «{бренд_название}»", бренд_название="Эспумизан (взрослый) / Espumisan (adults)") == \
        "для бренда «Эспумизан (взрослый) / Espumisan (adults)»"
    assert _t("Бренда «{бренд_название}» нет", бренд_название="A") == "Бренда «A» нет"
