"""Реквизиты сторон из XML УПД 1С против наших (владелец 12.11.2026: «проверял бы реквизиты из УПД и наши — и как-то
информировал: расходится, дополнить»). И банковский счёт продавца — тот, что в УПД, его же ставим в XML счёта.

Поломки: КПП/наименование покупателя в 1С другие, а экран молчит; у нас пустой адрес, а в 1С он есть — и никто не знает,
что карточку надо дополнить; различие кавычек и «ООО» в начале/конце считается расхождением."""
from app.onec_desk import requisites as RQ
from app.onec_desk import xmlparse as XP

UPD = """<?xml version="1.0" encoding="windows-1251"?>
<Файл ИдФайл="x" ВерсФорм="5.03"><Документ><СвСчФакт НомерДок="241" ДатаДок="31.10.2026">
<СвПрод><ИдСв><СвЮЛУч НаимОрг="ООО &quot;ПРОДАВЕЦ&quot;" ИННЮЛ="7700000001" КПП="770001001"/></ИдСв>
<Адрес><АдрИнф КодСтр="643" АдрТекст="г. Москва, ул. Тестовая, 1"/></Адрес>
<БанкРекв НомерСчета="40702810000000000001"><СвБанк НаимБанк="ТЕСТ-БАНК" БИК="044599001" КорСчет="30101810000000000901"/></БанкРекв></СвПрод>
<СвПокуп><ИдСв><СвЮЛУч НаимОрг="ООО &quot;ПОКУПАТЕЛЬ&quot;" ИННЮЛ="7700000002" КПП="770002001"/></ИдСв>
<Адрес><АдрИнф КодСтр="643" АдрТекст="г. Москва, ул. Пробная, 2"/></Адрес></СвПокуп>
</СвСчФакт></Документ></Файл>""".encode("cp1251")


def test_parties_are_read_from_upd():
    p = XP.parties(UPD)
    assert p["seller"] == {"name": 'ООО "ПРОДАВЕЦ"', "inn": "7700000001", "kpp": "770001001", "address": "г. Москва, ул. Тестовая, 1",
                           "bank": {"account": "40702810000000000001", "bik": "044599001", "corr": "30101810000000000901", "name": "ТЕСТ-БАНК"}}
    assert p["buyer"]["kpp"] == "770002001" and p["buyer"]["bank"] is None


def test_diff_says_differs_and_fill_in():
    onec = XP.parties(UPD)
    ours = {"seller": {"name": "ПРОДАВЕЦ ООО", "inn": "7700000001", "kpp": "770001001", "address": "г. Москва, ул. Тестовая, 1",
                       "accounts": ["40702810000000000001"]},
            "buyer": {"name": "ПОКУПАТЕЛЬ ООО", "inn": "7700000002", "kpp": "770002002", "address": None, "accounts": []}}
    got = {(d["who"], d["field"], d["kind"]) for d in RQ.diff(onec, ours)}
    assert got == {("покупатель", "КПП", "расходится"), ("покупатель", "адрес", "дополнить")}


def test_seller_account_missing_in_our_card_is_flagged():
    onec = XP.parties(UPD)
    ours = {"seller": {"name": "ПРОДАВЕЦ ООО", "inn": "7700000001", "kpp": "770001001", "address": "г. Москва, ул. Тестовая, 1",
                       "accounts": ["40702810999999999999"]},
            "buyer": {"name": "ПОКУПАТЕЛЬ ООО", "inn": "7700000002", "kpp": "770002001", "address": "г. Москва, ул. Пробная, 2", "accounts": []}}
    assert [(d["field"], d["kind"]) for d in RQ.diff(onec, ours)] == [("расчётный счёт", "дополнить")]


def test_full_legal_form_from_1c_equals_short_one():
    assert RQ._name("Общество с ограниченной ответственностью \"ПРОДАВЕЦ\"") == RQ._name("ПРОДАВЕЦ ООО")
