# -*- coding: utf-8 -*-
"""Отложенное письмо приходит таким же, как живое.

Найдено аудитом 14.09.2026 — дефект того же дня, и уже второй в этом семействе.

Утром чинили внутренний контур: досылка уведомлений сочиняла тело письма заново, потому
что в журнале лежал только заголовок. Вечером аудит нашёл ту же болезнь снаружи:
`notify_publisher` собирал письмо площадке по спокойной схеме — карточка, пилюля, плашки
фактов, кнопка — и отдавал его `send_and_log(html=…)`, а при попадании в тихие часы
`send_after` строка уходила в очередь ДО того, как `html` куда-либо записан. Колонки под
него не было. Досылка отправляла только `body`, то есть текст.

Со стороны площадки: одно и то же письмо днём приходит свёрстанным, вечером — голым
текстом. Без ошибок, со статусом `sent`.

Прибор держит ОБА конца: что разметка сохраняется и что досылка её берёт.
"""
import inspect

from app.mail import flush, send


def test_deferred_letter_keeps_its_markup():
    """`send_and_log` кладёт разметку в журнал вместе со строкой.

    Проверяется до раннего возврата: при `send_after` функция выходит сразу, и если
    `html` присвоен ПОСЛЕ этой точки, письмо теряет вёрстку молча.
    """
    src = inspect.getsource(send.send_and_log)
    row_def = src[src.index("row = MailLog("):src.index("db.add(row)")]
    assert "html=html" in row_def, (
        "разметка не попадает в строку журнала — при тихих часах она потеряется")


def test_flush_sends_the_stored_markup():
    """Досылка отправляет разметку ИЗ ЖУРНАЛА, а не собирает заново.

    Собрать её нечем: тона, тега, фактов и контекста в журнале нет. А пересчитанная по
    сегодняшнему состоянию она спорила бы с текстом, с которым приехала.
    """
    src = inspect.getsource(flush)
    assert "html=row.html" in src
    assert "Разметку в журнале не храним" not in src, (
        "остался комментарий, утверждавший неправду: разметку никто не собирал заново")


def test_mail_log_has_a_place_for_markup():
    from app.mail.models import MailLog
    assert hasattr(MailLog, "html")


def test_publisher_letter_is_built_before_it_may_be_deferred():
    """Письмо площадке собирается ДО решения об отсрочке.

    Если бы разметка строилась только в ветке немедленной отправки, отложенному письму
    её неоткуда было бы взять — и колонка в журнале не помогла бы.
    """
    from app.notify.outward import send as outward
    src = inspect.getsource(outward.notify_publisher)
    assert src.index("render.notification_html(") < src.index("send_and_log("), (
        "разметка строится после отправки — отложенному письму достанется пустое")
    assert "html=html" in src and "send_after=due" in src
