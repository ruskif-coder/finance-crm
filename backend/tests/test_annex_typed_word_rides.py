"""Слово документа в шаблоне (владелец 07.11.2026, жалоба аккаунта: «в шаблон я текстом ввела Соглашение, а при выгрузке
оно правит на Дополнительное соглашение — зачем?»).

Правило: по умолчанию слово документа — ПОДСТАНОВКА (`{вид_документа}` и падежи); где она стоит, подставляем форму вида
документа в нужном падеже. Где подстановку убрали и вписали слово руками — текст едет как написан. Раньше (31.10–06.11)
вписанное слово переписывалось к виду договора («синхронизировать»).

Пункты, вшитые в код старого генератора (`annex_docx._w`), — не шаблон: их слово по-прежнему следует виду документа."""
from app.annex_tpl import doc_kind as DK
from app.annex_tpl.assemble import _parts
from app.annex_tpl.document import clauses_of, rebrand_model


def _text(template, kind="дс"):
    return "".join(p["t"] for p in _parts(template, DK.values(kind)))


def test_typed_word_is_printed_as_written():
    s = "Настоящее Соглашение вступает в силу; по настоящему Приложению; согласно Доп. соглашению"
    assert _text(s, "дс") == s
    assert _text(s, "приложение") == s


def test_placeholder_takes_the_case_of_the_kind():
    t = ("{вид_документа}; настоящего {вид_документа_род}; согласно {вид_документа_дат}; "
         "настоящим {вид_документа_твор}; в настоящем {вид_документа_пред}")
    assert _text(t, "дс") == ("Дополнительное соглашение; настоящего Дополнительного соглашения; согласно Дополнительному "
                              "соглашению; настоящим Дополнительным соглашением; в настоящем Дополнительном соглашении")
    assert _text(t, "приложение") == ("Приложение; настоящего Приложения; согласно Приложению; настоящим Приложением; "
                                      "в настоящем Приложении")


def test_new_case_tags_are_in_the_dictionary():
    from app.annex_tpl.subs import SUBS
    assert {"вид_документа_твор", "вид_документа_пред"} <= set(SUBS)


FROZEN = {"number": "Доп. соглашение № 30", "kind": "дс",
          "blocks": [{"id": "p1", "num": "1.", "text": "по настоящему Соглашению, Доп. соглашение № 30",
                      "parts": [{"t": "по настоящему Соглашению, "}, {"t": "Доп. соглашение", "key": "вид_документа"},
                                {"t": " № 30"}]}],
          "closing_basis": {"text": "согласно Соглашению",
                            "parts": [{"t": "согласно Соглашению"}]}}


def test_frozen_document_keeps_typed_word_and_refills_the_tag():
    out = rebrand_model(FROZEN, "дс")
    assert out["number"] == "Дополнительное соглашение № 30"
    assert out["blocks"][0]["text"] == "по настоящему Соглашению, Дополнительное соглашение № 30"
    assert out["closing_basis"]["text"] == "согласно Соглашению"
    assert FROZEN["blocks"][0]["parts"][1]["t"] == "Доп. соглашение", "исходная модель не меняется"


def test_file_clauses_keep_typed_word_and_refill_the_tag():
    got = clauses_of(FROZEN, "дс")
    assert got[0]["text"] == "по настоящему Соглашению, Дополнительное соглашение № 30"
    assert clauses_of({"blocks": [{"id": "x", "num": "2.", "text": "по настоящему Соглашению"}]}, "дс")[0]["text"] == \
        "по настоящему Соглашению"
