# -*- coding: utf-8 -*-
"""Тихие часы площадки и время дайджеста.

Умолчания владельца 14.09.2026: дайджест в 09:00 по времени ПЛОЩАДКИ, тихие часы
21:00–09:00. Ошибка здесь тихая в обе стороны: письмо либо будит ночью, либо опаздывает
на сутки, и узнаём мы об этом от площадки.

## Что тут было не так и почему тесты переписаны

До 14.09.2026 эти тесты подавали на вход «наше время» и молча считали его московским —
ровно ту же посылку, что и код: в шапке `schedule.py` было написано «время в базе
московское». Замер показал обратное: и контейнер, и postgres живут в UTC
(`app/timez.py`). Тесты были зелёными, потому что повторяли ошибку кода слово в слово.

Последствие на живых данных: тихие часы 21:00–09:00 работали с 00:00 до 12:00 по
Москве. Письмо площадке в 23:00 уходило ночью, а утреннее в 09:30 ждало до полудня.

Поэтому теперь на вход подаётся ЯВНО UTC, и в каждом тесте рядом написано, который это
час по Москве. Лишнее слово в имени переменной — небольшая цена за то, чтобы следующая
правка не вернула прежнюю посылку.
"""
from datetime import datetime, timedelta

from app.notify.outward import schedule as sc
from app.timez import MSK_OFFSET


def msk(y, m, d, h):
    """Московское время → UTC. Пишем в тестах час по Москве, отдаём коду UTC."""
    return datetime(y, m, d, h) - timedelta(hours=MSK_OFFSET)


def test_quiet_hours_cross_midnight():
    """Интервал ЧЕРЕЗ ПОЛНОЧЬ: 23 больше начала, 3 меньше конца, оба тихие.

    Обычное сравнение `a <= h < b` здесь даёт ровно наоборот — тихим становится день."""
    quiet = [h for h in range(24) if sc.in_quiet_hours(datetime(2026, 9, 14, h))]
    assert quiet == [0, 1, 2, 3, 4, 5, 6, 7, 8, 21, 22, 23]


def test_daytime_goes_out_at_once():
    """Полдень по Москве — рабочее время, письмо уходит сразу."""
    assert sc.due_at(msk(2026, 9, 14, 12), 0, immediate=False) is None
    assert sc.due_at(msk(2026, 9, 14, 12), 0, immediate=True) is None


def test_evening_waits_for_tomorrow_morning():
    """22:00 по Москве — уйдёт завтра в 09:00, а не сегодня.

    Перепутать день у интервала через полночь — задержать письмо на сутки."""
    assert sc.due_at(msk(2026, 9, 14, 22), 0, immediate=False) == msk(2026, 9, 15, 9)


def test_small_hours_wait_for_the_same_morning():
    """03:00 по Москве — уйдёт СЕГОДНЯ в 09:00. Ночь принадлежит наступившему дню."""
    assert sc.due_at(msk(2026, 9, 15, 3), 0, immediate=False) == msk(2026, 9, 15, 9)


def test_offset_moves_both_the_window_and_the_hour():
    """Смещение площадки двигает и тихие часы, и время дайджеста.

    Иркутск (+5 к Москве): наши 05:00 — это у них 10:00, рабочее время, письмо уходит
    сразу. По московским часам оно попало бы в тихие и ждало бы четыре часа зря.
    """
    assert sc.due_at(msk(2026, 9, 15, 5), 5, immediate=False) is None
    # А наши 17:00 — это у них 22:00, и письмо ждёт их утра, то есть наших 04:00.
    assert sc.due_at(msk(2026, 9, 15, 17), 5, immediate=False) == msk(2026, 9, 16, 4)


def test_urgent_still_waits_out_the_night():
    """Срочное снаружи тоже не будит: разница с обычным — «уйдёт первым», а не «ночью».

    Это отличие от внутреннего контура, где три события помечены `locked` и проходят
    сквозь тихие часы. Площадка — не наш сотрудник."""
    assert sc.due_at(msk(2026, 9, 14, 23), 0, immediate=True) == msk(2026, 9, 15, 9)


def test_input_is_utc_not_moscow():
    """РЕГРЕССИЯ 14.09.2026: вход — UTC, и кто-то должен это проверять.

    Отправители зовут `due_at(datetime.utcnow(), …)`. Пока функция считала вход
    московским, у площадки в Москве тихие часы шли с 00:00 до 12:00:

        23:00 МСК (20:00 UTC) → письмо уходило НОЧЬЮ;
        09:30 МСК (06:30 UTC) → письмо ждало до полудня.

    Обе строки ниже падали до правки. Проверяется именно та пара часов, на которой
    ошибка видна в обе стороны — днём и ранним утром разницы не заметно.
    """
    assert sc.due_at(datetime(2026, 9, 14, 20, 0), 0, immediate=False) is not None, \
        "23:00 по Москве — письмо не должно уходить ночью"
    assert sc.due_at(datetime(2026, 9, 14, 6, 30), 0, immediate=False) is None, \
        "09:30 по Москве — тихие часы кончились, письмо должно уйти сразу"
