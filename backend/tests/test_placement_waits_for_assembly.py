# -*- coding: utf-8 -*-
"""Площадка без креативов ждёт СБОРКИ, а не трафика.

Замер владельца 18.09.2026: в расхлопе РК двадцать площадок стояли «у трафика», хотя по
ним нет ни одного креатива — сборка не закончена, отправлять нечего.

Разница не косметическая. «У трафика» означает «мяч у нас, работа идёт»: площадка
попадает в очередь, и человек ищет у себя задачу, которой не существует. Двадцать таких
строк превращают очередь в шум, а шум читают по диагонали — и пропускают настоящую.
"""
from app.ad import flight


def test_an_empty_placement_waits_for_assembly():
    """Ни одного креатива → «ждёт сборки». Раньше пустой список давал «у трафика»."""
    assert flight.best_chain_status([]) == "ждёт сборки"
    assert flight.PLACEMENT_WAIT == "ждёт сборки"


def test_the_first_sent_creative_moves_it_to_traffic():
    """Отправили хоть один креатив — площадка переходит «у трафика». Это и есть порог,
    названный владельцем: не появление площадки в РК, а появление по ней материала."""
    assert flight.best_chain_status(["у трафика"]) == "у трафика"
    assert flight.best_chain_status(["ждёт сборки", "у трафика"]) == "у трафика"


def test_the_ladder_keeps_its_order():
    """Порядок продвинутости: сборка → трафик → площадка → готова к запуску.

    Агрегат берёт САМЫЙ продвинутый статус: одна согласованная пара делает площадку
    готовой, даже если остальные креативы ещё ходят по кругу правок.
    """
    assert flight.best_chain_status(["ждёт сборки", "у площадки"]) == "у площадки"
    assert flight.best_chain_status(["у трафика", "ждёт запуска"]) == "ждёт запуска"
    assert flight.PLACEMENT_CHAIN[0] == "ждёт сборки"


def test_a_placement_that_waits_cannot_be_started():
    """Запустить нечем: согласованного креатива нет по определению."""
    assert not flight.can_start_placement([])
