"""Поверхность площадки в сделке — одна. Прибор на условие, а не на код.

Поверхность (web / app) решается ВЫШЕ, на услуге: площадка получает запрос по приложению,
только если оно у неё подключено (владелец 28.08.2026). Поэтому «частичное решение по
поверхностям» из эталона хендоффа нам не нужно.

Держится это не на коде, а на `uq_launch_prep_target (deal_id, publisher_id)`: получатель
один на пару, и `surface_kind` у него ОДИН. Тест ловит день, когда этого перестанет
хватать. Он не запрещает связку — он не даёт ей появиться незаметно.

**Переписан 16.09.2026 на репетиции релиза.** Прежняя формулировка — «ни у одной площадки
одна услуга не подключена и на web, и на app» — была снята с замера пустого справочника
(ноль таких связок 28.08). На живых данных прода их СЕМЬ, и все семь законны: еФарм
единственная услуга с раздельным прайсом web/app, обе поверхности у неё подключены
намеренно. Прибор кричал на нормальное состояние справочника — а такой прибор перестают
читать, и он пропускает настоящий случай.

Настоящий случай — не в справочнике, а в СДЕЛКЕ: когда одна сделка просит у одной
площадки обе поверхности сразу. Тогда получателей нужно два, а строка одна.

И считать это надо по ТЕКУЩЕЙ версии медиаплана. Первая редакция прибора считала по всем
версиям группы и «нашла» сделку 2483 — обе поверхности стояли в её второй, отменённой
редакции. Черновик не обязан укладываться в модель размещения; живой план обязан.
"""
from sqlalchemy import text

from app.database import SessionLocal

# Исключений нет и не нужно: на живых данных прода 16.09.2026 таких сделок ноль.
#
# Один кандидат был — 2483 «Полисорб · еФарм APP», — и оказался МОЕЙ ошибкой замера:
# запрос считал строки по ВСЕМ версиям группы медиапланов. Обе поверхности стояли во
# ВТОРОЙ версии, а живая, четвёртая, содержит только app. Отсюда правило запроса ниже:
# берём текущую версию каждой группы, а не все строки подряд. Черновая версия — это
# отменённое решение, и требовать от модели описывать его незачем.
KNOWN: set = set()


def test_a_deal_does_not_need_both_surfaces_at_one_publisher():
    """День, когда модель перестанет описывать размещение.

    Ищем сделку, у которой в медиаплане для ОДНОЙ площадки стоят и web, и app. Площадка
    берётся через услугу: строка МП называет услугу и инвентарь, а площадку выбирает
    подбор кандидатов по паре «услуга + поверхность».
    """
    db = SessionLocal()
    try:
        rows = db.execute(text("""
            WITH cur AS (
                SELECT DISTINCT ON (coalesce(group_id, id)) id, deal_id
                  FROM sales_media_plans WHERE deal_id IS NOT NULL
                 ORDER BY coalesce(group_id, id), version DESC, id DESC
            )
            SELECT cur.deal_id, ps.publisher_id, p.name, s.name AS service
            FROM cur
            JOIN sales_media_plan_rows r ON r.plan_id = cur.id
            JOIN sales_services  s  ON s.name = r.position
            JOIN sales_publisher_services ps
                 ON ps.service_id = s.id AND ps.surface_kind = r.inventory AND ps.is_active
            JOIN sales_publishers p ON p.id = ps.publisher_id
            WHERE r.inventory IN ('web', 'app')
            GROUP BY 1, 2, 3, 4
            HAVING count(DISTINCT r.inventory) > 1
        """)).all()
    finally:
        db.close()

    new = [r for r in rows if r.deal_id not in KNOWN]
    assert not new, (
        "Сделка просит у одной площадки ОБЕ поверхности: "
        + "; ".join(f"сделка {r.deal_id} · {r.name} · {r.service}" for r in new)
        + ". Получатель уникален по паре «сделка × площадка», и поверхность у него одна — "
          "второй половине размещения адресата не достанется. Решите, как её описывать, "
          "прежде чем отправлять задание."
    )


def test_the_directory_still_says_which_surfaces_a_publisher_has():
    """Связка «услуга на обеих поверхностях» сама по себе законна и должна оставаться
    видимой: на ней держится подбор кандидатов. Прибор смотрит, что данные не выродились
    — поверхность у связки всегда одна из двух, а не пусто и не что-то третье."""
    db = SessionLocal()
    try:
        bad = db.execute(text("""
            SELECT DISTINCT surface_kind FROM sales_publisher_services
            WHERE is_active AND (surface_kind IS NULL OR surface_kind NOT IN ('web', 'app'))
        """)).all()
    finally:
        db.close()
    assert not bad, f"поверхность связки вне web/app: {[b[0] for b in bad]}"
