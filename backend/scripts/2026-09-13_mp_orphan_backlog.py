"""Запись в бэклог отладки: судьба медиаплана, когда сделка уходит из-под него.

Отложено владельцем 13.09.2026 — вскрылось попутно при засеве услуги сделки, к текущей
задаче отношения не имеет.

Главное поле — signal_bad: как поломка выглядит СО СТОРОНЫ ПОЛЬЗОВАТЕЛЯ.

Запуск: docker exec finance_backend python -m scripts.2026-09-13_mp_orphan_backlog
"""
import sys
from datetime import date, timedelta

sys.stdout.reconfigure(encoding='utf-8')

from app import models as _core_models  # noqa: F401 — таблица users нужна FK бэклога
from app.backlog_models import BacklogItem
from app.database import SessionLocal

WATCH = (date.today() + timedelta(days=45)).isoformat()
AREA = "Аккаунты"

ITEMS = [
    dict(
        title="Удалённая сделка снимает печать со своего медиаплана",
        area=AREA,
        context=(
            "У sales_media_plans.deal_id НЕТ внешнего ключа, поэтому удаление сделки "
            "молча оставляет план указывать в никуда. Замер 13.09.2026: 14 планов из 35 "
            "ссылаются на несуществующие сделки (id 2470–2510, планы от 14 и 25.08) — "
            "это следы ручных удалений на стенде, кода, удаляющего сделки, в системе нет "
            "вовсе. Но дыра открыта: любой будущий путь удаления или ручная уборка на "
            "проде дадут то же самое.\n\n"
            "Опаснее самой ссылки то, что от неё зависит ЗАПЕЧАТЫВАНИЕ версии. "
            "_plan_is_sealed читает стадию сделки и при отсутствии сделки возвращает "
            "False — то есть план, который клиент уже видел, снова становится правимым "
            "на месте, без рождения новой версии."
        ),
        signal_ok=(
            "План с исчезнувшей сделкой честно говорит «сделка не найдена» и остаётся "
            "запечатанным: правки в него ложатся только новой версией."
        ),
        signal_bad=(
            "Аккаунт открывает старый план и правит его прямо в текущей версии, хотя "
            "раньше кнопка предлагала завести новую. Ничего не падает и не краснеет — "
            "просто редакция, которую видел клиент, тихо переписана, и сравнить уже не с "
            "чем. Второй признак: в реестре план числится привязанным к сделке, а переход "
            "по ней ведёт в пустоту."
        ),
        severity="высокая",
    ),
    dict(
        title="Не решено, что происходит с медиапланом на архиве сделки",
        area=AREA,
        context=(
            "Вопрос владельца 13.09.2026 вместе с удалением: что должно быть с планом, "
            "когда сделка доходит до терминальной стадии («Архив успешных сделок», "
            "«Сделка не случилась», «Сделка сорвалась»).\n\n"
            "Сегодня не происходит ничего: план остаётся привязанным и запечатанным — "
            "_plan_is_sealed считает запечатанным всё, что ушло с первой стадии, и "
            "терминальные сюда попадают заодно. Поведение похоже на правильное, но оно "
            "НЕ ВЫБРАНО, а получилось: у срыва и у успешного архива судьба плана может "
            "отличаться, и отдельного решения по ним не принимали."
        ),
        signal_ok=(
            "По плану видно состояние его сделки, и правила правки для архива и срыва "
            "названы явно, а не выведены из общего условия «ушла с первой стадии»."
        ),
        signal_bad=(
            "Кто-то правит план сорвавшейся сделки и удивляется, что это разрешено; либо "
            "наоборот — не может дописать план архивной сделки, когда это понадобилось "
            "для документов, и не понимает, почему именно."
        ),
        severity="низкая",
    ),
]


def main():
    db = SessionLocal()
    added = 0
    for item in ITEMS:
        if db.query(BacklogItem).filter(BacklogItem.title == item["title"]).first():
            continue
        db.add(BacklogItem(status="наблюдаем", watch_until=WATCH, **item))
        added += 1
    db.commit()
    total = db.query(BacklogItem).filter(BacklogItem.area == AREA).count()
    print(f"заведено: {added}, всего по области «{AREA}»: {total}, наблюдаем до {WATCH}")
    db.close()


if __name__ == "__main__":
    main()
