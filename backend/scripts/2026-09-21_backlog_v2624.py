def main():
    db = SessionLocal()
    added = skipped = 0
    for it in ITEMS:
        exists = (db.query(BacklogItem)
                  .filter(BacklogItem.title == it["title"]).first())
        if exists:
            skipped += 1
            continue
        db.add(BacklogItem(status="наблюдаем", watch_until=WATCH, **it))
        added += 1
    db.commit()
    print("заведено: %d, уже было: %d, наблюдаем до %s" % (added, skipped, WATCH))
    for row in (db.query(BacklogItem)
                .filter(BacklogItem.status == "наблюдаем")
                .order_by(BacklogItem.id.desc()).limit(6).all()):
        print("  [%s] %s" % (row.severity, row.title[:70]))


if __name__ == "__main__":
    main()
