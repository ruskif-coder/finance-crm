def main():
    db = SessionLocal()
    added = 0
    for item in ITEMS:
        if db.query(BacklogItem).filter(BacklogItem.title == item["title"]).first():
            continue
        db.add(BacklogItem(status="наблюдаем", watch_until=WATCH, **item))
        added += 1
    db.commit()
    total = db.query(BacklogItem).filter(BacklogItem.area == AREA).count()
    print(f"заведено: {added}, всего по области «{AREA}»: {total}, наблюдаем до {WATCH}")
    db.close()


if __name__ == "__main__":
    main()
