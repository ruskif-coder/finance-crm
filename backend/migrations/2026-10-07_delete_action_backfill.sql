-- Право «удаление» отдельно от «правки» у одиннадцати разделов. Согласовано с владельцем
-- 2026-10-07 (см. backend/tests/test_delete_action_split.py: что именно считается удалением).
--
-- До сих пор ручки удаления записей этих разделов были закрыты правом «правка», а в
-- конструкторе ролей у них не было галочки «удаление». Теперь галочка есть, и ручки удаления
-- её требуют. Поэтому в момент выкладки КОДА надо выдать «удаление» всем, у кого уже есть
-- «правка» — иначе они молча потеряли бы возможность удалять. Дальше владелец снимает
-- галочку у нужных ролей сам.
--
-- Колонка role_permissions.can_delete существует давно; схема не меняется, меняются данные
-- прав. Роль admin в role_permissions не представлена (её права синтезируются) — её тут нет.
--
-- ПОВТОР. Бэкфилл «включить» при повторном накате вернул бы галочку тем, у кого её
-- выключили вручную. Поэтому признак первого наката считается ПО КАЖДОМУ РАЗДЕЛУ отдельно:
-- «ни у одной роли в этом разделе «удаления» ещё нет» (до выкладки конструктор такой галочки
-- не предлагал, и у живых ролей она нулевая). Раздел, где «удаление» кто-то уже получил
-- (сохранили новым конструктором или по API до наката), пропускается целиком — но не мешает
-- остальным десяти. После первого наката признак у раздела ложен — повтор ничего не делает.
--
-- ПОРЯДОК ВЫКЛАДКИ. Накатывать вместе с кодом бэкенда: если код уйдёт раньше, все потеряют
-- удаление в этих разделах до наката; если миграция раньше кода — ничего не меняется, старый
-- код колонку can_delete у этих разделов не читает.

DO $mig$
DECLARE
    secs text[] := ARRAY['settings_articles', 'contracts', 'media_plans', 'year_plan',
                         'settings_pipelines', 'settings_services', 'creatives',
                         'dir_publishers', 'dir_publishers_bulk', 'dir_publishers_cabinets',
                         'sales_registry'];
BEGIN
    UPDATE role_permissions
       SET can_delete = 1
     WHERE section = ANY (secs)
       AND can_edit = 1
       AND section NOT IN (SELECT section FROM role_permissions
                            WHERE section = ANY (secs) AND can_delete = 1);
END
$mig$;
