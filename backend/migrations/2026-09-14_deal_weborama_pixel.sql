-- Доп. параметр РК: нужен ли по этой сделке пиксель Weborama.
--
-- Решение владельца 14.09.2026. До сих пор пиксель требовался БЕЗУСЛОВНО: выгрузка
-- креативов в DSP отказывала строкой «нет пикселя Weborama — сначала «ПИКСЕЛЬ WR»»
-- (`app/dsp/provision.py`, `_blocker`), и снять это требование было нечем. То есть РК,
-- которой верификатор не нужен, в DSP не уезжала вовсе.
--
-- Колонка живёт на СДЕЛКЕ, а не на РК, хотя параметр «про рекламную кампанию». Причины
-- две, и обе практические: у `ad_campaign` `deal_id` с UNIQUE, то есть РК и сделка
-- связаны один к одному и разницы в адресации нет; а ставится галочка НА СБОРКЕ, когда
-- строки РК может ещё не быть — её заводит синк. Поле на РК было бы недоступно ровно
-- тогда, когда его нужно заполнить.
--
-- Умолчание FALSE — решение владельца: пиксель заказывается осознанно, а не считается
-- нужным всем. Это МЕНЯЕТ нынешнее поведение (раньше требовался всегда), и менять его
-- безопасно: на проде на 14.09.2026 ноль РК и ноль размещений — мигрировать нечего.
--
-- NOT NULL с умолчанием, а не nullable: третьего состояния у этого вопроса нет.
-- «Не знаем, нужен ли пиксель» — это «не заказывали», и различать их значило бы завести
-- состояние, которое никто не умеет разрешить.

ALTER TABLE sales_deals
    ADD COLUMN IF NOT EXISTS weborama_pixel boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN sales_deals.weborama_pixel IS
    'Нужен ли по этой РК пиксель Weborama (решение владельца 14.09.2026). '
    'Включает требование пикселя в выгрузке в DSP и проверку стадии weborama_pixel. '
    'Включает аккаунт; снять может только мастер аккаунта или админ.';

-- Момент включения. Нужен не для отчётности, а для разбора: «почему трафик не увидел
-- задачу» и «когда появилось требование» — вопросы про ВРЕМЯ, и журнал действий на них
-- отвечает только пока не подчищен. Кто включил — там же, в audit_log.
ALTER TABLE sales_deals
    ADD COLUMN IF NOT EXISTS weborama_pixel_at timestamp;

COMMENT ON COLUMN sales_deals.weborama_pixel_at IS
    'Когда параметр включили. NULL — не включали ни разу.';
