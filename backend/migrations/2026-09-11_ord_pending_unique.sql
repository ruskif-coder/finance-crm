-- Незакрытая отправка в ОРД — не больше одной на объект. Согласовано с владельцем
-- 11.09.2026 (находка F2-07 внешнего аудита).
--
-- ЗАЧЕМ. `app/ord/submit.py` защищается от дубля так: проверяет, нет ли незакрытой
-- попытки по этому объекту, и только потом пишет свою. Между проверкой и записью
-- НЕТ НИКАКОЙ БЛОКИРОВКИ — два одновременных нажатия проходят проверку оба и заводят
-- две попытки. Дальше обе уходят в ОРД, и в ЕРИР появляется дубль, которого не отозвать.
--
-- Гонка достижима и на одном воркере: эндпоинты объявлены обычными `def`, а такие
-- FastAPI исполняет в пуле потоков (по умолчанию их сорок).
--
-- ПОЧЕМУ ИМЕННО ОГРАНИЧЕНИЕ В БАЗЕ, а не проверка в коде. Проверка в коде и была —
-- именно она не спасает. От одновременности защищает только то, что умеет сказать
-- «нет» второму пишущему, а это уникальный индекс. Тот же вывод, что в контуре
-- Weborama (`2026-09-09_weborama.sql`): там уникальность тоже живёт в базе.
--
-- Частичный — ТОЛЬКО по незакрытым. Завершённых попыток по одному объекту законно
-- бывает много: повтор после неудачи это норма. Ограничивается ровно состояние
-- «исход неизвестен», которое и блокирует повтор.
--
-- Повторно накатываемая.

-- Диагностика ДО создания: если ограничение не встанет, оператор должен видеть причину
-- здесь, а не разбирать текст ошибки индекса. На чистой базе печатает ноль строк.
SELECT kind, local_id, env, count(*) AS незакрытых_попыток
  FROM ord_submissions
 WHERE finished_at IS NULL
 GROUP BY kind, local_id, env
HAVING count(*) > 1;

-- Прежний `idx_ord_submissions_pending` с теми же колонками и тем же условием остаётся:
-- он обычный btree и нужен для поиска. Уникальный заводится рядом отдельным именем,
-- чтобы накат был обратимым — снять ограничение можно, не потеряв индекс поиска.
CREATE UNIQUE INDEX IF NOT EXISTS uq_ord_submissions_pending
    ON ord_submissions (kind, local_id, env)
    WHERE finished_at IS NULL;

COMMENT ON INDEX uq_ord_submissions_pending IS
  'Одна незакрытая отправка на объект: защита от дубля в ЕРИР при двух одновременных нажатиях.';
