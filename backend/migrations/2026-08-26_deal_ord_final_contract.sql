-- Выбранный доходный договор сделки. Согласовано с владельцем 26.08.2026.
--
-- Зачем колонка, если договор и так вычисляется. `resolve_final` находит его от
-- плательщика, и пока у плательщика ровно один помеченный ОРД договор — этого хватает.
-- Но у 16 из 40 юрлиц агентств помеченного договора нет вовсе, а там, где их станет
-- два, вычисление честно откажется выбирать. Ступень сборки без места для ответа
-- остаётся нерешаемой навсегда: человек видит кандидатов и не может указать нужного.
--
-- Пусто — работает вычисление, и экран показывает его как подсказку с обоснованием.
-- Заполнено — побеждает выбор человека. Тот же узор, что у изначального договора
-- (`ord_initial_contract_id` поверх подсказки `proposal`): подстановка предлагает,
-- решает человек, и видно, чьё именно решение показано.
--
-- Аддитивно: nullable, 899 существующих сделок не трогаются, вычисление для них
-- работает ровно как раньше.
ALTER TABLE sales_deals
  ADD COLUMN IF NOT EXISTS ord_final_contract_id INTEGER REFERENCES contracts(id);

-- Индекс под обратный вопрос «какие сделки висят на этом договоре» — он понадобится
-- на сдаче отчётности, когда акт собирается по договору, а не по сделке.
CREATE INDEX IF NOT EXISTS idx_sales_deals_ord_final_contract
  ON sales_deals(ord_final_contract_id) WHERE ord_final_contract_id IS NOT NULL;
