-- Посадочная страница переезжает со сделки на получателя.
-- Решение владельца 27.08.2026, докручено по ходу разбора модуля креативов.
--
-- ПОЧЕМУ ЭТО ИСПРАВЛЕНИЕ, А НЕ ДОБАВКА. Вчера ссылка была заведена на сделке
-- (2026-08-26_launch_prep_creatives.sql) — это ошибка проектирования: ссылка ведёт на
-- страницу КОНКРЕТНОГО сайта (карточку товара или подборку), то есть её грань —
-- «сделка × площадка», ровно как у получателя. Одной ссылки на сделку в этой модели
-- не существует, а держать её «по умолчанию» значило бы завести второе место для того
-- же факта. Колонка на сделке пуста (заведена накануне, никем не заполнялась) — поэтому
-- удаляется, а не замораживается.
--
-- Для ОРД грань не меняется: `advertiserUrls` в теле креатива — массив, и комплект,
-- ушедший на пять площадок, увозит пять ссылок. Маркер по-прежнему на комплект.

ALTER TABLE launch_prep_target ADD COLUMN IF NOT EXISTS advertiser_url VARCHAR(512);

-- Ссылку не всегда знаем: иногда её просят сделать саму площадку (например, собрать
-- подборку). Отметка запроса и его текст хранятся, а СОСТОЯНИЕ ссылки вычисляется:
-- пусто и не запрашивали — «нужна»; пусто и запрошено — «ждём площадку, N дней»;
-- заполнено — готово. Третьей колонки под статус нет намеренно.
ALTER TABLE launch_prep_target ADD COLUMN IF NOT EXISTS url_requested_at TIMESTAMP;
ALTER TABLE launch_prep_target ADD COLUMN IF NOT EXISTS url_request_text TEXT;

-- Готовые фразы для запроса ссылки — накопитель того же вида, что причины доработки,
-- виды площадок и должности контактов. Пополняется вводом: набранная фраза уходит в
-- общий список и дальше предлагается всем.
CREATE TABLE IF NOT EXISTS sales_url_request_phrases (
    id         SERIAL PRIMARY KEY,
    text       TEXT    NOT NULL UNIQUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active  BOOLEAN NOT NULL DEFAULT true
);

-- Стартовый набор: то, что пишут площадке чаще всего. Пополняется руками из формы.
INSERT INTO sales_url_request_phrases (text, sort_order) VALUES
    ('Просим прислать ссылку на страницу товара для размещения.', 10),
    ('Просим собрать подборку по бренду и прислать ссылку на неё.', 20),
    ('Нужна ссылка с UTM-метками — пришлём параметры отдельно.', 30),
    ('Ссылка нужна до старта размещения.', 40)
ON CONFLICT (text) DO NOTHING;

-- Ссылка на сделке: удаляется, потому что была ошибкой грани, а не устаревшим полем.
-- Данных в ней не было ни секунды.
ALTER TABLE sales_deals DROP COLUMN IF EXISTS advertiser_url;
