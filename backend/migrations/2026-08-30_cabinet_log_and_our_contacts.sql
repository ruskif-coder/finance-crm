-- Журнал действий кабинета и общие контакты с нашей стороны.
--
-- Согласовано с владельцем 30.08.2026 (экран «Кабинеты паблишеров», хендофф
-- docs/настройка кабинетов.zip).
--
-- 1. cabinet_log — ЖУРНАЛ С ДВУМЯ ЧИТАТЕЛЯМИ. Его смотрит администратор в колонке
--    «Лог действий» и сама площадка у себя в кабинете как историю действий. Из этого
--    следует главное ограничение: скрытых строк здесь НЕТ. Флаг видимости однажды
--    забудут проставить, и внутреннее уедет наружу; вместо флага правило — в `subject`
--    не пишем ничего, чего площадке видеть нельзя.
--
--    До сих пор кабинет не писал в журнал ничего: `log_action` в шлюзе не вызывался ни
--    разу, и в `audit_log` от внешнего контура нет ни строки. Отдельная таблица, а не
--    `audit_log`, — решение владельца: внешние действия не смешиваются с внутренними,
--    и лента, которую видит площадка, не собирается фильтром по чужому журналу.
--
-- 2. cabinet_our_contact — кого из НАШИХ видит площадка. Общие для всех кабинетов,
--    поэтому `cabinet_id` здесь нет намеренно. Внешний ключ на `sales_reps` вместо
--    строки в `company_settings` — потому что этот контакт видит внешняя сторона, и
--    повисший id показался бы ей пустой строкой вместо человека.
--
-- Словари значений (`actor_side`, `tone`, `action`) живут В КОДЕ, а не CHECK-ами: так
-- же устроены `cabinet.kind`/`state` и виды уведомлений. Набор меняется вместе с
-- экранами, а не с данными; опечатку ловит прибор, а не констрейнт.

-- ── журнал ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS cabinet_log (
    id           serial PRIMARY KEY,
    cabinet_id   integer NOT NULL REFERENCES cabinet(id) ON DELETE CASCADE,
    -- По какой площадке действие. Пусто у событий про кабинет целиком (приостановка).
    -- SET NULL, а не RESTRICT: журнал не должен запрещать удаление площадки и не должен
    -- исчезать вместе с ней — что произошло, остаётся в `action` и `subject`.
    publisher_id integer REFERENCES sales_publishers(id) ON DELETE SET NULL,
    account_id   integer REFERENCES cabinet_account(id) ON DELETE SET NULL,
    -- Имя на момент события. Учётку отключают, человек уходит — журнал обязан остаться
    -- читаемым, поэтому имя лежит строкой, а не только ссылкой.
    actor_name   text NOT NULL,
    -- «площадка» | «мы». В одну ленту попадают оба: «согласован креатив» делает
    -- площадка, «выдан пароль» — мы. Без этого поля наша выдача пароля выглядит у
    -- площадки её собственным действием.
    actor_side   text NOT NULL,
    action       text NOT NULL,          -- ключ события, словарь в коде
    tone         text NOT NULL,          -- info | ok | warn | bad — тон маркера
    subject      text,                   -- «креатив №4 · Мильгамма», «еФарм 2026-07»
    entity_type  text,
    entity_id    integer,
    created_at   timestamp NOT NULL DEFAULT now()
);

-- Оба чтения идут «последние сверху»: колонка админки — по кабинету, история в самом
-- кабинете — по площадке.
CREATE INDEX IF NOT EXISTS ix_cabinet_log_cabinet
    ON cabinet_log (cabinet_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_cabinet_log_publisher
    ON cabinet_log (publisher_id, created_at DESC);

-- ── наши контакты, общие на все кабинеты ─────────────────────────────────────
CREATE TABLE IF NOT EXISTS cabinet_our_contact (
    id         serial PRIMARY KEY,
    -- Название роли строкой, а не ссылкой на справочник: ролей единицы, заводятся они
    -- той же модалкой, и отдельный справочник на два значения — лишняя точка правки.
    role       text NOT NULL,
    rep_id     integer NOT NULL REFERENCES sales_reps(id),
    sort_order integer NOT NULL DEFAULT 0,
    -- Скрыть, не удаляя: сотрудник в отпуске или роль временно не показываем.
    is_shown   boolean NOT NULL DEFAULT true
);

-- Один человек — одна строка. Дважды показанный площадке сотрудник это опечатка, а не
-- совмещение должностей; роль при этом не уникальна — менеджеров сети может быть двое.
CREATE UNIQUE INDEX IF NOT EXISTS uq_cabinet_our_contact_rep
    ON cabinet_our_contact (rep_id);
