-- Песочница для HTML5-баннеров: распакованный архив раздаётся с ОТДЕЛЬНОГО домена.
--
-- ЗАЧЕМ. Баннер в архиве — чужой исполняемый код, и показать его можно только двумя
-- способами, оба плохие без песочницы: с нашего домена — он получает наши куки и
-- хранилище; из `blob:` — не находит собственные файлы по относительным путям. Поэтому
-- архив распаковывается на диск и отдаётся статикой с домена, где нет ни нашей сессии,
-- ни нашего API.
--
-- ТОКЕН, А НЕ ID. Каталог раздачи называется случайным ключом: раздача без авторизации
-- (иначе баннер не откроется в чужом кабинете), значит единственная защита — то, что
-- адрес нельзя подобрать. Идентификатор файла подбирается перебором, токен нет.
ALTER TABLE launch_prep_creative_file
    ADD COLUMN IF NOT EXISTS sandbox_token text,
    -- Точка входа внутри архива: у одних баннеров это index.html в корне, у других он
    -- лежит на уровень ниже. Ищется при загрузке и запоминается — гадать при каждом
    -- открытии значит гадать по-разному.
    ADD COLUMN IF NOT EXISTS entry_path text;

CREATE UNIQUE INDEX IF NOT EXISTS uq_lp_file_sandbox_token
    ON launch_prep_creative_file (sandbox_token) WHERE sandbox_token IS NOT NULL;
