-- Признак саморекламы на сделке. Согласовано с владельцем 26.08.2026.
--
-- Зачем отдельное поле, а не пометка в медиаплане: самореклама меняет не оформление,
-- а правила маркировки. У неё в ОРД свой тип договора (SelfPromotionContract), при
-- выпуске креатива обязателен флаг isSelfPromotion, и по решению владельца ЕРИД в этом
-- случае берётся из ОРД площадки, а не выпускается нами. То есть признак поедет в
-- цепочку, поэтому живёт на сделке, а не в представлении.
--
-- На 26.08.2026 флаг ТОЛЬКО помечает сделку: отдельная цепочка под саморекламу будет
-- расписана позже. Метка ставится уже сейчас, чтобы к моменту появления логики данные
-- на сделках накопились.
--
-- Аддитивно: колонка с умолчанием, существующие 899 сделок не трогаются.
ALTER TABLE sales_deals ADD COLUMN IF NOT EXISTS is_self_promo BOOLEAN NOT NULL DEFAULT FALSE;
