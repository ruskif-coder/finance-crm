-- Ставка НДС медиаплана — фиксируется на дату расчёта и живёт у версии плана.
--
-- ПРАВИЛО ВЛАДЕЛЬЦА 23.09.2026: ставка НДС фиксируется НА ДАТУ РАСЧЁТА. До 2026 года она
-- была 20 %, с 2026 — 22 %, и пересчёт уже посчитанного по новой ставке недопустим.
--
-- До этой миграции план ставку не хранил: сервер и конструктор считали «с НДС» по зашитым
-- 22 % при КАЖДОМ сохранении. Пока все планы 2026 года, вреда нет, но следующая смена
-- ставки пересчитала бы пересохранённый старый план задним числом.
--
-- Правило записи — в коде (`media_plans._apply_fields`): версия получает текущую ставку
-- нашего юрлица при первом расчёте, пересохранение ставку не трогает, новая версия — снова
-- текущая. Здесь только поле и его заполнение.
--
-- ЗАПОЛНЕНИЕ БЕЗ ПЕРЕСЧЁТА: ставка выводится из того, что уже посчитано и лежит в плане
-- (сумма с НДС / сумма без НДС − 1). Планы без суммы остаются с NULL — у них расчёта ещё
-- не было, и ставку им даст первое сохранение.
--
-- Первичные данные: состав согласован с владельцем 23.09.2026.

ALTER TABLE sales_media_plans ADD COLUMN IF NOT EXISTS vat_rate NUMERIC(5,2);

COMMENT ON COLUMN sales_media_plans.vat_rate IS
    'Ставка НДС (%), по которой посчитана версия плана. Фиксируется при расчёте и не пересчитывается (правило 23.09.2026). NULL — план ещё не считался.';

-- Выведенная ставка — приближение (суммы в копейках, у старых планов в рублях): 21,98
-- вместо 22. Она приводится к ставке, которая бывала по закону (20 или 22, допуск 0,5 —
-- то же правило, что `app/vat.py: snap`). Не приводится — суммы плана испорчены, и ставку
-- даёт закон на дату составления плана, а не угаданное число (ревью 23.09.2026).
UPDATE sales_media_plans m
   SET vat_rate = CASE
         WHEN abs(x.r - 22) <= 0.5 THEN 22
         WHEN abs(x.r - 20) <= 0.5 THEN 20
         WHEN m.created_at < DATE '2026-01-01' THEN 20
         ELSE 22 END
  FROM (SELECT id, (amount_gross / amount_net - 1) * 100 AS r
          FROM sales_media_plans
         WHERE vat_rate IS NULL AND amount_net > 0 AND amount_gross IS NOT NULL) x
 WHERE m.id = x.id;
