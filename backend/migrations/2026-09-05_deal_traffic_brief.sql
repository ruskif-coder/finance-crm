-- «Цели и особенности РК» — что аккаунт передаёт трафику вместе с кампанией.
--
-- Отдельное поле, а НЕ дописка в `brief`: бриф синхронизируется с Битриксом в обе
-- стороны (ufCrm_1761318500), и наш внутренний текст уехал бы в карточку Битрикса к
-- клиентским формулировкам. Здесь передача задачи внутри команды, снаружи её быть не
-- должно.
--
-- Пишет аккаунт (право `sales_registry:edit`), трафик читает. Кто и когда правил —
-- в журнале действий (`save_deal_traffic_brief`), поэтому своих колонок «кем/когда»
-- не заводим: вторая память о том же событии разошлась бы с первой.
--
-- Согласовано с владельцем 05.09.2026.
ALTER TABLE sales_deals ADD COLUMN IF NOT EXISTS traffic_brief TEXT;

COMMENT ON COLUMN sales_deals.traffic_brief IS
  'Цели и особенности РК: передача задачи от аккаунта трафику. Внутреннее, в Битрикс не уходит.';
