-- Отложенная доставка должна выглядеть так же, как живая.
--
-- Найдено 14.09.2026 храповиком, поставленным при сборке модуля уведомлений: досылка
-- (`notify/dispatch.py`) отправляла письмо СВОИМ способом, мимо канала, и отправляла
-- телом ЗАГОЛОВОК — `body=r.title`. То есть уведомление, доставленное сразу, приходило
-- карточкой с текстом, фактами и кнопкой, а то же уведомление, пролежавшее в очереди
-- ночь, — тремя словами без ссылки. Одно событие, два разных письма, и разница видна
-- только получателю.
--
-- Корень был не в досылке, а ЗДЕСЬ: в журнале доставок хранился один заголовок.
-- Воспроизвести письмо из него физически нельзя, поэтому досылка и сочиняла своё.
--
-- Колонки nullable: у строк, записанных до этого дня, тела и ссылки нет и взять их
-- неоткуда. Досылка на таких ведёт себя как раньше — заголовком, — и это честнее, чем
-- выдумать содержание задним числом.

ALTER TABLE notification_deliveries
    ADD COLUMN IF NOT EXISTS body text,
    ADD COLUMN IF NOT EXISTS link varchar(512);

COMMENT ON COLUMN notification_deliveries.body IS
    'Тело уведомления на момент события — чтобы отложенная доставка совпала с живой.';
COMMENT ON COLUMN notification_deliveries.link IS
    'Ссылка на объект. Без неё в отложенном письме нет кнопки.';
