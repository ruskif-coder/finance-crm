-- Отказ площадки — третий исход вердикта, а не разновидность доработки.
-- Решение владельца 27.08.2026: «у площадки может не быть в наличии рекламируемого
-- товара или ограничения на работу с брендом».
--
-- ПОЧЕМУ ЭТО НЕ «НА ДОРАБОТКУ». Доработка означает «переделайте и пришлите снова» —
-- площадка остаётся в кампании и ждёт новую версию. Отказ означает «мы это не берём»,
-- и новая версия делу не поможет: получатель обязан выпасть из кампании, а не висеть
-- в ожидании материала, которого не будет. Слить их в одно значение — значит потом
-- гадать по тексту причины, ждёт эта площадка чего-то или нет.
--
-- Само значение вердикта в базе не закреплено CHECK'ом (как и остальные перечисления
-- модуля) — оно живёт в app/launch_prep/models.py и пиньется тестом. Здесь только
-- справочник причин.

-- Причины отказа — отдельный накопитель, а не общий с причинами доработки: «нет товара
-- в наличии» и «тяжёлый файл» отвечают на разные вопросы, и в одном списке человек
-- выбирал бы из смеси несравнимого.
CREATE TABLE IF NOT EXISTS sales_refusal_reasons (
    id         SERIAL PRIMARY KEY,
    text       TEXT    NOT NULL UNIQUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active  BOOLEAN NOT NULL DEFAULT true
);

