-- Отложенная отправка письма: до какого момента оно ждёт.
--
-- Понадобилось для внешнего контура (владелец 14.09.2026): у площадок тихие часы
-- 21:00–09:00 по ИХ времени, и письмо, сочинённое вечером, уходит утром. Внутри контура
-- тихие часы решаются иначе — уведомление ложится в очередь доставки, — но у писем
-- площадке своей очереди не было: гейт либо шлёт сразу, либо пишет отказ.
--
-- Без этой колонки оставался выбор из двух плохих: слать ночью (невежливо и читается как
-- спам) или не слать вовсе (письмо теряется молча). Теперь третье: строка ждёт своего
-- часа в журнале, и её видно — в том же журнале почты, где видно всё остальное.
--
-- NULL — «отправлять сразу», то есть поведение всех писем, написанных до этого дня.

ALTER TABLE mail_log
    ADD COLUMN IF NOT EXISTS send_after timestamp;

COMMENT ON COLUMN mail_log.send_after IS
    'Не отправлять раньше этого момента (тихие часы площадки). NULL — сразу.';

-- Досылка ищет ровно по этим двум полям: что не ушло и чей час настал.
CREATE INDEX IF NOT EXISTS ix_mail_log_due
    ON mail_log (send_after) WHERE status = 'queued';
