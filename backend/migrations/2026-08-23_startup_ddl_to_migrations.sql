-- Разрушающие и данные-меняющие операции переезжают из стартового блока в миграции
-- (2026-08-23).
--
-- ЗАЧЕМ. Блок `with engine.begin()` в app/main.py выполняется при КАЖДОМ запуске
-- контейнера и разросся до сотни строк. Среди идемпотентных ADD COLUMN там оказались
-- три разрушающие операции и три бэкфилла данных — то есть вся разрушающая часть схемы
-- стеклась в стартовый код, не проходящий через процедуру согласования схемы. В самой
-- папке migrations/ при этом нет ни одного DROP или RENAME.
--
-- Цена этого становится ненулевой на кабинете паблишера: наружу отдаются не таблицы, а
-- представления pub.*_v1, и view над удалённой колонкой падает. Пока DROP живёт в
-- стартовом коде, любой рестарт бэкенда — окно поломки контракта, причём падает оно у
-- внешнего пользователя, а не у нас.
--
-- ЧТО ЗДЕСЬ. Дословный перенос того, что стартовый блок делал. Ничего нового не
-- вводится и ничего не удаляется сверх уже удалённого. На 2026-08-23 все операции —
-- no-op на локальной базе (проверено: таблицы нет, колонок нет, строк под бэкфилл ноль);
-- файл нужен для баз, которые эту точку ещё не прошли, и как запись о том, что было
-- сделано. Повторный прогон безопасен.

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Справочник услуг: промежуточная таблица вариантов и две колонки, выброшенные
--    при переходе на конструктор МП. Параметры услуги переехали в саму услугу
--    (placement_type / calc_form / unit_price*), варианты стали не нужны.
--    В ORM-моделях этих объектов нет, поэтому на чистой базе create_all их и не создаёт —
--    операции ниже касаются только баз, живших до того перехода.
-- ─────────────────────────────────────────────────────────────────────────────
DROP TABLE IF EXISTS sales_service_variants;
ALTER TABLE sales_services DROP COLUMN IF EXISTS platform;
ALTER TABLE sales_services DROP COLUMN IF EXISTS currency;

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Бэкфилл номера сделки внутри ячейки годового плана.
--    Колонка заведена с DEFAULT 0, но у строк, существовавших до её появления,
--    значение осталось NULL. Индекс ix_sales_deals_plan_link ключуется тройкой
--    (line, month, idx), и NULL в третьем элементе делает строку неотличимой.
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE sales_deals
   SET plan_deal_idx = 0
 WHERE year_plan_line_id IS NOT NULL
   AND plan_deal_idx IS NULL;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Легаси-строки годового плана без плана-родителя.
--    Под каждую уникальную тройку (рекламодатель, год, сейлз) заводится план с
--    автозаголовком, затем строки к нему привязываются.
--
--    Идемпотентность держится на `plan_id IS NULL`: после привязки условие ложно и
--    повторный прогон не вставляет ничего. Условие по году сравнивается обычным `=`,
--    а не `IS NOT DISTINCT FROM`, как два соседних — при NULL в году привязка не
--    сработала бы и вставка повторялась при каждом запуске. Это безопасно только
--    потому, что SalesYearPlanLine.year объявлен nullable=False (проверено 2026-08-23);
--    если ограничение когда-нибудь снимут, здесь появится рост дублей на ровном месте.
-- ─────────────────────────────────────────────────────────────────────────────
INSERT INTO sales_year_plans (advertiser_id, year, sales_rep_id, title, created_at)
SELECT DISTINCT l.advertiser_id, l.year, l.sales_rep_id,
       COALESCE(a.short_name, a.name, 'Без рекламодателя') || ' · ' || l.year::text, now()
  FROM sales_year_plan_lines l
  LEFT JOIN sales_advertisers a ON a.id = l.advertiser_id
 WHERE l.plan_id IS NULL;

UPDATE sales_year_plan_lines l
   SET plan_id = p.id
  FROM sales_year_plans p
 WHERE l.plan_id IS NULL
   AND p.advertiser_id IS NOT DISTINCT FROM l.advertiser_id
   AND p.year = l.year
   AND p.sales_rep_id IS NOT DISTINCT FROM l.sales_rep_id;
