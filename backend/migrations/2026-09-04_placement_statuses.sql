-- Шесть статусов площадки в РК (владелец 04.09.2026) вместо прежних трёх.
--
-- Было: вкл | выкл | пауза — только управление.
-- Стало: у трафика | у площадки | ждёт запуска | запущен | пауза | завершена.
--        Первые три ставит конвейер согласования креативов (руками не выбираются),
--        последние три — трафик. Словарь в app/ad/flight.py, приборы —
--        tests/test_ad_flight.py::test_status_vocabulary_is_pinned.
--
-- CHECK-ограничения на колонке нет и не заводим: словарь сравнивается в коде, как и
-- остальные русские перечисления проекта (статусы сделок, вердикты пар).
--
-- Перевод данных безопасен: на 04.09.2026 ВСЕ 234 строки стоят в «выкл» — ни одна
-- площадка ещё не включалась, терять нечего. «выкл» переезжает в «у трафика»: это
-- состояние свежего кандидата, которому ничего не отправляли, и мяч у трафика.
-- «вкл» и «пауза» переводятся на случай, если строки появятся между накаткой и кодом.

UPDATE ad_campaign_placement SET status = 'у трафика'  WHERE status = 'выкл';
UPDATE ad_campaign_placement SET status = 'запущен'    WHERE status = 'вкл';
-- «пауза» осталась с тем же словом — трогать нечего.

-- Доля стала ДОЛЕЙ (0…1) вместо процентов: рядом с долей из flight.distribute()
-- проценты читались бы как то же число, увеличенное в сто раз.
UPDATE ad_campaign_placement SET share = share / 100.0 WHERE share > 1;
