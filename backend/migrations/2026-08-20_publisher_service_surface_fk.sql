-- Услуга площадки не может висеть на несуществующей поверхности (2026-08-20).
--
-- Правило «услуга живёт на поверхности» до сих пор проверялось только в API. Любая
-- запись мимо него — ручной SQL, скрипт переноса, будущий кабинет паблишера отдельным
-- сервисом на общей базе — заводила услугу на несуществующем приложении, и это было
-- видно только по расхождению: в реестре счётчик растёт, в карточке блок APP пишет
-- «нет у площадки».
--
-- Уникальный индекс под ключ уже есть (uq_publisher_surface), данные чистые.
-- ON DELETE CASCADE делает то же, что сейчас делает код при удалении поверхности:
-- уносит отмеченные на ней услуги. Код остаётся дублирующей страховкой.
--
-- Побочный эффект, о котором нужно помнить: порядок записи становится обязательным —
-- сначала поверхность, потом услуги. Скрипт, написанный наоборот, теперь упадёт при
-- вставке, и это правильнее тихого мусора.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_publisher_service_surface') THEN
        ALTER TABLE sales_publisher_services
            ADD CONSTRAINT fk_publisher_service_surface
            FOREIGN KEY (publisher_id, surface_kind)
            REFERENCES sales_publisher_surfaces (publisher_id, kind)
            ON DELETE CASCADE;
    END IF;
END $$;
