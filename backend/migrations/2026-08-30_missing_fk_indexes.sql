-- Индексы на внешние ключи, которые их не получили.
--
-- Найдено замером 30.08.2026: из 24 внешних ключей модулей недели пять остались без
-- индекса. Сегодня это ничего не стоит — в таблицах десятки строк, и Postgres
-- справедливо выбирает последовательный проход. Кусает такое позже и с другой стороны:
--
--   · **удаление родителя сканирует ребёнка целиком.** Каждый DELETE в `users` обязан
--     убедиться, что на строку не ссылается `launch_prep_creative_file.uploaded_by`, и
--     без индекса это полный проход по всем загруженным файлам. То же с услугами и
--     кабинетами;
--   · **джойн по неиндексированному ключу** деградирует не плавно, а ступенькой: план
--     переключается с вложенного цикла на хеш-соединение, и до этого момента всё
--     выглядит прекрасно.
--
-- `CONCURRENTLY` НЕ используется: он не работает внутри транзакции, а миграции здесь
-- накатываются одним файлом через psql. Таблицы маленькие, блокировка на доли секунды.
-- Когда они вырастут, индексы уже будут стоять — в этом и смысл сделать это сейчас.

CREATE INDEX IF NOT EXISTS ix_lp_target_service
    ON launch_prep_target (service_id);

-- По нему прослеживается цепочка итераций: какой комплект заменил какой.
CREATE INDEX IF NOT EXISTS ix_lp_set_replaces
    ON launch_prep_creative_set (replaces_set_id);

-- Ссылка на пользователя: индекс нужен не чтению, а удалению учётки.
CREATE INDEX IF NOT EXISTS ix_lp_creative_file_uploader
    ON launch_prep_creative_file (uploaded_by);

-- Экран «Кабинеты» джойнит учётки к кабинету на каждой отрисовке.
CREATE INDEX IF NOT EXISTS ix_cabinet_account_cabinet
    ON cabinet_account (cabinet_id);

CREATE INDEX IF NOT EXISTS ix_cabinet_account_contact
    ON cabinet_account (contact_id);

-- Наш менеджер кабинета. Добавлен вторым заходом: первый список таблиц не включал сам
-- `cabinet`, и ключ уцелел от проверки — ровно тот случай, когда фильтр в запросе-замере
-- прячет находку лучше, чем её отсутствие.
CREATE INDEX IF NOT EXISTS ix_cabinet_manager
    ON cabinet (manager_id);
