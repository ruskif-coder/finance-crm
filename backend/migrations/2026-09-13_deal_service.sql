-- Услуга сделки отдельной колонкой.
--
-- Правило владельца 13.09.2026: ПЕРВАЯ услуга в медиаплане определяет услугу сделки,
-- и сделка несёт ровно одну услугу. Правило старое, но держателя у него не было: услуга
-- жила строкой `sales_deals.product`, у которой ПЯТЬ писателей, и правило соблюдал один
-- (рождение сделки из плана). Импорт из Битрикса клал своё — оттуда среди значений
-- «DSP OLV (не предлагать)», — а перенос плана в сделку услугу не вёз вовсе, поэтому
-- смена первой строки плана сделку не догоняла. Замер 13.09.2026: расхождение у одной
-- пары план↔сделка из двадцати двух, 201 сделка из 920 без услуги вообще.
--
-- Почему ссылка, а не строка. Разметка требований к стадиям сравнивает услугу; при
-- сравнении по имени переименование услуги в справочнике ТИХО отключило бы все её
-- требования — сделки продолжили бы двигаться, ошибки бы никто не увидел. На именах
-- воронок проект это уже проходил (`_cascade_pipeline_rename` в sales_directories).
--
-- `product` НЕ трогаем: правило проекта — поле замораживается, а не дропается. Оно
-- остаётся сырой строкой из Битрикса и подписью в старых выгрузках.
--
-- NULL — не ошибка, а «услуга не определена»: к такой сделке применяются только общие
-- требования, без привязки к услуге.

ALTER TABLE sales_deals
    ADD COLUMN IF NOT EXISTS service_id integer REFERENCES sales_services(id);

COMMENT ON COLUMN sales_deals.service_id IS
    'Услуга сделки = первая строка её медиаплана (правило владельца 13.09.2026). '
    'Везётся переносом план→сделка. NULL — услуга не определена.';

-- Индекс: разметка чек-листа фильтрует сделки по услуге, и реестр группирует по ней же.
CREATE INDEX IF NOT EXISTS ix_sales_deals_service_id ON sales_deals (service_id);
