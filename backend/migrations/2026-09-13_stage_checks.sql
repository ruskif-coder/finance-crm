-- Разметка стадий: требования к переходу, применимость к услуге, видимость блоков.
-- Согласовано с владельцем 13.09.2026.
--
-- ЗАЧЕМ. До сих пор на двенадцать рабочих стадий приходился ОДИН жёсткий гейт —
-- `sales_stages.requires_media_plan`. Сделку можно было довести до «Оплаты» без
-- плательщика, без договора и без ЕРИД: ничто не останавливало. Всё остальное жило
-- советами в очереди аккаунта, а совет можно не заметить.
--
-- ГЛАВНОЕ РЕШЕНИЕ: строка требования ссылается НЕ НА ПОЛЕ, а на ИМЯ ПРОВЕРКИ. Реестр
-- именованных проверок живёт в коде, конфигурация — здесь. Новый случай — строка; новая
-- порода проверки — функция. Ветвление не растёт ни от того, ни от другого. Если бы в
-- строке стояло имя поля, код обрастал бы разветвлением на каждый вид проверки: колонка
-- сделки, документ и состояние в чужом модуле проверяются по-разному.
--
-- АДРЕСАЦИЯ ВХОДНАЯ: требование висит на стадии, в которую ВХОДИМ (владелец 13.09.2026).
-- Так точнее на развилках: у перехода «вперёд» и у перехода «в срыв» требования разные,
-- и входная адресация выражает это сама, без правил-исключений. Плата известна: список
-- на карточке зависит от цели перехода, поэтому обязан её называть, а требования
-- пройденных стадий задним числом не перепроверяются сами.
--
-- ПРИМЕНИМОСТЬ БЫВАЕТ ДВУХ УРОВНЕЙ, и путать их нельзя:
--   · СДЕЛОЧНАЯ (услуга, самореклама) — здесь, в `applies_when`;
--   · ПО ПЛОЩАДКАМ («код не наш») — ВНУТРИ веерной проверки, которая сама обходит
--     площадки и пропускает неприменимые. Сделочным условием её не выразить: у одной
--     сделки часть площадок с нашим кодом, часть без, и ответа «да/нет» на уровне сделки
--     не существует.
--
-- Пустая конфигурация = нынешнее поведение: стадия без строк требований никого не
-- держит, без строк в `sales_stage_services` применима ко всем услугам, без строк в
-- `sales_stage_blocks` показывает все блоки. Выкатывание не должно обнулить ничью
-- карточку, а новая стадия — молча выключить проверки.
--
-- Права: настройка садится на существующий ключ `settings_pipelines` (экран
-- «Настройки → Стадии»). Нового права не заводим, бэкфилл `role_permissions` не нужен.
--
-- Старая `sales_stage_requirements` НЕ трогается: 0 строк, ни одного читателя. Её форма
-- (воронка + stage_key) к нынешней лестнице не подходит — `stage_key` это шесть грубых
-- позиций на двенадцать стадий, и десять из двенадцати делят ключ с соседом. Решение об
-- удалении отдельное и за владельцем.

-- ── Требования к переходу ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS sales_stage_checks (
    id            serial PRIMARY KEY,
    stage_id      integer NOT NULL REFERENCES sales_stages(id) ON DELETE CASCADE,
    -- Имя проверки из реестра в коде. FK нет намеренно: реестр — код, а не таблица
    -- (тот же узор, что у `notification_subscriptions.event_key`). Ключ проверяется
    -- при СОХРАНЕНИИ разметки, а не при работе.
    check_key     varchar(60) NOT NULL,
    -- Запрет или предупреждение. Запирает движение ТОЛЬКО исход «не сделано»:
    -- «неизвестно» (проверить нечем — нет интеграции) показывается, но пропускает,
    -- иначе недостроенный мост заморозил бы конвейер.
    is_blocking   boolean NOT NULL DEFAULT false,
    -- Условия применимости: {"service_id": 7, "self_promo": false}. Пусто = всегда.
    -- Ключи проверяются при сохранении: опечатка иначе означала бы «применимо всегда»,
    -- и требование тихо расползлось бы на все услуги.
    applies_when  jsonb,
    sort_order    integer NOT NULL DEFAULT 0,
    -- Что человеку сделать. Пусто — берётся текст из реестра проверок.
    hint          text,
    CONSTRAINT uq_stage_check UNIQUE (stage_id, check_key)
);

COMMENT ON TABLE sales_stage_checks IS
    'Что должно быть выполнено, чтобы ВОЙТИ в стадию. check_key — имя проверки из '
    'реестра в коде, а не имя поля.';

-- ── Применимость стадии к услуге ─────────────────────────────────────────────
-- Лестница ОДНА на все услуги, а не своя у каждой: от неё кормятся реестр, очередь,
-- годовой план и слои денег — при нескольких лестницах каждый из них должен был бы
-- спрашивать «чья». Применимость трогает только движение: неприменимая стадия
-- проскакивается. Нет строк у стадии = применима ко всем услугам.
CREATE TABLE IF NOT EXISTS sales_stage_services (
    id          serial PRIMARY KEY,
    stage_id    integer NOT NULL REFERENCES sales_stages(id) ON DELETE CASCADE,
    service_id  integer NOT NULL REFERENCES sales_services(id),
    CONSTRAINT uq_stage_service UNIQUE (stage_id, service_id)
);

COMMENT ON TABLE sales_stage_services IS
    'Стадия применима к услуге. Нет строк у стадии — применима ко всем.';

-- ── Видимость блоков карточки ────────────────────────────────────────────────
-- «С этой стадии блок виден» — и дальше не исчезает: иначе движение вперёд прятало бы
-- заполненное, и это читается как «данные потерялись». Второе правило живёт в коде и
-- важнее этой таблицы: НЕПУСТОЕ НЕ ПРЯЧЕМ НИКОГДА. Спрятанные данные не просто
-- невидимы — их невозможно найти, человек считает, что их нет, и заводит второй раз.
CREATE TABLE IF NOT EXISTS sales_stage_blocks (
    id         serial PRIMARY KEY,
    stage_id   integer NOT NULL REFERENCES sales_stages(id) ON DELETE CASCADE,
    -- Ключ блока карточки: mp | ord | traffic-brief | creatives | campaign | docs.
    -- Совпадает с `id` секции в pages/sales/deals/[id].js.
    block_key  varchar(40) NOT NULL,
    CONSTRAINT uq_stage_block UNIQUE (stage_id, block_key)
);

COMMENT ON TABLE sales_stage_blocks IS
    'С какой стадии блок карточки становится виден. Нет строк — виден всегда.';

CREATE INDEX IF NOT EXISTS ix_sales_stage_checks_stage ON sales_stage_checks (stage_id);
CREATE INDEX IF NOT EXISTS ix_sales_stage_services_stage ON sales_stage_services (stage_id);
CREATE INDEX IF NOT EXISTS ix_sales_stage_blocks_stage ON sales_stage_blocks (stage_id);
