-- Бот кабинета и лента событий для площадки.
--
-- ДВА ОТДЕЛЬНЫХ РЕШЕНИЯ ВЛАДЕЛЬЦА 15.09.2026, и оба видны в составе полей.
--
-- 1. БОТ — ЛИЧНОЕ ДЕЛО ЧЕЛОВЕКА, а не наша раздача. Почту мы включаем сами галочкой
--    «получает уведомления» на контакте площадки; бота за него подключить нельзя в
--    принципе — чат заводит он сам, отправив боту код. Поэтому привязка лежит на
--    УЧЁТКЕ (тот, кто вошёл и нажал кнопку), а не на контакте, и к галочке почты
--    отношения не имеет: человек без галочки, зайдя в кабинет, бота себе подключает.
--
-- 2. БОТ ОТДЕЛЬНЫЙ ОТ ВНУТРЕННЕГО. Токен свой (`TELEGRAM_PUB_BOT_TOKEN`), имя своё,
--    вебхук свой. Площадка видит бота подрядчика, а не наш внутренний алёрт-бот, и
--    обработчик `/start` не должен гадать, чей перед ним код.
--
-- ЛЕНТА не заводит своей таблицы вовсе. `cabinet_log` с самого начала объявлен журналом
-- с ДВУМЯ читателями — админом и самой площадкой, — и правило «в subject не попадает
-- ничего, чего площадке видеть нельзя» написано там же. Не хватало ровно одного:
-- площадке его никто не отдавал. Второе хранилище «то же самое, но наружу» разошлось бы
-- с первым молча.

-- ── Привязка бота ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS cabinet_account_tg (
    account_id   INTEGER PRIMARY KEY
        REFERENCES cabinet_account(id) ON DELETE CASCADE,
    -- Чат в телеграме. Заполнен вместе с verified_at или пуст вместе с ним: «чат есть,
    -- но не подтверждён» означало бы, что мы готовы писать туда, куда код не приходил.
    chat_id      TEXT,
    -- Код привязки живёт полчаса и гасится в момент привязки. Одноразовый по построению:
    -- после успеха оба поля обнуляются, и повтор того же кода уже никого не найдёт.
    link_code    TEXT,
    link_expires TIMESTAMP,
    verified_at  TIMESTAMP,
    -- «Не беспокоить до» — то же поле, что у сотрудников. Тихие часы внешнего контура
    -- заданы нами (21:00–09:00 по времени площадки), а это личная пауза человека.
    mute_until   DATE,
    created_at   TIMESTAMP NOT NULL DEFAULT now()
);

COMMENT ON TABLE cabinet_account_tg IS
    'Привязка телеграм-бота к учётке кабинета. Подключает себе сам человек, не мы.';

-- Код ищется по значению на вебхуке — там он единственное, что у нас есть.
CREATE INDEX IF NOT EXISTS cabinet_account_tg_code_idx
    ON cabinet_account_tg (link_code) WHERE link_code IS NOT NULL;

-- ВИДА ДЛЯ КАБИНЕТА ЗДЕСЬ НЕТ, и это осознанно. Состояние привязки кабинет спрашивает
-- у ядра одним вызовом, потому что половина ответа живёт не в базе: имя бота ядро берёт
-- у самого Телеграма (getMe по токену), и из него же собирается диплинк с кодом. Отдав
-- кабинету представление, мы получили бы ДВА источника одного экрана — таблицу и вызов,
-- — и на перепривязке они разошлись бы. `chat_id` наружу не отдаётся ни в каком виде:
-- площадке он не нужен, а утёкший идентификатор чата — чужая точка входа.

-- ── Лента событий ────────────────────────────────────────────────────────────
--
-- Область видимости берётся от ПЛОЩАДОК, как везде в этой схеме, но через кабинет:
-- у половины строк `publisher_id` пуст по смыслу — «Выдан пароль» и «Вход в кабинет»
-- относятся к учётке, а не к сайту. Фильтр по одному publisher_id выбросил бы их, и
-- лента показывала бы только часть своей же истории.
CREATE OR REPLACE VIEW pub.log_v1 WITH (security_barrier) AS
SELECT l.id,
       l.created_at,
       l.action,
       l.tone,
       l.actor_side AS side,
       l.actor_name,
       l.subject,
       l.publisher_id
  FROM cabinet_log l
 WHERE l.cabinet_id IN (SELECT cp.cabinet_id
                          FROM cabinet_publisher cp
                         WHERE cp.publisher_id = ANY (pub.allowed_publisher_ids()));

GRANT SELECT ON pub.log_v1 TO cabinet;
