-- Зеркало справочника ККТУ (Классификатор категорий товаров и услуг) из ОРД.
--
-- ЗАЧЕМ. Код ККТУ обязателен при регистрации креатива, ровно один и ровно третьего
-- уровня. До 27.08.2026 он вводился в карточке бренда руками — а откуда его взять,
-- система не отвечала («ККТУ где я возьму?» — владелец). Справочник нашёлся у самого
-- ОРД: GET /webapi/v3/dictionaries/kktu, 407 строк, из них 294 третьего уровня.
--
-- ПОЧЕМУ ЗЕРКАЛОМ, А НЕ ЗАПРОСОМ НА ЛЕТУ. Код нужен для выпуска маркера, то есть
-- недоступность ОРД заблокировала бы не показ справочника, а саму возможность
-- заполнить бренд. Плюс поиск по 294 строкам идёт по нашей базе одним LIKE.
--
-- ПОЧЕМУ БЕЗ КОЛОНКИ ord_env, в отличие от прочих зеркал ОРД. У договоров и креативов
-- идентификатор ВЫДАЁТ контур, и демовский снаружи неотличим от боевого. Здесь код —
-- сам классификатор, общий и внешний по отношению к обоим контурам; повторный синк
-- с прода просто дольёт строки по тому же первичному ключу.
CREATE TABLE IF NOT EXISTS ord_kktu (
    code        text PRIMARY KEY,          -- «12.2.2» — он же идентификатор в ОРД
    level       integer NOT NULL,          -- 1 | 2 | 3; креативу нужен только третий
    parent_code text,                      -- без FK: справочник чужой, порядок строк не наш
    name        text NOT NULL,
    synced_at   timestamp
);

CREATE INDEX IF NOT EXISTS ix_ord_kktu_level ON ord_kktu (level);
CREATE INDEX IF NOT EXISTS ix_ord_kktu_parent ON ord_kktu (parent_code);
