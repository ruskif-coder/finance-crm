-- Годовой план: развести «кто ведёт» и «кому считаются деньги».
--
-- До 21.09.2026 у строки была ОДНА ось владения — sales_rep_id, и она отвечала сразу
-- на два разных вопроса: «в чей дашборд продаж попадёт сумма» и «кому эту строку
-- показывать». Пока планы заводили сейлзы себе, оба ответа совпадали, и расхождения
-- не было видно. Годовые планы заводят и аккаунты — и тогда план ложился в
-- персональную корзину аккаунта: его не видел ни продавец, ни руководитель, а деньги
-- считались не тому. Обнаружилось это как «аккаунт сохранил план, я его не вижу».
--
-- Теперь sales_rep_id значит ТОЛЬКО продавца, а ведущего держит отдельная колонка.
-- Строка видна тому и другому.
ALTER TABLE sales_year_plan_lines
    ADD COLUMN IF NOT EXISTS account_manager_id INTEGER REFERENCES sales_reps(id);

CREATE INDEX IF NOT EXISTS ix_year_plan_lines_account_manager
    ON sales_year_plan_lines (account_manager_id);

-- Бэкфилл: сегодня в sales_rep_id стоит СОЗДАТЕЛЬ строки (его записывали в обе роли
-- сразу), то есть по смыслу это и есть ведущий. Условие на NULL делает повторный
-- прогон безопасным и не трогает то, что уже проставлено новым кодом.
UPDATE sales_year_plan_lines
   SET account_manager_id = sales_rep_id
 WHERE account_manager_id IS NULL AND sales_rep_id IS NOT NULL;
