-- Вид файла на паре: скриншот размещения или иллюстрация к доработке.
--
-- Таблица `launch_prep_pair_file` заводилась под одно — доказательства размещения,
-- которые снимает трафик. Теперь в неё же кладёт файлы ПЛОЩАДКА, объясняя, что не так
-- с креативом (владелец 28.08.2026).
--
-- Разделять их обязательно. Без вида очередь трафика посчитала бы чужие приложения
-- своими доказательствами («скрины · 3» у пары, где размещения ещё не было), а уборка
-- по срокам стёрла бы их вместе: у доказательства и у приложенной к отказу картинки
-- разная судьба и разный смысл.
--
-- Значение по умолчанию — 'размещение': все существующие строки завёл трафик.
ALTER TABLE launch_prep_pair_file
    ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'размещение';

CREATE INDEX IF NOT EXISTS ix_lp_pair_file_kind
    ON launch_prep_pair_file (pair_id, kind);
