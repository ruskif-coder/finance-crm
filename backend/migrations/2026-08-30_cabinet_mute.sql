-- Выключатели уведомлений в кабинете паблишера.
--
-- Профиль рассылки паблишера ЖЁСТКО ЗАДАН (владелец): бот наш, набор один на всех, и
-- собирать площадке подписку с нуля незачем. Но выключить лишнее она должна уметь —
-- иначе единственный способ перестать получать то, что не читают, это перестать читать
-- всё.
--
-- ХРАНИМ ТОЛЬКО ВЫКЛЮЧЕННОЕ (решение владельца 30.08.2026). Строка есть — вид выключен;
-- строки нет — включён. Так новый вид уведомления включается сам и не требует
-- миграции-бэкфилла всем учёткам. Цена: «ничего не настраивали» и «всё включено
-- осознанно» в базе неразличимы — но для набора из четырёх пунктов это дешевле, чем
-- заводить строку каждому на каждый вид.
--
-- Профили финмодуля (`notification_profiles`) сюда не годятся: они привязаны к `users`,
-- а паблишер — `cabinet_account`, другая таблица и другой контур. Общая таблица
-- потребовала бы дать роли кабинета доступ к `public`, то есть распустить изоляцию.

CREATE TABLE IF NOT EXISTS cabinet_account_mute (
    account_id INTEGER NOT NULL
        REFERENCES cabinet_account(id) ON DELETE CASCADE,
    -- Вид уведомления. Не внешний ключ на справочник: справочник живёт в коде
    -- (`app/cabinet/notify_kinds.py`), потому что набор меняется вместе с экранами
    -- кабинета, а не данными. Опечатку ловит прибор, а не констрейнт.
    kind       TEXT    NOT NULL,
    muted_at   TIMESTAMP NOT NULL DEFAULT now(),
    -- Кто выключил: сама площадка из кабинета или наш админ по её просьбе. Через год
    -- «почему им это не приходит» будет вопросом без ответа, если не записать.
    muted_by   TEXT,
    PRIMARY KEY (account_id, kind)
);

COMMENT ON TABLE cabinet_account_mute IS
    'Выключенные виды уведомлений учётки кабинета. Отсутствие строки = включено.';

-- Читать список кабинету можно (он рисует переключатели), писать — нет: запись идёт
-- через шлюз ядра, как вердикт и посадочная ссылка. Инвариант «у таблицы один
-- писатель» остаётся.
CREATE OR REPLACE VIEW pub.mute_v1 WITH (security_barrier) AS
SELECT m.account_id, m.kind, m.muted_at
FROM cabinet_account_mute m;

GRANT SELECT ON pub.mute_v1 TO cabinet;
