-- Строка финансового отчёта у статьи.
--
-- Зачем отдельное поле, а не существующая group: группа статьи отвечает за удобство
-- ввода и вид справочника, и одна группа законно собирает статьи с разной судьбой в
-- отчёте. Живой пример — группа НАЛОГИ: НДС оттуда транзитный и в P&L не попадает,
-- «Прибыль» — отдельная строка налога, «Пени» — прочие расходы, а НДФЛ и страховые
-- взносы по смыслу ФОТ. Одним полем это не выражается, поэтому отнесение к строке
-- отчёта живёт своей колонкой.
--
-- До этой правки отнесение было захардкожено в двух местах: списком PL_GROUPS_ORDER
-- в reports.py (из-за чего группы «Сотрудники» и «Офис» — 100,6 млн расходов — молча
-- не попадали в P&L, потому что их не было в списке) и регулярками по названию статьи
-- в finreport.py (ФОТ распознавался, АВАНС и ПРЕМИЯ — нет).
--
-- Значения (NULL = не размечена, попадает в «Требует разметки», деньги не теряются):
--   revenue        выручка
--   cogs           себестоимость
--   opex           операционные расходы (включая весь ФОТ и офис)
--   marketing      маркетинг
--   finance        финансовые расходы (проценты по займам и кредитам)
--   profit_tax     налог на прибыль
--   tax_other      прочие налоги — тот же раздел «Налоги», вычитается после EBITDA
--   other          прочие расходы
--   excluded       вне P&L (транзитный НДС, дивиденды, тело займа)
--   by_description назначение определяется текстом платежа, а не статьёй: единый
--                  налоговый платёж (внутри сразу НДС, прибыль, НДФЛ, взносы) и
--                  кредиты, где в одной статье и тело, и проценты. Разметить статьёй
--                  нельзя в принципе, пока платёж один.

ALTER TABLE articles ADD COLUMN IF NOT EXISTS pl_line VARCHAR;

COMMENT ON COLUMN articles.pl_line IS
  'Строка финансового отчёта. NULL — статья не размечена, суммы уходят в «Требует разметки».';

-- Бэкфилл по согласованной с владельцем разметке (2026-08-18). Пишем по имени статьи:
-- имя уникально (UNIQUE в схеме), а id между стендами не совпадают.
UPDATE articles SET pl_line = 'revenue' WHERE name IN (
  'РЕАЛИЗАЦИЯ', 'еФарм', 'А-Таргет', 'Приоритезация', 'Клик-АУТ', 'Польза',
  'eFMCG', 'Спецпроект', 'Доп услуги');

-- «НАЛОГИ | Реклама» и ОРД — налог на рекламу и маркировка: расход, напрямую
-- завязанный на реализацию, поэтому себестоимость, а не налоги.
UPDATE articles SET pl_line = 'cogs' WHERE name IN (
  'АПТЕКА', 'ПАБЛИШЕР', 'СК АГЕНТСКАЯ', 'СК ПАРТНЕРСКАЯ',
  'НАЛОГИ | Реклама', 'ОРД', 'БАННЕРЫ', 'ПОДРЯДЧИКИ');

-- Блок «Сотрудники» целиком операционный: ровно он и выпадал из старого P&L.
-- ДОЛГ оставлен здесь намеренно — владелец отложил решение (тело долга или проценты),
-- поведение не меняем, чтобы отчёт не поехал молча. См. бэклог отладки.
UPDATE articles SET pl_line = 'opex' WHERE name IN (
  'IT', 'РАЗРАБОТКА', 'БАНК', 'ПОДПИСКИ', 'ДОЛГ', 'Аренда', 'ОФИС содержание',
  'ФОТ', 'АВАНС', 'ПРЕМИЯ', 'БОНУСЫ', 'НАЛОГИ | НДФЛ', 'НАЛОГИ | Страх.Взносы');

UPDATE articles SET pl_line = 'marketing' WHERE name IN (
  'МЕРОПРИЯТИЯ', 'ПРЕДСТАВИТЕЛЬСКИЕ', 'PR', 'ГОЛЬФ');

UPDATE articles SET pl_line = 'profit_tax' WHERE name = 'НАЛОГИ | Прибыль';
UPDATE articles SET pl_line = 'tax_other'  WHERE name IN ('НАЛОГИ | ПРОЧИЕ', 'НАЛОГИ | Пени');

-- ТРАНЗИТ: сам оборот сквозной и в P&L не место, но списание стабильно больше
-- поступления, и эта разница — реальный расход (наценка на проходящих деньгах).
-- Строка считается как нетто по своему знаку, поэтому 'other' даёт ровно
-- «списано − поступило». ПРОЧЕЕ — по решению владельца обычные прочие расходы,
-- а не «вне P&L», как было записано в его группе.
UPDATE articles SET pl_line = 'other' WHERE name IN ('ТРАНЗИТ', 'ПРОЧЕЕ');

UPDATE articles SET pl_line = 'excluded' WHERE name IN ('НАЛОГИ | НДС', 'ДИВИДЕНТЫ');

UPDATE articles SET pl_line = 'by_description' WHERE name IN ('НАЛОГИ', 'КРЕДИТЫ');
