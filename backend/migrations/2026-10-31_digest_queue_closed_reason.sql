-- Конечное состояние строки очереди дайджеста площадкам.
--
-- Зачем. До 31.10.2026 строка, которую отправитель больше не возьмёт, лежала с пустым
-- sent_at навсегда: «ждёт своего часа» было не отличить от «не уйдёт никогда». Замер на
-- проде 31.10.2026 — 22 строки лежали третьи сутки, 17 из них после того, как 29.10.2026
-- к отбору добавилось условие «писать можно только тому, кто может войти в кабинет и
-- снять „Письма“ сам»: строки встали в очередь до этого правила и оказались отрезаны.
--
-- Пустое значение — строка живая, её ещё можно отдать. Непустое — строка закрыта, и
-- здесь написано ПОЧЕМУ, причём причина настоящая (например «получатель без учётки
-- кабинета»), а не только «протухла»: по «протухла» чинили бы очередь, тогда как чинить
-- надо данные получателя.
--
-- Ставить sent_at вместо этого было нельзя: это означало бы «отправлено», тогда как в
-- журнале почты письма нет, и разобрать такую строку потом нечем.
ALTER TABLE cabinet_digest_queue ADD COLUMN IF NOT EXISTS closed_reason text;

-- Живая строка теперь — (sent_at IS NULL AND closed_reason IS NULL), по этому условию
-- идут и отбор дайджеста, и проверка на экране состояния.
--
-- Прежний частичный индекс cabinet_digest_queue_due_idx (due_at) WHERE sent_at IS NULL
-- НЕ удаляется: в проекте устаревшее замораживается, а не дропается. Он просто перестаёт
-- быть точным — по нему проходят и закрытые строки.
CREATE INDEX IF NOT EXISTS cabinet_digest_queue_live_idx
    ON cabinet_digest_queue (due_at)
 WHERE sent_at IS NULL AND closed_reason IS NULL;
