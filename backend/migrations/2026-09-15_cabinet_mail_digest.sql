-- Почтовая рассылка площадке: матрица «событие × способ доставки» и дайджест.
--
-- Состав согласован с владельцем 15.09.2026 по макету v2. Три вещи, которых не было:
--
-- 1. МАТРИЦА. До сих пор выключатель был один на вид и глушил сразу все каналы
--    (`cabinet_account_mute`). Макет разложил его по каналам: панель — всегда, бот и
--    почта — по галочке. Старая таблица ЗАМОРАЖИВАЕТСЯ по правилу проекта (устаревшее
--    не дропается), её содержимое переезжает сюда как «почта выключена».
--
-- 2. СПОСОБ ДОСТАВКИ ПОЧТЫ — У КАЖДОГО СОБЫТИЯ СВОЙ. Первая редакция этой миграции
--    держала режим на канале целиком («по событию» или «дайджест» одним переключателем);
--    владелец 15.09.2026 поправил: колонки матрицы — «бот», «почта срочное», «дайджест».
--    То есть человек решает не «как мне присылать почту», а «что срочным письмом, а что
--    в утренней пачке». Час пачки при этом остаётся один на человека — выбирать час
--    отдельно каждому событию значило бы дробить пачку, ради которой всё и затевалось.
--
-- 3. НАКОПИТЕЛЬ. Дайджест — это письмо из НЕСКОЛЬКИХ событий, и собирать его не из чего:
--    `mail/render.py::digest_html` написан с 13.09 и не вызывается никем, а `send_after`
--    у письма умеет только придержать каждое по отдельности. Отсюда очередь.

-- ── Матрица: чем именно человек отличается от умолчания ──────────────────────
--
-- ХРАНИМ ОТКЛОНЕНИЯ, а не полное состояние: строки нет — канал включён. Так новый вид
-- уведомления включается сам и не требует бэкфилла всем учёткам, и так же устроена
-- замораживаемая `cabinet_account_mute` — правило не меняется, к нему добавляется
-- измерение. Цена та же: «не настраивал» и «оставил включённым» неразличимы, и для
-- набора из четырёх видов это дешевле строки на каждую клетку.
--
-- Отсюда же «Вернуть по умолчанию» на экране — это DELETE всех строк учётки, а не
-- проставление галочек: умолчание не состояние, а ОТСУТСТВИЕ решения.
CREATE TABLE IF NOT EXISTS cabinet_account_notify (
    account_id INTEGER NOT NULL
        REFERENCES cabinet_account(id) ON DELETE CASCADE,
    -- Вид уведомления. Не FK: справочник живёт в коде (`app/notify/outward/kinds.py`),
    -- потому что набор меняется вместе с экранами, а не с данными.
    kind       TEXT    NOT NULL,
    -- Способ доставки. Три, и два из них — почта: «почта» это письмо СРАЗУ, «дайджест»
    -- — то же письмо в общей утренней пачке. Они взаимоисключающи (проверку несёт
    -- ручка), оба выключены = почты по этому событию нет вовсе.
    --
    -- ПАНЕЛИ здесь нет: у паблишера панели уведомлений не существует (владелец
    -- 15.09.2026). Лента кабинета — журнал наших с ним действий, а не канал доставки, и
    -- выключателя у неё нет по той же причине, по какой его нет у истории переписки.
    channel    TEXT    NOT NULL CHECK (channel IN ('бот', 'почта', 'дайджест')),
    enabled    BOOLEAN NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT now(),
    -- Кто менял: сама площадка или наш админ по её просьбе. Через год «почему им это не
    -- приходит» без этого поля — вопрос без ответа.
    changed_by TEXT,
    PRIMARY KEY (account_id, kind, channel)
);

COMMENT ON TABLE cabinet_account_notify IS
    'Матрица «событие × канал» учётки кабинета. Отсутствие строки = канал включён.';

-- ── ЧАСА ПАЧКИ В БАЗЕ НЕТ ────────────────────────────────────────────────────
--
-- Дайджест уходит в 09:00 ПО ВРЕМЕНИ ПЛОЩАДКИ (владелец 15.09.2026). Час — константа
-- (`app/notify/outward/schedule.py::DIGEST_HOUR`), а не настройка: выбирать его площадка
-- не будет, и хранить нечего.
--
-- «По времени площадки» — не фигура речи: смещение лежит в её карточке
-- (`sales_publishers.timezone_offset`), и 09:00 в Иркутске наступает на пять часов раньше
-- нашего. Замер 14.09.2026: смещение равно нулю у всех 41 площадки, то есть сегодня это
-- одно и то же — и начнёт различаться, как только поле заполнят.
--
-- Первая редакция этой миграции заводила здесь `cabinet_account_mail` с колонками
-- `mode` и `digest_hour`. Обе умерли в день написания, до выкладки куда бы то ни было:
-- способ доставки переехал на событие, а час стал общим. Дропать нечего.

-- ── Накопитель дайджеста ─────────────────────────────────────────────────────
--
-- Событие, ждущее своего часа. Ключ — КОНТАКТ, а не учётка: письмо уходит контакту, и
-- контакт без учётки (таких большинство: 33 с почтой против нескольких учёток) тоже
-- обязан получать свою пачку — просто с умолчаниями, раз настраивать ему негде.
--
-- Лежит здесь СОДЕРЖИМОЕ события, а не готовое письмо: дайджест собирается из карточек,
-- и сохранённый HTML одного письма в пачку не складывается.
CREATE TABLE IF NOT EXISTS cabinet_digest_queue (
    id           SERIAL PRIMARY KEY,
    publisher_id INTEGER REFERENCES sales_publishers(id) ON DELETE CASCADE,
    contact_id   INTEGER REFERENCES sales_publisher_contacts(id) ON DELETE CASCADE,
    -- Адрес снимком: контакт могут переименовать или сменить ему почту, пока письмо
    -- лежит в очереди, и уйти оно должно туда, куда собиралось.
    email        TEXT NOT NULL,
    to_name      TEXT,
    kind         TEXT NOT NULL,
    title        TEXT NOT NULL,
    body         TEXT,
    context      TEXT,
    link_abs     TEXT,
    facts        JSONB NOT NULL DEFAULT '[]'::jsonb,
    tone         TEXT NOT NULL DEFAULT 'info',
    tag          TEXT,
    created_at   TIMESTAMP NOT NULL DEFAULT now(),
    -- Когда пачка должна уйти — в НАШЕЙ шкале, как `send_after` у письма. Переводить
    -- туда-обратно в момент отправки значило бы делать это дважды и однажды ошибиться
    -- знаком (та же причина, что в `outward/schedule.py`).
    due_at       TIMESTAMP NOT NULL,
    sent_at      TIMESTAMP,
    -- Ссылка на письмо, в которое событие уехало: «почему мне это не пришло» должно
    -- иметь ответ в системе.
    mail_log_id  INTEGER
);

COMMENT ON TABLE cabinet_digest_queue IS
    'События, ждущие своего часа дайджеста. Одна строка = одна карточка в письме.';

-- Разгребается задачей `app.notify.outward.digest` раз в час: берутся неотправленные,
-- чей час настал. Индекс ровно под этот запрос.
CREATE INDEX IF NOT EXISTS cabinet_digest_queue_due_idx
    ON cabinet_digest_queue (due_at) WHERE sent_at IS NULL;

-- ── Переезд выключателей ─────────────────────────────────────────────────────
--
-- Старая строка означала «выключено везде», но каналов тогда было два и бот не работал
-- ни у кого — фактически это было «выключено на почте». Так и переносим, а не дублируем
-- в бот: приписать человеку выключение бота, которого он не подключал, значит выключить
-- канал раньше, чем он его увидел.
--
-- Почта переносится в ОБА способа: человек выключил письма по этому событию, и неважно,
-- срочным они пришли бы или пачкой. Перенеси мы только «почта срочное», события начали
-- бы приходить ему в дайджесте — то есть выключение обернулось бы включением.
INSERT INTO cabinet_account_notify (account_id, kind, channel, enabled, changed_at, changed_by)
SELECT m.account_id, m.kind, ch, false, m.muted_at,
       coalesce(m.muted_by, 'перенос из cabinet_account_mute')
  FROM cabinet_account_mute m, unnest(ARRAY['почта', 'дайджест']) AS ch
 ON CONFLICT (account_id, kind, channel) DO NOTHING;

COMMENT ON TABLE cabinet_account_mute IS
    'ЗАМОРОЖЕНО 15.09.2026: заменено cabinet_account_notify (матрица «событие × канал»). '
    'Не читается кодом, не дропается по правилу проекта.';

-- Кабинет читает матрицу сам (рисует экран), пишет — ядро через шлюз: инвариант «у
-- таблицы один писатель» остаётся. Очередь дайджеста наружу не отдаётся вовсе — это наша
-- кухня доставки, площадке видеть в ней нечего.
CREATE OR REPLACE VIEW pub.notify_v1 WITH (security_barrier) AS
SELECT n.account_id, n.kind, n.channel, n.enabled FROM cabinet_account_notify n;

GRANT SELECT ON pub.notify_v1 TO cabinet;
