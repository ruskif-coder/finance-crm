-- Светофор 2/2/2: факт разделён на две позиции (владелец, 2026-08-17).
--
--   5. closing       «Закрытие подготовка»  — Подготовка ДС · Согласование ДС · Подготовка закрывающих
--   6. closing_fact  «Закрытие фактическое» — ЭДО · Отчёты в ОРД · Оплата
--
-- Архив выходит из шести позиций бара (в каталоге помечен terminal), но КЛЮЧ 'archive'
-- за стадией сохраняется. Убирать ключ нельзя по трём причинам, каждая уже проверена:
--   • он есть в sales_bitrix_stage_map (3 строки) — иначе битриксовые архивные стадии
--     при импорте перестали бы резолвиться и садились бы в «требует разбора»;
--   • фильтр «скрыть архив» в реестре сделок работает через stage_key = 'archive';
--   • слой денег 963 архивных сделок выводится из ключа — без него они выпали бы
--     из «фактических» в «Без группы», то есть сдвинулись бы ДДС и P&L.
--
-- Слой денег НИ У ОДНОЙ сделки не меняется: closing и closing_fact оба «фактические».
-- Двигается только светофор — он начинает различать «готовим документы» и «документы
-- в обороте». Колонку money_layer обновляем вместе с ключом, чтобы строка была
-- согласована сама с собой (отчёты читают колонку, а не выводят из ключа).

BEGIN;

UPDATE sales_stages SET stage_key = 'closing_fact', money_layer = 'фактические'
 WHERE name IN ('ЭДО', 'Отчёты в ОРД', 'Оплата');

COMMIT;
