-- Комментарии на карточке сделки: лента человеческих записей рядом с журналом событий.
--
-- Раздельно с историей осознанно (владелец 05.09.2026): история — системные события из
-- audit_log, комментарий — то, что человек сказал сам. Смешать в один поток можно, но
-- тогда фильтр «только комментарии» становится обязательным, а он нужен всегда.
--
-- Каждая запись отдельной строкой, правок и удалений нет: редактируемая лента перестаёт
-- быть свидетельством о том, кто что и когда написал.
--
-- Автор — УЧЁТКА (users), а не профиль ответственного (sales_reps): профиль есть не у
-- всех, он заводится только при назначении (app/sales/reps.py), и комментарий от
-- человека без профиля потерял бы автора.
--
-- Права — общие правила сделки: пишет тот, у кого sales_registry:edit на эту сделку,
-- читает тот, кто видит карточку. Своей секции прав не заводим.
--
-- Согласовано с владельцем 05.09.2026.
CREATE TABLE IF NOT EXISTS sales_deal_comments (
    id          SERIAL PRIMARY KEY,
    deal_id     INTEGER   NOT NULL REFERENCES sales_deals(id),
    user_id     INTEGER   NOT NULL REFERENCES users(id),
    text        TEXT      NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- Лента всегда читается по одной сделке и в обратном хронологическом порядке.
CREATE INDEX IF NOT EXISTS ix_deal_comments_deal
    ON sales_deal_comments (deal_id, created_at DESC);

COMMENT ON TABLE sales_deal_comments IS
  'Комментарии на карточке сделки. Лента: правок и удалений нет.';
