-- Материнская операция: связь частичной оплаты с исходной плановой операцией.
--
-- ПРАКТИКА (владелец 23.09.2026). При частичном закрытии плановую операцию копируют с
-- поправкой сумм: копия с полученной суммой закрывается «оплачено», исходная остаётся
-- планом на остаток — до полного погашения. В данных это давало несколько операций с
-- одинаковыми № ДС и Счётом и никакой связи между ними: импорт принимал их за одну
-- (аудит 23.09.2026, 2.H1 — транши склеивались и перезаписывались), а дебиторка видела
-- один счёт как несколько несвязанных строк.
--
-- ОДНО ПОЛЕ, ССЫЛКА ВСЕГДА НА КОРЕНЬ цепочки, а не на предыдущую часть: цепочка плоская —
-- материнская и её части. Сумма договора отдельно не хранится: она равна материнской плюс
-- все части, и так никогда не разойдётся с самими операциями.
--
-- УДАЛЕНИЕ материнской с частями на уровне приложения запрещено, кроме принудительного
-- с вводом пароля (решение владельца 23.09.2026). База при этом не держит висячую ссылку:
-- ON DELETE SET NULL — части становятся самостоятельными, а не исчезают.
--
-- Первичные данные: состав согласован с владельцем 23.09.2026.

ALTER TABLE operations
    ADD COLUMN IF NOT EXISTS parent_operation_id INTEGER
        REFERENCES operations(id) ON DELETE SET NULL;

COMMENT ON COLUMN operations.parent_operation_id IS
    'Материнская операция, от которой отделена эта часть (частичная оплата). NULL — операция самостоятельная или сама материнская. Ссылка всегда на корень цепочки.';

CREATE INDEX IF NOT EXISTS ix_operations_parent_operation_id
    ON operations (parent_operation_id);

-- Операция не может быть частью самой себя.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_operations_parent_not_self') THEN
        ALTER TABLE operations
            ADD CONSTRAINT ck_operations_parent_not_self
            CHECK (parent_operation_id IS NULL OR parent_operation_id <> id);
    END IF;
END $$;
