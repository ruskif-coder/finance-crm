-- Номер ДС — полной формой: «Дополнительное соглашение № 30», а не «Доп. соглашение № 30».
--
-- Решение владельца 02.11.2026: «надо писать полностью Дополнительное соглашение». Формы слова — в
-- app/annex_tpl/doc_kind.py; новые ДС получают полную форму при подтверждении. Здесь — уже сохранённые номера
-- (на проде 02.11.2026 таких два). Печать приводит слово к полной форме и сама (`doc_kind.renumber`), а эта правка — для
-- реестров и карточек, которые показывают номер как записан. Повторный прогон ничего не меняет.

UPDATE sales_annexes
   SET number = regexp_replace(number, '^\s*Доп\.\s*соглашение', 'Дополнительное соглашение')
 WHERE number ~ '^\s*Доп\.\s*соглашение';
