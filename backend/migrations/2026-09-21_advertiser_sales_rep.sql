-- Ответственный сейлз у рекламодателя.
--
-- Зачем: сейлз закреплён за рекламодателем, а не за каждым документом по отдельности.
-- Медиаплан (обычный и годовой) подставляет его сам, когда поле «Продавец» пустое —
-- иначе одного и того же человека выбирают руками в каждом новом плане.
--
-- Пусто = не назначен. Это нормальное состояние, а не пропуск данных: у части
-- рекламодателей персонального сейлза нет.
--
-- Храним профиль из sales_reps (как у сделки и годового плана), а ручка принимает
-- id УЧЁТКИ и заводит профиль в момент назначения (app/sales/reps.py: ensure_rep).
-- Справочник ответственных — не список сотрудников, см. заметку reps-directory-is-not-staff.
ALTER TABLE sales_advertisers
    ADD COLUMN IF NOT EXISTS sales_rep_id INTEGER REFERENCES sales_reps(id);
