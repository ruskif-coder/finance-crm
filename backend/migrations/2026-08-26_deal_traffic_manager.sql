-- на users(id) заставила бы выбирать трафик-менеджера из другого, более узкого
-- списка (кто имеет логин в самом финмодуле) и резолвить его в /sales/deals/{id}
-- иначе, чем продавца/аккаунта — то есть не «так же», как просит эта задача.
--
-- Аддитивно: колонка nullable, существующие 899 сделок не трогаются, у них роль
-- показывается как «не назначен».
