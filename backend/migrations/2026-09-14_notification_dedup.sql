-- Уведомление как СОСТОЯНИЕ, а не как след события.
--
-- Спека канала `app` (хендофф 14.09.2026) требует трёх вещей, которых модель не знала:
--
--   1. СХЛОПЫВАНИЕ. Повторная сработка сканера не должна плодить строки: «сделка стоит
--      17 дней» и та же сделка назавтра — одна запись, а не две. Ключ — событие плюс
--      объект.
--   2. УХУДШЕНИЕ. Снова непрочитанной строка становится ТОЛЬКО при ухудшении тона
--      (warn → bad). Без собственного тона у записи сравнивать нечем: в реестре тон
--      постоянный, а у сработки он меняется вместе со срочностью.
--   3. ГАШЕНИЕ. Причина исчезла — строка уходит из панели, даже если её не открывали.
--      У сканера это уже есть (`notification_alert_state.resolved_at`), но до самого
--      уведомления не доходило, и панель показывала разобранное.
--
-- Все три колонки nullable: записи, сделанные до этого дня, живут как жили — без ключа
-- схлопывания они просто не схлопываются, и это честнее, чем задним числом склеить то,
-- что человек видел раздельно.

ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS dedup_key varchar(120),
    ADD COLUMN IF NOT EXISTS tone varchar(8),
    ADD COLUMN IF NOT EXISTS resolved_at timestamp;

COMMENT ON COLUMN notifications.dedup_key IS
    'event_key:entity_type:entity_id — ключ схлопывания. Повтор обновляет строку.';
COMMENT ON COLUMN notifications.tone IS
    'Тон СРАБОТКИ (bad|warn|ok|info). Меняется вместе со срочностью; ухудшение делает '
    'строку снова непрочитанной.';
COMMENT ON COLUMN notifications.resolved_at IS
    'Причина исчезла — строка уходит из панели. NULL — живая.';

-- Поиск строки для схлопывания идёт по получателю и ключу, среди живых.
CREATE INDEX IF NOT EXISTS ix_notifications_dedup
    ON notifications (user_id, dedup_key) WHERE resolved_at IS NULL;
