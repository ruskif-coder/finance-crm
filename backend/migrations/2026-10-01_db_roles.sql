-- Роли базы, на которые выдают права миграции и дамп (владелец 01.10.2026).
--
-- Роли живут на уровне КЛАСТЕРА, а не базы, поэтому в `pg_dump` не попадают. Тренировка
-- развёртывания ночного бэкапа на чистом Postgres (01.10.2026) упала на первой же выдаче
-- прав: `role "cabinet" does not exist` — в дампе 25 строк `GRANT ... TO cabinet`.
-- Пока база собиралась миграциями, роль создавала `2026-08-28_publisher_cabinet.sql`;
-- при восстановлении из дампа миграции не идут, и роли взяться неоткуда.
--
-- Этот файл — ЕДИНСТВЕННЫЙ список ролей. Его зовёт `deploy.sh restore` ДО разворота
-- дампа, а на живой базе он — пустышка (каждая роль «создать, если нет»). Прибор
-- `tests/test_db_roles.py` не даст выдать права роли, которой здесь нет.
--
-- Пароль и право входа здесь НЕ задаются: файл лежит в гите, пароль — в `.env`.
-- `deploy.sh restore` выдаёт `cabinet` вход с паролем из CABINET_DB_PASSWORD; руками —
-- см. README миграций, раздел «Что миграции НЕ делают».
--
-- Повторный накат ничего не меняет.

DO $$
BEGIN
    -- Кабинет паблишера: читает только схему `pub` (2026-08-28_publisher_cabinet.sql).
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cabinet') THEN
        CREATE ROLE cabinet NOLOGIN;
    END IF;
END $$;
