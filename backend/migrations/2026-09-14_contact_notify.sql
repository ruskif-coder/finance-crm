-- Контакт площадки: получает ли он уведомления кабинета.
--
-- Решение владельца 14.09.2026. До сих пор адресат вычислялся правилом «первый по
-- признаку основного», то есть был следствием чужого флага: `is_primary` заведён, чтобы
-- знать, к кому идти с вопросом, а не чтобы решать, кому слать почту. Совпадали они по
-- случайности, и расходиться начали бы при первом же контакте, который «главный, но
-- писать ему не надо».
--
-- ОДИН ФЛАГ НА ВСЕ ВИДЫ, а не по видам. Что именно приходит — площадка выключает у себя
-- в кабинете (`cabinet_account_mute`), и вторая ось выключения с нашей стороны спорила бы
-- с первой: два места, где написано «не слать», рано или поздно скажут разное.
--
-- БЭКФИЛЛ СОХРАНЯЕТ ПОВЕДЕНИЕ. Замер 14.09.2026: 45 контактов у 26 площадок, основным
-- помечены только 9 — то есть у семнадцати площадок основного нет вовсе, и письмо им
-- уходило первому контакту по порядку. Проставляем ровно того, кто получал бы письмо
-- сегодня: основного, а где его нет — первого. Иначе после миграции не получает никто, и
-- рассылка замолкает молча.
--
-- Умолчание для НОВЫХ контактов — false: человека заводят в справочник, чтобы знать, а
-- рассылку включают отдельным решением.

ALTER TABLE sales_publisher_contacts
    ADD COLUMN IF NOT EXISTS notify boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN sales_publisher_contacts.notify IS
    'Получает ли контакт уведомления кабинета (решение владельца 14.09.2026). '
    'Какие именно виды — площадка выключает у себя в кабинете.';

-- Бэкфилл: по одному получателю на площадку, тому же, что получал бы сегодня.
WITH chosen AS (
    SELECT DISTINCT ON (publisher_id) id
      FROM sales_publisher_contacts
     WHERE coalesce(email, '') <> ''
     ORDER BY publisher_id, is_primary DESC, id
)
UPDATE sales_publisher_contacts c
   SET notify = true
  FROM chosen
 WHERE c.id = chosen.id
   AND NOT c.notify;

CREATE INDEX IF NOT EXISTS ix_publisher_contacts_notify
    ON sales_publisher_contacts (publisher_id) WHERE notify;
