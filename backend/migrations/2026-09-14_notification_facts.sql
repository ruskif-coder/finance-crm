-- Плашки фактов и код объекта у уведомления.
--
-- По хендоффу «Уведомления · спокойная схема» (PINS_плашки_фактов.md, §8):
--
--     «Плашки собирает СОБЫТИЕ, а не шаблон письма: одно и то же уведомление
--      показывает одинаковые факты в панели, в почте и в телеграме.»
--
-- До сих пор числа жили внутри `title`/`body` строкой. Это работало ровно до первого
-- канала, который рисует их иначе: в панели плашками, в телеграме строкой «ключ:
-- значение», в письме таблицей. Разбирать их обратно из текста — гадание.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ПЕРЕСБОРКА НА ЛЕТУ. Отложенное письмо уходит досылкой через час
-- и сутки, когда исходного состояния уже нет: сделка сдвинулась, просрочка стала другой.
-- Пересчитанные при отправке факты противоречили бы заголовку, с которым они приехали.
-- Ровно этот дефект мы чинили 14.09.2026, когда досылка сочиняла тело письма заново —
-- поэтому `body`/`link` и переехали в журнал. `facts` живут по той же причине.
--
-- СОСТАВ. Массив объектов, форма задана хендоффом:
--
--     [{"k": "ждёт", "v": "6 дн.", "fg": "danger", "hot": true},
--      {"k": "к оплате", "v": "188 400 ₽"}]
--
--     k    ключ, 2–3 слова нижним регистром (капс наводится отрисовкой)
--     v    ГОТОВАЯ строка значения: форматирование применено до записи
--     fg   danger | warning | income | accent | muted — цвет значения, необязателен
--     hot  ровно у одного факта в карточке: то число, ради которого пришло письмо
--
-- Форматирование хранится применённым намеренно: «188 400 ₽» собирается там, где
-- известны валюта и правило округления, а не в четырёх отрисовщиках по-разному.
--
-- `code` — метка объекта (`7E2JWE`), в макете стоит справа от кнопки. Держим отдельным
-- полем, а не вычисляем по `entity_id`: досылке иначе пришлось бы ходить в чужую таблицу
-- на каждое письмо, а внешнему контуру код не положен вовсе — там колонка остаётся пустой.

ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS facts jsonb NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS code varchar(20);

ALTER TABLE notification_deliveries
    ADD COLUMN IF NOT EXISTS facts jsonb NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS code varchar(20);

COMMENT ON COLUMN notifications.facts IS
    'Плашки фактов: [{k,v,fg?,hot?}]. Собирает событие, каналы только отрисовывают.';
COMMENT ON COLUMN notifications.code IS
    'Метка объекта (код сделки). Во внешнем контуре пусто — код наружу не уходит.';
COMMENT ON COLUMN notification_deliveries.facts IS
    'Копия фактов на момент события: досылка не пересобирает их заново.';
COMMENT ON COLUMN notification_deliveries.code IS
    'Метка объекта на момент события.';
