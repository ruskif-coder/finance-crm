-- Креатив НАЦЕЛИВАНИЯ в DSP: хеш креатива, заведённого у демоклиента.
-- Состав согласован с владельцем 12.09.2026 («да, схема ок»); имена колонок приведены к
-- слову «нацеливание» в тот же день, когда выяснилось, что предпросмотр и нацеливание —
-- РАЗНЫЕ функции, обращающиеся к одному архиву креатива.
--
-- ЗАЧЕМ. Трафик проверяет баннер на живом сайте до старта: открывает ссылку нацеливания,
-- она привязывает его браузер к креативу, и дальше он видит рекламу на площадке. Чтобы
-- увидеть ИМЕННО НАШ баннер, креатив должен существовать в DSP — а боевой попадает туда
-- только после согласования площадки (замер 12.09.2026: на стадии «у трафика» хеш есть у
-- 0 креативов из 205). Поэтому на отправку трафику заводится ОТДЕЛЬНЫЙ креатив — в
-- демокампании демоклиента, где такие и должны жить.
--
-- Предпросмотр (песочница у нас) этих колонок не касается вовсе: он читает тот же архив,
-- но наружу ничего не отправляет.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ТАБЛИЦА. Креатив нацеливания ОДИН на комплект: баннер в комплекте
-- один и тот же для всех площадок, различается только место показа. Таблица понадобилась
-- бы, если бы их стало несколько на комплект; сегодня это было бы хранилище с
-- единственной строкой на родителя.
--
-- ПОЧЕМУ ХЕШ ХРАНИТСЯ ВООБЩЕ. В DSP нет удаления: повторная отправка того же комплекта
-- не должна заводить второй такой же креатив, а единственный признак «уже заведён» — это
-- сохранённый хеш. Тот же принцип, что у `ad_campaign_creative.ms_creative_xxhash` и у
-- `weborama_refs`: уникальность обеспечиваем МЫ, потому что чужая система её не даёт.

ALTER TABLE launch_prep_creative_set
    ADD COLUMN IF NOT EXISTS ms_targeting_creative_xxhash VARCHAR(32),
    ADD COLUMN IF NOT EXISTS ms_targeting_at             TIMESTAMP;

COMMENT ON COLUMN launch_prep_creative_set.ms_targeting_creative_xxhash IS
  'Креатив НАЦЕЛИВАНИЯ в DSP (демокампания демоклиента): на него выпускается ссылка, привязывающая браузер трафика. НЕ боевой креатив (у того свой хеш в ad_campaign_creative) и НЕ предпросмотр (тот живёт у нас в песочнице).';

COMMENT ON COLUMN launch_prep_creative_set.ms_targeting_at IS
  'Когда завели креатив нацеливания. Нужен, чтобы отличить «не заводили» от «заводили, а хеш потеряли»: второе означает сироту в чужом кабинете.';
