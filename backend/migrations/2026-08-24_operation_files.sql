-- Приложенные файлы операции: сканы документов (2026-08-24).
--
-- ЗАЧЕМ. Часть первички существует только на бумаге и приходит сканом — в реестр
-- Диадока такой документ не попадает, потому что у него нет собственной личности
-- в ЭДО (box_id / letter_id / document_id). Ссылка `operations.document_link` для
-- этого тоже не подходит: она указывает наружу, а скан надо хранить у себя.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКИ НА ОПЕРАЦИИ. У одного платежа бывает
-- несколько бумаг сразу — счёт, акт, УПД. Колонкой это выражается ровно один раз,
-- после чего появляется вторая колонка, третья, и порядок теряется.
-- Состав согласован с владельцем до написания кода (решение 2026-08-24).
--
-- ПОЧЕМУ НЕ РЕЕСТР ДИАДОКА. `diadoc_documents` описывает электронный документ с его
-- идентификаторами в ЭДО; у скана их нет. Сложив оба происхождения в одну таблицу,
-- пришлось бы в каждом запросе проверять, откуда взялась запись.
--
-- Существующие 664 ссылки в `operations.document_link` не трогаются: ссылка остаётся
-- ссылкой, скан живёт рядом, у операции может быть и то, и другое.

CREATE TABLE IF NOT EXISTS operation_files (
    id            SERIAL PRIMARY KEY,
    operation_id  INTEGER NOT NULL REFERENCES operations(id) ON DELETE CASCADE,
    -- Относительный ключ от корня хранилища: 'operations/op1234_a1b2c3d4_akt.pdf'.
    -- Именно ключ, а не абсолютный путь и не голое имя — соглашение зафиксировано
    -- 2026-08-23 в docs/TASK_единый_стандарт_хранения_документов.md. Он переживает
    -- и смену тома, и переезд в S3, где является прямо именем объекта.
    path          VARCHAR NOT NULL,
    -- Как файл назывался у отправителя: именно это имя получает тот, кто скачивает.
    original_name VARCHAR NOT NULL,
    size_bytes    INTEGER,
    uploaded_at   TIMESTAMP NOT NULL DEFAULT NOW(),
    -- Снимок автора, по образцу audit_log: кто приложил, видно даже если учётку
    -- потом отключат.
    uploaded_by   INTEGER REFERENCES users(id),
    uploaded_by_name VARCHAR
);

-- Список файлов запрашивается для каждой открытой операции и для реестра пачкой.
CREATE INDEX IF NOT EXISTS ix_operation_files_operation ON operation_files (operation_id);
