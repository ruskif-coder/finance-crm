-- Учёт применённых миграций для базы dsp_analytics.
-- Согласовано с владельцем 11.09.2026 (пять решений: таблица в КАЖДОЙ базе; бэкфилл
-- существующих; пишет `deploy.sh migrate`; повтор предупреждает, а не блокирует;
-- контрольная сумма остаётся).
--
-- ЗАЧЕМ. Alembic убран, порядок наката живёт только списком в README, и на вопрос «что
-- уже накачено на проде» до сих пор отвечали осмотром схемы через `\d`. Осмотр даёт
-- СОСТОЯНИЕ, но не историю: он не скажет, какой файл пропустили и в каком порядке шли.
--
-- ЧЕГО ЭТА ТАБЛИЦА НЕ ДЕЛАЕТ — и это надо знать, чтобы не переоценить её. Она отвечает
-- «что НАКАТЫВАЛИ», а не «что реально в схеме». Часть колонок и таблиц заводит
-- `create_all()` из ORM-моделей мимо всяких миграций, поэтому сверять прод по-прежнему
-- приходится через `\d`. Ledger даёт порядок и историю, не больше.
--
-- ПОЧЕМУ В КАЖДОЙ БАЗЕ СВОЯ. Баз две, и запись о накате обязана лежать там же, где его
-- след: восстановление одной базы из дампа иначе принесло бы чужую историю. Цена —
-- одинаковый DDL в двух файлах; колонки «в какую базу» нет намеренно, её однажды
-- заполнили бы неверно.
--
-- Повторно накатываемая.

CREATE TABLE IF NOT EXISTS schema_migrations (
    -- Имя файла без пути: путь у одного и того же файла разный на стенде и на проде.
    filename    VARCHAR(200) PRIMARY KEY,
    -- NULL = «накачено до заведения учёта, время неизвестно». Честнее, чем проставить
    -- всем сегодняшнюю дату и сделать вид, что мы это знаем.
    applied_at  TIMESTAMP,
    applied_by  VARCHAR(64),
    -- sha256 файла НА МОМЕНТ НАКАТА. Ловит случай «накатили, потом отредактировали»:
    -- имя совпадает, содержимое — нет, и без суммы это не видно ничем.
    checksum    VARCHAR(64),
    note        TEXT
);

COMMENT ON TABLE schema_migrations IS
  'Что накатывали в эту базу и когда. НЕ описывает схему целиком: часть её заводит create_all().';

