-- Сырьё статистики Weborama: суточный срез по вставкам + курсор выкачки.
-- База dsp_analytics (НЕ основная). Состав согласован с владельцем 12.09.2026.
--
-- ПОЧЕМУ ЗДЕСЬ, А НЕ В ОСНОВНОЙ БАЗЕ. Сырьё внешних измерителей живёт отдельно от учёта:
-- его много, оно перезабирается, и его потеря не стоит ничего — перекачаем. В основную
-- базу из него отдаётся ТОЛЬКО суточный срез, апсертом в `ad_campaign_stat` с
-- `source='weborama'`. Тот же порядок, что у коннектора DSP (`2026-09-02_dsp_analytics`).
--
-- ПОЧЕМУ БЕЗ HYPERTABLE, хотя рядом Timescale. У DSP гранула часовая и строк миллионы —
-- там гипертаблица оправдана. Здесь грань суточная: 452 вставки × 365 дней ≈ 165 тысяч
-- строк в год. Обычная таблица справляется, а каждая лишняя механика — это то, что
-- когда-нибудь придётся чинить. Перейти на часы значит ДОБАВИТЬ таблицу сырья, а не
-- переделывать эту.

-- ── 1. Суточный срез по вставкам ────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS wcm_stat_daily (
    day           DATE         NOT NULL,
    -- Аккаунт WCM — ЧАСТЬ КЛЮЧА, а не справочная колонка. Weborama выдаёт аккаунты
    -- списком и закрепляет за клиентами; нумерация вставок внутри аккаунта своя, и
    -- вставка 559 в двух аккаунтах — две разные вставки. Так же ключуется weborama_refs.
    account_id    VARCHAR(32)  NOT NULL,
    -- Их вставка ↔ weborama_refs.wcm_id при kind='insertion'. Внешнего ключа нет и не
    -- будет: сырьё приходит по ВСЕМ вставкам аккаунта, включая те, что заводились мимо
    -- нашей системы (замер 12.09.2026: таких 452 из 452). Требовать соответствия значит
    -- выбрасывать данные, которых мы пока не умеем прицепить.
    insertion_id  VARCHAR(32)  NOT NULL,
    -- Их имя вставки из metadata. Внутри data меток нет вовсе, одни ключи-id, а по имени
    -- человек сверяет строку отчёта Weborama с нашей площадкой. Переименовать вставку в
    -- их кабинете нельзя, поэтому имя — часть факта, а не украшение.
    label         VARCHAR(255),
    -- Показ по решению владельца 10.09.2026 — именно `impression`, не
    -- `impression_without_IVT`: сверять наш счётчик надо с тем же, что считает площадка.
    impression    BIGINT       NOT NULL DEFAULT 0,
    click         BIGINT       NOT NULL DEFAULT 0,
    -- Ответ целиком, как пришёл. Метрик у них 130, берём 4; колонка на метрику означала
    -- бы миграцию на каждый новый вопрос. Вдобавок часть метрик сегодня НЕ приходит
    -- (видимость), и когда их включат, ответить на старый период можно будет из сырья,
    -- а не перекачкой — окно их выдачи не вечно.
    metrics       JSONB,
    imported_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Идемпотентность перезабора: окно съёма перекрывает трое суток назад, потому что
    -- Weborama дозаливает задним числом. Без этого ограничения каждый прогон плодил бы
    -- копии одних и тех же суток, и сумма росла бы сама.
    CONSTRAINT uq_wcm_stat_daily UNIQUE (day, account_id, insertion_id)
);

-- Читаем всегда «эта вставка за период», отсюда порядок колонок в индексе.
CREATE INDEX IF NOT EXISTS ix_wcm_stat_daily_ins
    ON wcm_stat_daily (insertion_id, day DESC);

COMMENT ON TABLE wcm_stat_daily IS
  'Сырьё Weborama: вставка × сутки. В основную базу уходит срезом в ad_campaign_stat (source=weborama).';

-- ── 2. Курсор выкачки ───────────────────────────────────────────────────────
-- Зерно — аккаунт, а не вставка: их API отдаёт весь аккаунт одним ответом (замер:
-- 452 вставки за 43 дня = 533 КБ), и спрашивать повставочно значило бы 452 обращения
-- к чужой системе ради тех же данных.
CREATE TABLE IF NOT EXISTS wcm_sync_cursor (
    account_id       VARCHAR(32) PRIMARY KEY,
    last_pulled_day  DATE,                    -- последние сутки, уже лежащие в срезе
    last_run_at      TIMESTAMPTZ,             -- когда съём отработал в последний раз
    last_rows        INTEGER,                 -- сколько строк принёс — пустой прогон виден
    last_absent      TEXT,                    -- метрики, не пришедшие НИ РАЗУ
    last_error       TEXT,                    -- NULL = прошлый прогон удался
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON COLUMN wcm_sync_cursor.last_absent IS
  'Метрики, которые запросили, а Weborama не прислала ни по одной вставке. Не ошибка обмена: ответ 200, метрики нет. Молчание тут неотличимо от нуля, поэтому хранится.';
