-- Контур вызова в журнале отправок: боевой или демо (решение владельца 06.09.2026).
--
-- В DSP есть демо-клиент, на котором можно тренироваться вне боевых кампаний. Но журнал
-- один, и на нём стоит защита от дублей `ensure_campaign`: она ищет последний удачный
-- хеш по нашему local_ref. Демо-прогон по той же сделке записал бы туда СВОЙ хеш, и
-- боевое заведение решило бы, что кампания уже создана, — то есть боевая РК просто не
-- завелась бы, молча и «успешно».
--
-- Поэтому контур — колонка, а не отдельная таблица: история обмена остаётся в одном
-- месте (разбор «что ответил DSP» ведётся одним запросом), но перепутать контуры нельзя.
-- Умолчание 'prod': всё, что записано до 06.09.2026, — боевое.
--
-- Накатывается в АНАЛИТИЧЕСКУЮ базу dsp_analytics, не в finance:
--   docker exec -i finance_dsp_db psql -U dsp_user -d dsp_analytics < <файл>

ALTER TABLE dsp_send_log
    ADD COLUMN IF NOT EXISTS contour VARCHAR(8) NOT NULL DEFAULT 'prod';

-- Поиск дублей идёт по (контур, тип, наш id) — индекс повторяет этот порядок.
DROP INDEX IF EXISTS ix_dsp_send_log_ref;
CREATE INDEX IF NOT EXISTS ix_dsp_send_log_ref
    ON dsp_send_log (contour, entity_type, local_ref);
