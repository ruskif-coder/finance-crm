-- Разметка отложенного письма — в журнале.
--
-- Найдено аудитом 14.09.2026, дефект того же дня.
--
-- ЧТО ЛОМАЛОСЬ. `notify_publisher` собирает письмо площадке по спокойной схеме — карточка,
-- пилюля важности, плашки фактов, кнопка — и отдаёт его `send_and_log(html=…)`. Если
-- письмо попало в тихие часы площадки, `send_and_log` кладёт строку в очередь и выходит
-- ДО того, как `html` куда-либо записан: колонки под него не было. Досылка `mail/flush.py`
-- потом отправляла только `body`, то есть ТЕКСТ.
--
-- Наружу это выглядело так: одно и то же письмо днём приходит свёрстанным, а вечером —
-- голым текстом. Молча, без ошибок в журнале: статус `sent`, письмо ушло.
--
-- ПОЧЕМУ ХРАНИМ РАЗМЕТКУ, А НЕ СОБИРАЕМ ЗАНОВО. Пересборка требует тона, тега, фактов,
-- контекста и ссылки — пяти полей, которых в журнале нет, — и считала бы их по состоянию
-- НА МОМЕНТ ДОСЫЛКИ, а не на момент события. Ровно этот дефект мы чинили утром во
-- внутреннем контуре, когда досылка сочиняла тело письма заново. Письмо — то, что было
-- составлено; хранить его целиком честнее, чем обещать точное воспроизведение.
--
-- Комментарий в `flush.py` утверждал обратное («разметка собирается заново отправителем»)
-- — утверждение неверное, её не собирал никто. Он исправлен вместе с этой миграцией.
--
-- ОБЪЁМ. Письмо спокойной схемы — около 20 КБ. Рост ограничен сроком хранения журнала:
-- три месяца, `app/retention.py`. Без срока это была бы вечно растущая колонка.

ALTER TABLE mail_log
    ADD COLUMN IF NOT EXISTS html text;

COMMENT ON COLUMN mail_log.html IS
    'Разметка письма на момент составления. Нужна досылке: собрать её заново нечем, '
    'и пересчитанная по сегодняшнему состоянию она спорила бы с текстом, с которым '
    'приехала. NULL — письмо без разметки (только текст).';
