-- Импорт операций перевели на право правки операций — и возвращаем его тем, у кого
-- импорт был. Решение владельца 11.09.2026, в два хода.
--
-- ЧТО БЫЛО. Секция `import` объявлена в `permissions.py` с ЕДИНСТВЕННЫМ действием
-- `view`, и на нём висели все три ручки импорта, включая `/import/apply` — а он не
-- только вставляет, но и ПЕРЕЗАПИСЫВАЕТ существующие операции: дату, статус, суммы,
-- банк, период, ставку НДС. То есть роль с правом ТОЛЬКО СМОТРЕТЬ журнал денег меняла
-- файлом уже проведённые операции. Внешний аудит 11.09.2026 счёл это косметикой
-- (F1-19); по сути это тихая эскалация прав.
--
-- ЧТО СДЕЛАНО В КОДЕ. Пишущие ручки (`/import` и `/import/apply`) переведены на
-- `operations:edit` — то самое право, что у одиночной и массовой правки. Второго права
-- «можно писать деньги» заводить не стали: оно уже есть, и вторая его копия неизбежно
-- разошлась бы с первой. Разбор (`/import/preview`) остался на `import:view`: он ничего
-- не пишет, а посмотреть, что файл сделает с журналом, полезно и тому, кто применять
-- не вправе.
--
-- ЗАЧЕМ ЭТА МИГРАЦИЯ. Замер показал: `operations.can_edit` нет НИ У ОДНОЙ неадминской
-- роли. То есть одна правка кода оставила бы применение импорта только админу, и роль
-- «Фин Менеджер», которая им пользуется, потеряла бы рабочий инструмент. Владелец
-- решил: импорт ей разрешить.
--
-- ПОБОЧНОЕ СЛЕДСТВИЕ, названное вслух: `operations:edit` — это ещё и правка операций
-- по одной и массовая правка в реестре. Отдельного права «только импорт» нет и заводить
-- его не стали (см. выше про вторую копию). Если понадобится разделить — это отдельное
-- решение и отдельная секция.
--
-- Повторно накатываемая: `ON CONFLICT` по паре (роль, секция), а при существующей
-- строке просто поднимаем флаг.

INSERT INTO role_permissions (role_id, section, can_view, can_edit)
SELECT r.id, 'operations', 1, 1
  FROM roles r
 WHERE r.key = 'manager'
   AND NOT EXISTS (SELECT 1 FROM role_permissions rp
                    WHERE rp.role_id = r.id AND rp.section = 'operations');

UPDATE role_permissions rp
   SET can_edit = 1
  FROM roles r
 WHERE rp.role_id = r.id
   AND r.key = 'manager'
   AND rp.section = 'operations'
   AND rp.can_edit IS DISTINCT FROM 1;

-- Проверка глазами: у роли должно стать видно и править.
SELECT r.label AS роль, rp.can_view AS смотрит, rp.can_create AS создаёт,
       rp.can_edit AS правит,
       (SELECT count(*) FROM role_permissions x
         WHERE x.role_id = r.id AND x.section = 'import' AND x.can_view = 1) AS импорт
  FROM roles r
  JOIN role_permissions rp ON rp.role_id = r.id AND rp.section = 'operations'
 WHERE r.key = 'manager';
