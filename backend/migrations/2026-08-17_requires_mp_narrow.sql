-- Флаг «требует привязанный медиаплан» сузить до двух стадий (владелец, 2026-08-17):
-- «МП Отправлено» и «Бронь». Дальше по лестнице сделка без плана оказаться не может,
-- а на легаси-данных флаг только запирает движение.
--
-- Цифры, из-за которых правка нужна: МП есть у 64 сделок из 1581. Флаг стоял у 12 стадий
-- из 15, включая «Оплату», «ЭДО» и «Архив успешных сделок», то есть 1517 сделок нельзя
-- было двинуть дальше первой стадии вообще — диалог движения упирался в «нужен
-- привязанный медиаплан». Для предстоящей сегментации истории это блокер.
--
-- Терминальные стадии флага и так не проверяют (см. sales_dashboard.move_deal), но
-- снимаем и с них — чтобы состояние в базе совпадало с тем, что реально работает.

BEGIN;

UPDATE sales_stages SET requires_media_plan = false
 WHERE name NOT IN ('МП Отправлено', 'Бронь');

UPDATE sales_stages SET requires_media_plan = true
 WHERE name IN ('МП Отправлено', 'Бронь');

COMMIT;
