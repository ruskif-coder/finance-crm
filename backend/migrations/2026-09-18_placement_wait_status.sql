-- Площадка без креативов — «ждёт сборки», а не «у трафика».
--
-- Замер владельца 18.09.2026: в расхлопе РК двадцать площадок стояли со статусом
-- «у трафика», хотя по ним нет ни одного креатива — сборка не закончена, отправлять
-- нечего. Разница не косметическая: «у трафика» ставит площадку в очередь работы, и
-- человек ищет у себя задачу, которой не существует.
--
-- Значение добавлено в начало конвейерной части шкалы (`app/ad/flight.PLACEMENT_CHAIN`),
-- ограничения CHECK на колонке нет — список статусов живёт в коде и приборах, как и у
-- остальных русских перечислений проекта.
--
-- Что делает этот файл:
--   1. меняет умолчание колонки — новые строки рождаются «ждёт сборки»;
--   2. чинит уже записанное: «у трафика» у площадок, по которым нет НИ ОДНОГО креатива.
--      Тех, у кого креативы есть, не трогаем — их статус пересчитает сборка.
--
-- Повторный накат безопасен: второй прогон не найдёт строк для правки.

ALTER TABLE ad_campaign_placement ALTER COLUMN status SET DEFAULT 'ждёт сборки';

UPDATE ad_campaign_placement p
   SET status = 'ждёт сборки'
 WHERE p.status = 'у трафика'
   AND NOT EXISTS (SELECT 1 FROM ad_campaign_creative c WHERE c.placement_id = p.id);
