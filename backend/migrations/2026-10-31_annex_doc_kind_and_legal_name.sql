-- Вид документа ДС и юридическое название рекламодателя. Состав согласован с владельцем
-- 31.10.2026 (три колонки, больше ничего).
--
-- 1. Юридическое название рекламодателя.
--
-- Зачем колонка, а не вывод из связей: на проде `sales_advertisers.counterparty_id`
-- заполнен у 0 из 226 рекламодателей, связка М:М `sales_advertiser_counterparties` — у 7.
-- То есть вывести юрлицо рекламодателя сегодня не из чего, а `annex_tpl/legal_name.py`
-- умеет только переставить форму вперёд («ГРИНДЕКС РУС ООО» → «ООО «ГРИНДЕКС РУС»»), но
-- не придумать название.
--
-- Печатается БУКВАЛЬНО, без прогона через legal_name(): смысл юридического названия в
-- том, что оно вписано точно как в реестре. Тихая правка чужих реквизитов — ровно то, от
-- чего предостерегает докстрока самого legal_name.py: её не видно, а ошибку в реквизитах
-- подписывают.
ALTER TABLE sales_advertisers ADD COLUMN IF NOT EXISTS legal_name text;

-- 2. Тумблер «Приложение / ДС» — у ДОГОВОРА.
--
-- Историческое название тянется за договором, а не за контрагентом: у контрагента
-- договоров может быть несколько, и названия у них бывают разные (решение владельца
-- 31.10.2026).
--
-- NULL = «приложение». Это сохраняет то, как печатаются все 185 договоров сегодня:
-- выкладка не должна молча переименовать документы. Значения — 'приложение' | 'дс';
-- проверки CHECK нет намеренно, незнакомое значение код деградирует к умолчанию
-- (app/annex_tpl/doc_kind.py::kind_of), потому что документ нужен как раз в плохую минуту.
ALTER TABLE contracts ADD COLUMN IF NOT EXISTS annex_word text;

-- 3. Вид, зафиксированный на момент выпуска документа.
--
-- Зачем отдельно от тумблера: тумблер у договора можно переключить и завтра, а уже
-- выпущенный документ обязан сохранить своё имя — подписанное не переименовывают.
-- Заводим сейчас, пока чистовых документов нет ни одного (владелец 31.10.2026: «мы пока
-- не сделали чистовых доков, так что как раз доделаем») — позже та же колонка потребовала
-- бы разбора, какой из 68 приложений чем был.
--
-- NULL — документ выпущен до этой правки либо ещё не выпущен: вид берётся от договора.
ALTER TABLE sales_annexes ADD COLUMN IF NOT EXISTS doc_kind text;
