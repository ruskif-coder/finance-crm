-- Два поля услуги, которые печатаются в приложении к договору (ДС).
--
-- Решение владельца 05.09.2026: и текстовка позиции, и тип ротации задаются в
-- конструкторе услуг — то есть у услуги, а не у строки медиаплана. Одна услуга
-- продаётся одинаково, и держать это в каждой строке плана значило бы переписывать
-- один и тот же абзац при каждой сборке.
--
-- Почему НЕ переиспользован существующий `sales_services.note`: в соседних справочниках
-- (рекламодатели, агентства) `note` означает внутренний комментарий. Текст, который
-- печатается в подписанном клиентом документе, и внутренняя заметка — разные вещи, и
-- одно поле на двоих потом разделять дороже, чем завести второе сейчас.
--
-- Третья колонка документа, «Место размещения», полем не становится: у всех наших услуг
-- она одна и та же (SIMB-AD) и живёт константой в app/sales/annex.py.

ALTER TABLE sales_services
    ADD COLUMN IF NOT EXISTS doc_position  TEXT,          -- колонка «Позиция» в ДС: описание услуги целиком
    ADD COLUMN IF NOT EXISTS rotation_type VARCHAR(20);   -- «Динамика» / «Статика»; пусто — формат не медийный

COMMENT ON COLUMN sales_services.doc_position IS
    'Текст колонки «Позиция» в приложении к договору. Пусто — в документе останется одно название услуги.';
COMMENT ON COLUMN sales_services.rotation_type IS
    'Тип ротации для медийных форматов: «Динамика» или «Статика». Строкой, а не FK: значений два, и переименование не должно осиротить услугу.';
