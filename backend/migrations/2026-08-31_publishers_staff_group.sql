-- Контур «Паблишеры» становится рабочей группой роли.
--
-- НАЙДЕНО РЕПЕТИЦИЕЙ на боевой базе 31.08.2026. Событие `creative_silence` («площадка
-- молчит») было адресовано ключом `role_10` — а это НОМЕР строки в таблице ролей той
-- установки, где роль завели. Здесь и на проде номер совпал случайно; следующая установка
-- совпадением не обязана, и событие ушло бы в пустоту молча.
--
-- Тот же разбор, что у ролей трафика (2026-08-28_traffic_queue.sql): адресат — это КОНТУР,
-- а контур уже есть в схеме, `roles.staff_group`. К трём существующим значениям
-- (`seller` / `account` / `traffic`) добавляется четвёртое — `publishers`. Оно и так
-- существует как контур меню и как профиль уведомлений; в ролях его просто не было.
--
-- Сравнение метки БЕЗ РЕГИСТРА И БЕЗ КРАЁВ — по той же причине, по которой репетиция
-- нашла на проде «траффик» с маленькой буквы рядом с «Траффик».
UPDATE roles
   SET staff_group = 'publishers'
 WHERE lower(btrim(label)) = 'менеджер паблишеров'
   AND staff_group IS DISTINCT FROM 'publishers';
