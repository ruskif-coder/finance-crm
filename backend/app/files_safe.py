# -*- coding: utf-8 -*-
"""Одна проверка пути на все места, где файл отдают или удаляют.

ЗАЧЕМ. Относительный ключ файла лежит в базе, и код доверяет ему как своему. Доверие
законное — путь туда кладём мы сами, — но оно держится на том, что запись никто не
испортил: ни ошибкой миграции, ни правкой руками в psql, ни импортом, который однажды
подставит не то. Стоит этому случиться, и `os.path.join(корень, путь)` с `..` внутри
выведет чтение за пределы хранилища.

Это защита в глубину, а не затыкание известной дыры: имена при загрузке уже
санитизируются. Но проверка была ровно в ОДНОМ месте из десяти (`operations.py`), а
остальные девять отдавали файл по пути из базы как есть — разбор внешнего аудита
11.09.2026, F1-06.

ПОЧЕМУ ОБЩЕЙ ФУНКЦИЕЙ. Девять копий одной проверки разойдутся: в одной забудут `realpath`,
в другой сравнят через `in` вместо `startswith`, в третьей потеряют разделитель на конце —
и `/app/uploads-evil` пройдёт как `/app/uploads`. Ровно поэтому в проекте уже есть один
форматтер денег и один генератор имени сделки.

ДВА РЕЖИМА, и это не удобство, а разные обязанности.

`safe_upload_path` / `existing_upload_path` отказывают клиенту — они для ручек, которые
отдают ОДИН файл: там отказ и есть правильный ответ.

`inside_uploads` возвращает `None` и молчит наружу. Он для двух случаев, где отказ не к
месту:

  · **сборка архива.** Одна испорченная строка из тридцати не должна лишать человека
    остальных двадцати девяти — цикл её пропускает, как уже пропускает отсутствующие
    на диске файлы;
  · **удаление.** К моменту `os.remove` строки в базе обычно уже нет, и сказать «400,
    некорректный путь» некому — запрос обязан завершиться успехом. Здесь важно НЕ
    удалить, а не пожаловаться.

Оба тихих случая пишут в лог: путь за пределами хранилища означает испорченную запись, и
об этом должен узнать человек, даже если запросу это не мешает. Первый режим до
11.09.2026 покрывал только `FileResponse`, а второй не существовал вовсе: в каждой паре
«скачать / удалить» скачивание было проверено, а стоящее на пятнадцать строк ниже
удаление — нет.
"""
import logging
import os

from fastapi import HTTPException

log = logging.getLogger("finance.files")

UPLOADS_ROOT = "/app/uploads"


def inside_uploads(rel, *, root: str = UPLOADS_ROOT,
                   subdir: str | None = None) -> str | None:
    """Абсолютный путь внутри хранилища — или `None`, БЕЗ исключения.

    `rel` — относительный ключ из базы. `subdir` сужает границу до конкретной папки:
    файл договора не должен отдаваться ручкой креативов, даже если путь формально внутри
    `uploads`.

    Сравнение по `realpath`: символическая ссылка внутри хранилища, указывающая наружу,
    иначе прошла бы проверку — путь-то начинается правильно.
    """
    if not rel or not str(rel).strip():
        return None

    base = os.path.realpath(os.path.join(root, subdir) if subdir else root)
    try:
        full = os.path.realpath(os.path.join(root, str(rel)))
    except ValueError:
        # `\0` в пути — `realpath` бросает ValueError. Это испорченная запись, а не сбой
        # сервера: тихий режим возвращает None, шумный превратит это в 400, а не в 500.
        log.warning("Путь файла нечитаем (%r) — запись в базе испорчена", rel)
        return None

    # Разделитель на конце обязателен: без него `/app/uploads-evil` проходит как
    # начинающийся с `/app/uploads`.
    if full != base and not full.startswith(base + os.sep):
        log.warning("Путь файла ведёт за пределы хранилища: %r → %r", rel, full)
        return None
    return full


def safe_upload_path(rel: str, *, root: str = UPLOADS_ROOT,
                     subdir: str | None = None) -> str:
    """Тот же расчёт, но негодный путь — отказ клиенту. Для ручек, отдающих один файл."""
    if not rel or not str(rel).strip():
        raise HTTPException(status_code=404, detail="У записи не указан файл")
    full = inside_uploads(rel, root=root, subdir=subdir)
    if full is None:
        raise HTTPException(status_code=400, detail="Некорректный путь файла")
    return full


def existing_upload_path(rel: str, *, root: str = UPLOADS_ROOT,
                         subdir: str | None = None) -> str:
    """То же плюс проверка существования. Два разных ответа намеренно: «путь неверный» —
    это про запись в базе, «файла нет» — про диск, и чинятся они по-разному."""
    full = safe_upload_path(rel, root=root, subdir=subdir)
    if not os.path.exists(full):
        raise HTTPException(status_code=404, detail="Файл не найден на сервере")
    return full


def remove_upload(rel, *, root: str = UPLOADS_ROOT, subdir: str | None = None) -> bool:
    """Удалить файл хранилища по ключу из базы. `True`, если удалили.

    Единственный способ звать `os.remove` по пути из базы. Ни один из вызовов не имеет
    права:

      · выйти за границу хранилища — сюда и приходит `inside_uploads`;
      · уронить запрос, если файла нет. Строку из базы к этому моменту уже удалили, и
        ошибка на уборке превратила бы успешное удаление записи в «500» на глазах у
        человека, который всё сделал правильно. Оставшийся файл — сирота, а не отказ;
        сирот ловит отдельная проверка на экране состояния.
    """
    full = inside_uploads(rel, root=root, subdir=subdir)
    if full is None:
        return False
    try:
        os.remove(full)
        return True
    except OSError:
        return False


__all__ = ["inside_uploads", "safe_upload_path", "existing_upload_path",
           "remove_upload", "UPLOADS_ROOT"]
