# -*- coding: utf-8 -*-
"""Имена позиций Weborama и сборка итогового тега. Чистая логика, без сети и БД.

Два потребителя: ручной путь (заполнение `Mediaplan template` для менеджера) и API —
в обоих одни и те же правила имён, и расходиться им нельзя.
"""
import re

# Таблица транслитерации ИЗ ИНСТРУКЦИИ Weborama (pixel_algorithm, п. 1.1).
#
# ⚠ Она НЕ равна `sales/reconcile.translit`, и это осознанно. Тот огрубляет намеренно
# (`ё→e`, `й→i`, `х→h`, `щ→sch`), потому что решает другую задачу — нечёткое сравнение
# названий компаний. Здесь имя уезжает наружу как ТОЧНЫЙ идентификатор позиции, по
# которому Weborama потом вернёт пиксель. Одна функция на две задачи поссорила бы их:
# сравнение стало бы строже, а идентификатор — неверным.
#
# Инструкция называет таблицу «ГОСТ 7.79-2000, система Б», но ею не является (в стандарте
# `х→x`, `ц→cz/c`, `щ→shh`). Идём по таблице, а не по названию.
_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "j", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    # ⚠ Буквы «ы» в таблице инструкции НЕТ вовсе. Ставим `y` как общепринятое; вопрос
    # владельцу задан. Молча пропустить букву нельзя: «Крым» стал бы «krm».
    "ы": "y",
}

# Что разрешено в имени. Шапка шаблона говорит «latin with no special symbols except "_"»,
# но в собственном заполнении владельца домены идут с точками (`aptechestvo.ru`), а имена
# площадок бывают с дефисом. Поэтому точку и дефис оставляем, остальное режем: имя без
# точки перестало бы быть доменом, а это половина смысла строки.
_ALLOWED = re.compile(r"[^A-Za-z0-9_.\-]+")

# Плейсхолдер рандомизатора в сыром пикселе Weborama.
RANDOM_PLACEHOLDER = "[RANDOM]"

# Чем его заменяют. Ключ — куда пойдёт тег; значение — макрос платформы плюс разделитель
# параметра площадки. Хвост `&a.ycp=` одинаков у обоих, но живёт здесь, а не в коде
# сборки: он часть подстановки, и разнести их значило бы позволить им разойтись.
RANDOM_MACRO = {
    "dsp": "{RND}&a.ycp=",
    "adfox": "%system.random%&a.ycp=",
}


def translit(value: str) -> str:
    """Кириллица → латиница по таблице Weborama, с очисткой недопустимых символов."""
    out = []
    for ch in (value or ""):
        low = ch.lower()
        if low in _TRANSLIT:
            rep = _TRANSLIT[low]
            # Заглавной делаем ПЕРВУЮ букву замены, а не всю: «Ё» — это «Yo», не «YO».
            out.append(rep.capitalize() if ch.isupper() and rep else rep)
        else:
            out.append(ch)
    return _ALLOWED.sub("_", "".join(out)).strip("_")


def has_cyrillic(value: str) -> bool:
    """Осталась ли кириллица. Шаблон красит такую ячейку красным, и мы обязаны поймать
    это раньше: файл с кириллицей менеджер вернёт, а вызов API отвергнут."""
    return bool(re.search(r"[А-Яа-яЁё]", value or ""))


def domain_of(site: str) -> str:
    """Голый домен: без протокола, без пути, без завершающего слэша, в нижнем регистре.

    У нас домены площадок и так лежат без протокола (замер 09.09.2026: 41 из 41), но
    приходят они и из ручного ввода, поэтому нормализуем на входе, а не надеемся.
    """
    s = (site or "").strip().lower()
    s = re.sub(r"^[a-z]+://", "", s)
    s = s.split("/")[0].split("?")[0]
    return s.strip(". ")


def row_name(channel: str, campaign: str, site: str) -> str:
    """Колонка D шаблона — `Channel_кампания_домен`, уникальная в пределах медиаплана.

    ⚠ Инструкция описывает этим именем ДРУГОЕ поле: её пример
    `SIMB-AD_banner_Desktop_afalaza_aptechestvo.ru` — это колонка E, которую в шаблоне
    собирает формула. Реальный D в заполнении владельца короче ровно на «аккаунт_формат».
    Сверено по файлу, а не по тексту.
    """
    parts = [translit(channel), translit(campaign), domain_of(site)]
    return "_".join(p for p in parts if p)


def position_name(account_id: str, fmt: str, name: str) -> str:
    """Колонка E — `Аккаунт_формат_<имя строки>`. В шаблоне это формула
    `="SIMB-AD_banner_"&D19`; повторяем её значение, чтобы имя можно было сверить с
    ответом Weborama, не открывая Excel."""
    return "_".join(p for p in (translit(account_id), translit(fmt), name) if p)


def final_tag(pixel: str, site: str, kind: str = "dsp") -> str:
    """Итоговый тег: подстановка макроса рандомизатора и хвост с адресом площадки.

    Формулы из инструкции (п. 3.1.2–3.1.3) один в один:
        =SUBSTITUTE(E2;"[RANDOM]";"{RND}&a.ycp=") & "https://" & домен

    Адрес — БЕЗ завершающего слэша: инструкция подчёркивает это отдельно, а лишний слэш
    уедет в параметр площадки и склеит его со следующим значением.
    """
    if not pixel or not pixel.strip():
        raise ValueError("Пустой пиксель — собирать нечего")
    macro = RANDOM_MACRO.get((kind or "").lower())
    if macro is None:
        raise ValueError(
            f"Неизвестный тип трафика «{kind}»: ожидается {' или '.join(RANDOM_MACRO)}")
    dom = domain_of(site)
    if not dom:
        raise ValueError("Пустой домен площадки — тег без адреса бессмыслен")
    if RANDOM_PLACEHOLDER not in pixel:
        # Отказываем: тег без кеш-бастера считает показы неверно, а выяснится это по
        # расхождению цифр через месяц. Если окажется, что Weborama законно присылает
        # пиксель без плейсхолдера, — это решение владельца, а не молчаливое допущение.
        raise ValueError(
            f"В пикселе нет {RANDOM_PLACEHOLDER} — проверьте, тот ли столбец взят из "
            f"ответа Weborama")
    return pixel.replace(RANDOM_PLACEHOLDER, macro) + f"https://{dom}"


def same_position(a: str, b: str) -> bool:
    """Одна ли это позиция. Сравнение БЕЗ учёта регистра — и это не придирка.

    Их имена собраны из того, что человек набрал в Excel: в кабинете живёт
    `..._anaferon_Maksavit.ru` с заглавной M, рядом `..._minicen.ru` со строчной. Наши
    домены все в нижнем регистре (замер 09.09.2026: 41 из 41), поэтому генерация даст
    `maksavit.ru`, и точное сравнение объявит уже заведённую позицию новой — а это либо
    дубль в чужом кабинете, либо «пиксель потерялся».

    Генерируем всё же в нижнем регистре: наш справочник — источник, и приводить его к
    чужим опечаткам значит закрепить их навсегда.
    """
    return (a or "").strip().lower() == (b or "").strip().lower()


def project_label(deal_code: str, brand: str, month) -> str:
    """Имя проекта WCM: `<код сделки>_<бренд>_<ГГГГ-ММ>` — решение владельца 09.09.2026.

    Их собственные проекты названы иначе (`afalaza_2026`, `prospekta 2026`), то есть
    бренд плюс ГОД. Наше имя добавляет сделку и сужает год до месяца — расхождение с уже
    заведёнными осознанное: по их имени нельзя понять, к какой сделке относится проект, а
    у нас в месяце может быть несколько сделок одного бренда.

    Берётся КОД сделки (`sales_deals.code`), а не числовой id: код — это то, чем сделка
    зовётся во всём интерфейсе и в ссылках, он есть у всех 920 сделок и читается человеком,
    который потом сверяет отчёт в чужом кабинете. Числовой id там не значит ничего.

    Бренд приводится к нижнему регистру: так названы ВСЕ кампании в их файле и в кабинете
    (`tenoten`, `salvisar`, `afalaza`), и так же написал владелец.
    """
    code = translit(str(deal_code or "")).strip("_")
    if not code:
        raise ValueError("Нет кода сделки — по имени проекта её будет не найти")
    b = translit(str(brand or "")).lower().strip("_")
    if not b:
        raise ValueError("Нет бренда — проект в WCM заводится по бренду")
    m = month.strftime("%Y-%m") if hasattr(month, "strftime") else str(month or "").strip()
    if not re.fullmatch(r"\d{4}-\d{2}", m):
        raise ValueError(f"Месяц «{month}» не в формате ГГГГ-ММ")
    return f"{code}_{b}_{m}"


def campaign_label(brand: str, ident) -> str:
    """Имя кампании WCM: `<бренд>_<ID>` — решение владельца 09.09.2026.

    У них кампания зовётся просто `anaferon`, и в списке из двадцати пяти одинаковых имён
    невозможно понять, к чему относится строка. ID делает её самоопознаваемой там, где
    проект не виден — а на обзорном экране кабинета видны именно кампании.

    `ident` читаю как КОД СДЕЛКИ — тот же, что в имени проекта: владелец назвал их одним
    словом «ID», а параллельная структура «сделка+бренд+месяц» / «бренд+ID» напрашивается
    на один и тот же идентификатор. Если имелся в виду id нашей РК — меняется вызывающей
    стороной, функция принимает что дадут.
    """
    b = translit(str(brand or "")).lower().strip("_")
    if not b:
        raise ValueError("Нет бренда — имя кампании собирать не из чего")
    i = translit(str(ident or "")).strip("_")
    if not i:
        raise ValueError("Нет идентификатора — кампанию не отличить от соседней")
    return f"{b}_{i}"


