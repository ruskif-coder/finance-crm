# -*- coding: utf-8 -*-
"""Шаблоны писем: подстановки и их проверка.

ПОЧЕМУ ПОДСТАНОВКИ ПРОВЕРЯЮТСЯ ПРИ СОХРАНЕНИИ, А НЕ ПРИ ОТПРАВКЕ. Опечатка в имени
поля — `{плошадка}` вместо `{площадка}` — при отправке не падает: получатель просто
видит фигурные скобки в письме. Узнаём мы об этом от площадки, а не от системы, и уже
после того, как письмо ушло. Поэтому набор полей у каждого шаблона объявлен, а экран не
даёт сохранить текст с неизвестным полем.

ПОЧЕМУ НЕ `str.format`. У него любая одиночная фигурная скобка в тексте — синтаксическая
ошибка, а письма пишут люди, и скобка там появится. Своя подстановка проще и не роняет
отправку из-за знака препинания.
"""
from __future__ import annotations

import re
from typing import Dict

# Поля, доступные шаблону. Набор ОБЪЯВЛЕН, а не выведен из текста: иначе опечатка
# становится «новым полем», и проверять было бы нечего.
FIELDS: Dict[str, Dict[str, str]] = {
    "url_request": {
        "площадка": "название площадки",
        "домен": "домен площадки",
        # Не название сделки — оно внутреннее и наружу не уходит (аудит 23.09.2026, 5.L10).
        "сделка": "бренд и период размещения",
        "бренд": "бренд",
        "период": "период размещения",
        "сотрудник": "кто отправляет",
        # Сам вопрос площадке. Его выбирает трафик из справочника формулировок в момент
        # запроса, и он же записывается у получателя как «что мы спросили». Шаблон —
        # конверт вокруг него: приветствие, подпись, тема.
        "текст": "текст запроса, выбранный отправителем",
    },
    "notify": {
        "заголовок": "заголовок уведомления",
        "текст": "текст уведомления",
        "ссылка": "ссылка на экран",
        # Числа события одной строкой «ключ: значение · …» — те же, что в панели и в
        # телеграме. Поле появилось 16.09.2026, и шаблон, заведённый раньше, его не
        # упоминает: тогда строка фактов дописывается в конец сама. Потерять цифры
        # нельзя — ради них письмо и открывают.
        "факты": "числа события одной строкой",
    },
    # Письмо ПЛОЩАДКЕ об одном событии. Отдельно от «notify», хотя вёрстка та же:
    # обращение и подпись у внешнего письма другие, а править их вместе со служебным
    # означало бы выбирать между «здравствуйте, коллеги» и «здравствуйте».
    "pub_notify": {
        "заголовок": "заголовок события",
        "контекст": "к чему относится — площадка, бренд, период",
        "текст": "пояснение к событию",
        "факты": "числа события одной строкой",
        "ссылка": "ссылка в кабинет",
    },
    "test": {"сотрудник": "кому отправляем проверку"},
}

_PLACEHOLDER = re.compile(r"\{([^{}]+)\}")


def known_fields(kind: str) -> Dict[str, str]:
    return FIELDS.get(kind, {})


def placeholders(text: str) -> list:
    """Все поля, упомянутые в тексте, в порядке появления и без повторов."""
    seen, out = set(), []
    for m in _PLACEHOLDER.finditer(text or ""):
        name = m.group(1).strip()
        if name and name not in seen:
            seen.add(name)
            out.append(name)
    return out


def unknown_fields(kind: str, *texts: str) -> list:
    """Поля, которых у этого вида письма нет. Пусто — можно сохранять."""
    allowed = set(known_fields(kind))
    bad = []
    for t in texts:
        for name in placeholders(t):
            if name not in allowed and name not in bad:
                bad.append(name)
    return bad


def render(text: str, values: Dict[str, object]) -> str:
    """Подставить значения. Незаполненное поле становится ПУСТОТОЙ, а не скобками.

    Скобки в готовом письме читаются получателем как неисправность системы, и это хуже
    пропуска: пропуск он переживёт, а «{площадка}» заставит усомниться во всём письме.
    """
    def sub(m):
        name = m.group(1).strip()
        v = values.get(name)
        return "" if v is None else str(v)
    return _PLACEHOLDER.sub(sub, text or "")


def apply(db, key: str, values: Dict[str, object], *,
          subject_default: str, text_default: str) -> tuple:
    """Тема и текст письма по шаблону. Одна точка на оба контура.

    Возвращает `(тема, текст)`. Шаблона нет или он выключен — отдаём умолчания,
    собранные кодом: письмо уходит в любом случае, молчать нельзя.

    Строка фактов ДОПИСЫВАЕТСЯ в конец, если шаблон её не упоминает. Поле `{факты}`
    появилось 16.09.2026, и шаблон, заведённый раньше, о нём не знает — а факты это
    ровно те цифры, ради которых письмо открывают.

    Функция здесь, а не в каждом контуре: до неё письмо сотруднику и письмо площадке
    собирались двумя разными кусками кода, и правка одного тихо расходилась с другим.
    """
    from app.mail.models import MailTemplate       # локально: models импортирует этот модуль

    row = (db.query(MailTemplate)
           .filter(MailTemplate.key == key, MailTemplate.is_active.is_(True)).first())
    if row is None:
        return subject_default, text_default
    subject = render(row.subject, values).strip() or subject_default
    text = render(row.body, values)
    line = str(values.get("факты") or "")
    if line and line not in text:
        text = text.rstrip() + "\n\n" + line
    # Пустые подстановки оставляют дыры из пустых строк: «\n\n\n\n» в письме читается
    # как оборванный текст. Схлопываем, но абзацы сохраняем.
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return subject, text.strip()


def missing_values(text: str, values: Dict[str, object]) -> list:
    """Поля шаблона, для которых значения не пришли. Для предупреждения ДО отправки."""
    return [n for n in placeholders(text)
            if values.get(n) is None or str(values.get(n)).strip() == ""]


