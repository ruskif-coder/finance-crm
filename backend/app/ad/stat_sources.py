# -*- coding: utf-8 -*-
"""Кто пишет в `ad_campaign_stat` и чей показ считается ФАКТОМ.

Зачем отдельный файл на четыре строки данных. В таблице `ad_campaign_stat` ключ —
`(campaign_id, placement_id, date, source)`, то есть она с рождения рассчитана на
несколько источников одного и того же дня. А все шесть запросов к ней в дашборде
трафика суммировали строки БЕЗ РАЗБОРА источника. Пока источник был один, это работало;
в день, когда рядом с нашим счётчиком легла бы статистика верификатора, факт на экране
удвоился бы — и остался бы правдоподобным. Ровно тот вид отказа, который в этом проекте
дороже всего: не падение, а тихо неверное число, по которому перераспределяют объём.

Поэтому список живёт в ОДНОМ месте, а не повторяется условием в каждом запросе.

РАЗНИЦА МЕЖДУ ДВУМЯ ГРУППАМИ — НЕ ТЕХНИЧЕСКАЯ, А СМЫСЛОВАЯ.

`OWN` — наш счётчик: сколько показов система ОТДАЛА. Это то, что идёт в закрытие, в
полосу выполнения, в темп и в недокрут. Несколько источников тут складываются законно:
одна РК может крутиться в двух DSP сразу, и её показы — сумма.

`VERIFIER` — независимое измерение: сколько показов чужая система ЗАСЧИТАЛА. Эти цифры
не обязаны совпадать с нашими и не должны с ними складываться НИКОГДА. Решение владельца
10.09.2026: «факт показов Weborama — отдельная ячейка, справочная величина, не к
закрытию».

Прибор, который держит правило, — `tests/test_stat_sources.py`: он не даёт появиться
запросу к `ad_campaign_stat` без упоминания источника.
"""

# Наш счётчик. Складываются между собой.
#
# `ms`   — умолчание колонки, унаследованное от первого коннектора;
# `dsp`  — суточный срез из аналитической базы (`app/dsp/stat_daily`, крон 04:30 МСК);
#          строка без площадки — показы кампании, не разнесённые по нашим креативам;
# `demo` — генератор демо-данных стенда (`scripts/2026-09-04_demo_traffic_month.py`).
#          Он ЗДЕСЬ намеренно: на стенде это единственный факт, и убрать его из суммы
#          значит показать пустой дашборд там, где мы проверяем расчёты;
# `manual` — правка рукой, предусмотрена моделью с самого начала.
OWN = ("demo", "dsp", "manual", "ms")

# Независимые измерители. В факт не входят ни при каких условиях.
#
# `weborama`        — снято нами через их API, по вставкам, которые заводили мы;
# `weborama_manual` — введено руками с их выгрузки. Появляется у кампаний с ВНЕШНИМ
#                     пикселем: вставка там одна на всю сеть, разбивки по площадкам в
#                     отчёте нет, и тянуть нечего (решение владельца 14.09.2026).
#
# Два источника, а не один: складываются они одинаково, но доверие к ним разное — одно
# измерено, другое перепечатано человеком с чужого файла. На экране числа выглядят
# одинаково, и различить их потом можно будет только здесь.
# `weborama_demo` — демо-наполнение стенда (скрипт 2026-09-27_demo_weborama), как `demo`
# у нашего счётчика: отдельный источник, чтобы демо-цифры не смешались с настоящими и
# убирались одним DELETE по источнику.
VERIFIER = ("weborama", "weborama_manual", "weborama_demo")

KNOWN = tuple(sorted(set(OWN) | set(VERIFIER)))

# Боевой факт — из кабинета DSP. Всё прочее в OWN (демо, ручная правка) экран обязан
# подписать «факт не боевой». Верификаторы сюда не относятся вовсе: они не факт.
# До 01.10.2026 экран сверял список источников с одним `ms` — и Weborama-сверка, и
# настоящий `dsp` давали алерт «факт не боевой» на проде.
COMBAT = ("dsp", "ms")


def non_combat(sources) -> list:
    """Из источников, найденных у РК, — те, из-за которых факт нельзя считать боевым."""
    return sorted(s for s in sources if s in OWN and s not in COMBAT)


def fact_sources() -> list:
    """Список для `source = ANY(:src)` в запросах факта.

    Список, а не сравнение с одной строкой: источников нашего счётчика заведомо больше
    одного — вторая DSP со статистикой экселькой уже известна и отложена, а не отменена.
    """
    return list(OWN)


def fact_as_of(db, today=None):
    """Дата среза статистики — последний день, за который пришёл БОЕВОЙ факт (владелец
    02.10.2026). По ней считаются план на сегодня, темп, стена дней и сверка с WR.

    Факт DSP приезжает ночью за вчера, а Weborama утром приносит и неполный текущий день.
    План «на сегодня» против факта «по вчера» показывал РК на день отстающей, а WR за
    полтора дня против DSP за сутки читался задвоением. Нет боевого факта (стенд) — по
    нашему счётчику вообще; нет никакого — вчера.
    """
    from datetime import date as _date, timedelta
    from sqlalchemy import text
    today = today or _date.today()
    q = text("SELECT max(date) FROM ad_campaign_stat WHERE source = ANY(:s) AND date <= :t")
    for group in (COMBAT, OWN):
        d = db.execute(q, {"s": list(group), "t": today}).scalar()
        if d:
            return d
    return today - timedelta(days=1)


def is_stale(as_of, today=None) -> bool:
    """Срез старше вчерашнего — ночной съём DSP встал (ревью 02.10.2026). Без этого флага
    застывший срез прятал бы сбой: темп считается на ту же дату, и все РК «в графике»."""
    from datetime import date as _date
    return ((today or _date.today()) - as_of).days > 1


def wr_outside(own_by_placement, ver) -> int:
    """Показы WR по площадкам БЕЗ нашего факта — вне DSP (прямой тег у аптеки). В сверку
    не идут, на экране — справочной строкой (владелец 02.10.2026)."""
    by = (ver or {}).get("by_placement") or {}
    return sum(n or 0 for pid, n in by.items() if not own_by_placement.get(pid))


def is_verifier(source: str) -> bool:
    return source in VERIFIER


def mismatch_pct(own, verifier):
    """Расхождение нашего счётчика с верификатором, в процентах. None — сравнивать нечем.

    ЗНАМЕНАТЕЛЬ — НАШ показ, а не их и не среднее. Причина не математическая: в договоре
    и в акте стоит то, что отдали МЫ, и вопрос звучит «насколько верификатор недосчитал
    относительно того, что мы предъявляем». Поменяй знаменатель — и то же самое
    расхождение получит другое число, а порог приёмки («до 10 %») останется прежним.

    Знак сохраняется: плюс — верификатор насчитал МЕНЬШЕ нашего (обычный случай, часть
    показов он не засчитал), минус — больше. Модуль здесь брать нельзя: «их больше» и
    «их меньше» разбираются по-разному, а одинаковое число спрячет разницу.

    Ноль у нас — не ноль расхождения, а отсутствие базы: 0 против 1000 в процентах не
    выражается. Возвращаем None, и экран рисует прочерк.
    """
    if not own or verifier is None:
        return None
    return round((own - verifier) / own * 100, 1)


def comparable(own_total, own_by_placement, ver):
    """Что с чем сверять: `(наш факт, WR, сколько площадок покрыто)`.

    Верификатор покрывает не все площадки: соответствие «их вставка → наша площадка»
    есть только у тех, что заводили мы. Делить их сумму на НАШ факт по всей РК —
    арифметически верно и по смыслу ложно: замер 14.09.2026 дал «77 %» там, где по
    единственной покрытой площадке было 10 %. Поэтому, если Weborama мерила площадки,
    сравниваются ТОЛЬКО они; если замер есть лишь по РК целиком (строки без площадки —
    ручной ввод с их отчёта), сравнение идёт по всей РК.

    `own_by_placement` — {placement_id: наш факт} по площадкам РК; `ver` — ответ
    `traffic_dashboard._verifier` для этой РК ({shows, by_placement}) или None.
    Одно правило на карточку сделки, строку и график дашборда трафика (ревью 27.09.2026).
    """
    ver = ver or {}
    by = ver.get("by_placement") or {}
    # Только площадки с НАШИМ фактом (владелец 02.10.2026): площадку вне DSP — прямой тег
    # у аптеки — мерит одна Weborama, и её показы в сверке выглядели «лишними».
    covered = [pid for pid in by if own_by_placement.get(pid)]
    if covered:
        return (sum(own_by_placement[pid] or 0 for pid in covered),
                sum(by[pid] or 0 for pid in covered), len(covered))
    if by:
        return own_total, None, 0          # мерили только площадки вне нашего факта
    return own_total, ver.get("shows"), 0


# ── цвет расхождения с верификатором (владелец 27.09.2026) ─────────────────────
#
# Порог — из плановых показателей сделки (`goals.weborama`, поле свободного ввода: «до
# 10 %», «7,5»); числа там нет — базовые 10 %. Шкала: до порога зелёный, до двух порогов
# жёлтый (при 10 % — 10–20 %), дальше красный. Weborama больше нашего факта — красный
# отдельно: «больше нашего не видел никогда», значит недосчитали МЫ — сбой съёма.
# Одно правило на дашборд трафика и блок «Рекламная кампания» в карточке сделки.
DEFAULT_MISMATCH_LIMIT = 10


def goal_limit(goals) -> float:
    import re
    raw = str((goals or {}).get("weborama") or "").replace(",", ".")
    m = re.search(r"\d+(?:\.\d+)?", raw)
    return float(m.group(0)) if m else DEFAULT_MISMATCH_LIMIT


def mismatch_level(pct, limit):
    """{level: ok|warn|bad, reason, hint} по проценту расхождения; None — сверять нечем."""
    if pct is None:
        return None
    lim = limit or DEFAULT_MISMATCH_LIMIT
    if pct < 0:
        return {"level": "bad", "reason": "wr_higher", "limit": lim,
                "hint": "Weborama насчитала больше нашего факта — проблема со съёмом "
                        "статистики на нашей стороне"}
    if pct <= lim:
        return {"level": "ok", "reason": None, "limit": lim,
                "hint": f"в пределах допустимого ({lim:g} %)"}
    if pct <= 2 * lim:
        return {"level": "warn", "reason": "over_limit", "limit": lim,
                "hint": f"больше допустимых {lim:g} %"}
    return {"level": "bad", "reason": "over_double", "limit": lim,
            "hint": f"больше {2 * lim:g} % — вдвое выше допустимого"}
