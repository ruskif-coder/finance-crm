# -*- coding: utf-8 -*-
"""Кто пишет в `ad_campaign_stat` и чей показ считается ФАКТОМ.

Зачем отдельный файл на четыре строки данных. В таблице `ad_campaign_stat` ключ —
`(campaign_id, placement_id, date, source)`, то есть она с рождения рассчитана на
несколько источников одного и того же дня. А все шесть запросов к ней в дашборде
трафика суммировали строки БЕЗ РАЗБОРА источника. Пока источник был один, это работало;
в день, когда рядом с нашим счётчиком легла бы статистика верификатора, факт на экране
удвоился бы — и остался бы правдоподобным. Ровно тот вид отказа, который в этом проекте
дороже всего: не падение, а тихо неверное число, по которому перераспределяют объём.

Поэтому список живёт в ОДНОМ месте, а не повторяется условием в каждом запросе.

РАЗНИЦА МЕЖДУ ДВУМЯ ГРУППАМИ — НЕ ТЕХНИЧЕСКАЯ, А СМЫСЛОВАЯ.

`OWN` — наш счётчик: сколько показов система ОТДАЛА. Это то, что идёт в закрытие, в
полосу выполнения, в темп и в недокрут. Несколько источников тут складываются законно:
одна РК может крутиться в двух DSP сразу, и её показы — сумма.

`VERIFIER` — независимое измерение: сколько показов чужая система ЗАСЧИТАЛА. Эти цифры
не обязаны совпадать с нашими и не должны с ними складываться НИКОГДА. Решение владельца
10.09.2026: «факт показов Weborama — отдельная ячейка, справочная величина, не к
закрытию».

Прибор, который держит правило, — `tests/test_stat_sources.py`: он не даёт появиться
запросу к `ad_campaign_stat` без упоминания источника.
"""

# Наш счётчик. Складываются между собой.
#
# `ms`   — умолчание колонки, унаследованное от первого коннектора;
# `dsp`  — суточный срез из аналитической базы (тянучка ещё не написана);
# `demo` — генератор демо-данных стенда (`scripts/2026-09-04_demo_traffic_month.py`).
#          Он ЗДЕСЬ намеренно: на стенде это единственный факт, и убрать его из суммы
#          значит показать пустой дашборд там, где мы проверяем расчёты;
# `manual` — правка рукой, предусмотрена моделью с самого начала.
OWN = ("demo", "dsp", "manual", "ms")

# Независимые измерители. В факт не входят ни при каких условиях.
#
# `weborama`        — снято нами через их API, по вставкам, которые заводили мы;
# `weborama_manual` — введено руками с их выгрузки. Появляется у кампаний с ВНЕШНИМ
#                     пикселем: вставка там одна на всю сеть, разбивки по площадкам в
#                     отчёте нет, и тянуть нечего (решение владельца 14.09.2026).
#
# Два источника, а не один: складываются они одинаково, но доверие к ним разное — одно
# измерено, другое перепечатано человеком с чужого файла. На экране числа выглядят
# одинаково, и различить их потом можно будет только здесь.
VERIFIER = ("weborama", "weborama_manual")

KNOWN = tuple(sorted(set(OWN) | set(VERIFIER)))


def fact_sources() -> list:
    """Список для `source = ANY(:src)` в запросах факта.

    Список, а не сравнение с одной строкой: источников нашего счётчика заведомо больше
    одного — вторая DSP со статистикой экселькой уже известна и отложена, а не отменена.
    """
    return list(OWN)


def is_verifier(source: str) -> bool:
    return source in VERIFIER


def mismatch_pct(own, verifier):
    """Расхождение нашего счётчика с верификатором, в процентах. None — сравнивать нечем.

    ЗНАМЕНАТЕЛЬ — НАШ показ, а не их и не среднее. Причина не математическая: в договоре
    и в акте стоит то, что отдали МЫ, и вопрос звучит «насколько верификатор недосчитал
    относительно того, что мы предъявляем». Поменяй знаменатель — и то же самое
    расхождение получит другое число, а порог приёмки («до 10 %») останется прежним.

    Знак сохраняется: плюс — верификатор насчитал МЕНЬШЕ нашего (обычный случай, часть
    показов он не засчитал), минус — больше. Модуль здесь брать нельзя: «их больше» и
    «их меньше» разбираются по-разному, а одинаковое число спрячет разницу.

    Ноль у нас — не ноль расхождения, а отсутствие базы: 0 против 1000 в процентах не
    выражается. Возвращаем None, и экран рисует прочерк.
    """
    if not own or verifier is None:
        return None
    return round((own - verifier) / own * 100, 1)
