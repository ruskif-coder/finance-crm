# -*- coding: utf-8 -*-
"""Сроки хранения журналов.

Решение владельца 14.09.2026: **три месяца** — и почтовому журналу, и журналу доставок
уведомлений. Один срок на оба: они отвечают на один и тот же вопрос «ушло ли сообщение
и что в нём было», просто в разные двери.

## Почему у журнала вообще есть срок

Журнал открывают, когда площадка говорит «мы ничего не получали» или когда надо
перечитать отправленное. Дальше трёх месяцев этот вопрос не задают: спор о письме
полугодовой давности решается перепиской, а не журналом.

При этом строка — не метаданные. В почтовом журнале лежит ТЕЛО письма целиком, в журнале
доставок — заголовок, текст, ссылка и плашки фактов на каждый канал каждому получателю.
Второй растёт быстрее: одно событие даёт до трёх строк на человека.

## Почему три КАЛЕНДАРНЫХ месяца, а не 90 дней

Потому что сказано «три месяца», а не «девяносто дней», и в феврале это разные вещи.
Человек, которому обещали три месяца, отсчитывает от 14 сентября — 14 июня, а не 16-е.
Разница в два дня несущественна для дела и существенна для доверия к обещанию.

## Что не убирается никогда

Строки в очереди (`queued`). Очередь — это работа, которую система ещё должна сделать,
а не история: в почтовом журнале это отложенное письмо, в журнале доставок — очередь
дайджеста. Застрявшая строка трёхмесячной давности означает незамеченную поломку
отправки, и стереть её — значит стереть улику вместе с задачей.

Строки панели (`notifications`) под уборку не попадают вовсе: это не журнал, а СОСТОЯНИЕ
объекта. Оно гаснет само, когда исчезает причина, и удалять его по возрасту значило бы
убрать с глаз живую задачу.
"""
from __future__ import annotations

from datetime import date, datetime, timedelta

# Срок хранения журналов в МЕСЯЦАХ. Менять — решение владельца, не программиста.
JOURNAL_MONTHS = 3

# Статусы, которые уборка НЕ трогает ни при каком возрасте.
KEEP_STATUSES = ("queued",)


def cutoff(today: date | None = None, months: int = JOURNAL_MONTHS) -> datetime:
    """Граница хранения: всё, что создано РАНЬШЕ, подлежит уборке.

    Считается по календарю, а не в днях: «три месяца назад» от 31 мая — это 28 февраля,
    а не 31-е, которого не существует. Перебор дня зажимается последним днём месяца —
    без зажима `datetime(2026, 2, 31)` роняет уборку раз в несколько месяцев, и молча:
    замечают это по кончившемуся диску.
    """
    d = today or date.today()
    month, year = d.month - months, d.year
    while month <= 0:
        month += 12
        year -= 1
    return datetime(year, month, min(d.day, _days_in(year, month)))


def _days_in(year: int, month: int) -> int:
    nxt = date(year + (month == 12), (month % 12) + 1, 1)
    return (nxt - timedelta(days=1)).day
