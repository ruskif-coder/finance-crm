"""Кто и на каком контуре уже зарегистрирован.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. До 27.08.2026 идентификатор ОРД жил ровно в одной колонке у
записи (`Contract.ord_contract_id`, `OrdInitialContract.ord_id`,
`Counterparty.ord_client_id`) — то есть модель молча предполагала ОДИН контур. Как только
контуров стало два, это стало неверной кардинальностью: договор может быть заведён и в
боевом ЕРИР, и в песочнице, и это РАЗНЫЕ записи с разными идентификаторами.

Проявлялось это так: охранник повторной регистрации смотрел только на заполненность
колонки и отказывал независимо от контура. Договор с боевым идентификатором нельзя было
завести на демо вовсе, а если бы колонку перезаписали — потерялась бы боевая связь.

ГДЕ ХРАНИТСЯ ВТОРОЙ КОНТУР. Нигде дополнительно: журнал отправок `ord_submissions` уже
несёт `(kind, local_id, env, ord_id)` — по строке на попытку, с контуром. Это и есть
запись «эта наша строка заведена там-то под таким-то номером». Заводить параллельные
колонки `*_demo` значило бы дублировать то, что уже записано, и заводить второе место,
где правда может разойтись с первым.

ЧТО ОСТАЁТСЯ В КОЛОНКАХ. Колонка — по-прежнему главный ответ для СВОЕГО контура (в неё
легли идентификаторы из выгрузки боевого кабинета, где записи журнала нет вовсе). Поэтому
поиск двухступенчатый: сперва колонка, если её контур совпал с запрошенным, потом журнал.
"""
from typing import Optional

from sqlalchemy.orm import Session

from app.ord.models import OrdSubmission

# Контур записи, у которой он не проставлен. Выгрузка кабинета приехала до того, как
# появилась колонка `ord_env`, и все её идентификаторы — боевые.
ENV_WHEN_UNKNOWN = 'prod'


def journal_id(db: Session, kind: str, local_id: int, env: str) -> Optional[str]:
    """Идентификатор, выданный ЭТИМ контуром, по журналу отправок.

    Берётся последняя ЗАВЕРШЁННАЯ попытка с идентификатором: незавершённая (обрыв связи)
    ничего не доказывает — ровно та причина, по которой она блокирует повтор, а не
    засчитывается за регистрацию.
    """
    row = (db.query(OrdSubmission)
             .filter(OrdSubmission.kind == kind,
                     OrdSubmission.local_id == local_id,
                     OrdSubmission.env == env,
                     OrdSubmission.ord_id.isnot(None),
                     OrdSubmission.finished_at.isnot(None))
             .order_by(OrdSubmission.id.desc())
             .first())
    return row.ord_id if row else None


def known_id(db: Session, kind: str, local_id: int, env: str,
             column_id: Optional[str], column_env: Optional[str]) -> Optional[str]:
    """Чем эта запись зовётся на контуре `env` — или None, если там её ещё нет.

    Пустая строка и «местная заглушка» `local-…` за идентификатор не считаются: первая
    это незаполненное поле, вторая — наша временная метка до заведения в кабинете.
    """
    if column_id and not str(column_id).startswith('local-'):
        if (column_env or ENV_WHEN_UNKNOWN) == env:
            return column_id
    return journal_id(db, kind, local_id, env)


def own_contour(column_id: Optional[str], column_env: Optional[str], env: str) -> bool:
    """Можно ли писать выданный идентификатор прямо в колонку записи.

    Можно, когда колонка пуста (или держит заглушку) либо уже про этот же контур.

    Асимметрия между контурами намеренная: **боевой вытесняет песочницу, песочница
    боевой — никогда.** В колонке должна оказаться та запись, по которой сдаётся
    отчётность; демовская, легшая поверх боевой, увела бы отчётность на запись,
    которой в ЕРИР нет. Обратный случай безобиден: комплект, проверенный на демо,
    потом регистрируется по-настоящему, и настоящий маркер обязан вытеснить пробный.
    Вытесненный идентификатор не теряется — он остаётся в журнале отправок.
    """
    if not column_id or str(column_id).startswith('local-'):
        return True
    if (column_env or ENV_WHEN_UNKNOWN) == env:
        return True
    return env == 'prod'


def client_key(inn: str) -> int:
    """Ключ юрлица в журнале: у него нет нашей строки, к которой привязаться.

    Тот же приём, что в `submit.ensure_client`, вынесен сюда, чтобы «чем считается
    юрлицо» было записано в одном месте, а не в двух.
    """
    digits = ''.join(ch for ch in (inn or '') if ch.isdigit())
    return int(digits[:9]) if digits else 0
