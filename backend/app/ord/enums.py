def code_by_label(mapping: Dict[str, str], label: Optional[str]) -> Optional[str]:
    """Подпись → код. Незнакомая подпись даёт None, а не «похожее».

    Угадывать здесь нельзя: подставленный не тот вид договора уедет в ЕРИР молча.
    """
    if not label:
        return None
    needle = str(label).strip().lower()
    for code, text in mapping.items():
        if text.lower() == needle:
            return code
    return None


def label_by_code(mapping: Dict[str, str], code: Optional[str]) -> str:
    """Код → подпись. Незнакомый код показывается как есть.

    Наоборот, чем в code_by_label: в ОРД может появиться новое значение, и справочник
    должен его показать, а не упасть.
    """
    if not code:
        return ''
    return mapping.get(code, str(code))
