"""Наше юрлицо — одна точка на весь бэкенд.

Зачем отдельный модуль на четыре короткие функции: вопрос «какое юрлицо здесь наше»
задают четыре разных места, и до 26.08.2026 на него отвечали двумя РАЗНЫМИ правилами.
`operations.py` брал `ORDER BY id LIMIT 1` — первое попавшееся; карточка сделки
отказывалась отвечать, когда юрлиц несколько. Пока юрлицо одно, оба правила дают один
ответ, и расхождение невидимо; со вторым юрлицом операции молча получили бы то, у
которого меньше id, а карточка честно сказала бы «не знаю». Ровно так в этом проекте
однажды разошлась формула НДС в четырёх копиях — отсюда `compute_vat_fact`.

Состояние на 26.08.2026: юрлицо одно (ПРОГРАММАТИК МЕДИА ООО). Второе — гипотеза,
поэтому здесь закладка, а не многоюрлицовость.

**Что уже готово ко второму юрлицу.** Измерение существует и заполнено полностью:
`operations.own_company_id` 3035/3035, `contracts.own_company_id` 173/173,
`bank_balances.own_company_id` 4/4. Справочник уже отдаёт СПИСОК своих юрлиц с
банковскими счетами (`/counterparties/own-companies`). Договор знает своё юрлицо
через готовую связь — см. `of_contract` ниже.

**Чего не готово, и это надо будет решать с владельцем, а не выводить из кода:**

1. Ни один отчёт не фильтрует по юрлицу — ДДС, P&L, финотчёт, дебиторка и сверка
   сложат два юрлица в один результат. Выглядеть будет нормально. Это дороже всего
   остального вместе взятого.
2. У сделки и медиаплана нет выбора юрлица: сегодня оно выводится, а не выбирается.
3. Второе юрлицо заводится галочкой «Наша» в реестре контрагентов любым админом —
   ничто не мешает сделать это раньше, чем пункты 1–2 будут решены. Сигнал об этом
   один: `tests/test_deal_card_contract.py` краснеет в ту же секунду.

Пока пунктов 1–3 нет, `sole()` намеренно ОТКАЗЫВАЕТСЯ отвечать при нескольких
юрлицах вместо того, чтобы выбрать одно. Пустое значение видно и лечится; тихо
подставленное чужое юрлицо не видно и портит учёт задним числом.
"""
from typing import List, Optional

from app.models import Counterparty


def all_own(db) -> List[Counterparty]:
    """Все наши юрлица, по имени. Основа справочных списков и дропдаунов."""
    return (db.query(Counterparty)
              .filter(Counterparty.is_own_company.is_(True))
              .order_by(Counterparty.name)
              .all())


def sole(db) -> Optional[Counterparty]:
    """Единственное наше юрлицо, или None, если их не ровно одно.

    None и при нуле, и при двух — оба случая означают «однозначного ответа нет»,
    и оба обязаны привести к пустому значению у вызывающего, а не к догадке.
    """
    rows = (db.query(Counterparty)
              .filter(Counterparty.is_own_company.is_(True))
              .limit(2).all())
    return rows[0] if len(rows) == 1 else None


def sole_id(db) -> Optional[int]:
    """id единственного нашего юрлица — для автоштампа own_company_id."""
    c = sole(db)
    return c.id if c else None


def public(db) -> Optional[dict]:
    """Форма для фронта: кто мы и по какой ставке продаём.

    Ставка берётся из `vat_rate_income`, а не из `vat_rate`: последний заморожен
    (см. routers/counterparties.py) и остался от старой одноставочной схемы.
    """
    c = sole(db)
    if c is None:
        return None
    from app import vat
    # `vat_current` — ставка, по которой считается НОВЫЙ расчёт (`vat.current`: пустая или
    # нулевая ставка юрлица — это «не задана», и берётся текущая по закону). Фронт берёт её,
    # а не сырое поле: форма новой сделки иначе держала свою константу 22 (ревью 23.09.2026).
    return {"id": c.id, "name": c.name, "vat_rate_income": c.vat_rate_income,
            "vat_current": vat.current(db)}


def of_contract(contract) -> Optional[Counterparty]:
    """Юрлицо конкретного договора — точка, в которую переедут вызовы `sole`.

    Здесь уже всё есть: колонка размечена у всех договоров, связь объявлена в
    models.py. Не хватает только выбора договора там, где сегодня спрашивают
    просто «наше юрлицо» — у сделки и медиаплана платёжный договор пока не
    зафиксирован. Поэтому функция существует, но никем не вызывается: это шов,
    а не мёртвый код, и переезд начнётся именно с него.
    """
    return getattr(contract, "own_company", None) if contract is not None else None
