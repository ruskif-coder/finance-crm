"""Выключатель изменяющих вызовов во внешние боевые системы: `EXTERNAL_WRITES=off` в .env стенда (аудит 21.10.2026).

ЗАЧЕМ. Стенд — копия прода с боевыми токенами. Он ходит в боевой DSP, и любой пересчёт лимитов со стенда менял реальные
креативы (08.10.2026); у приоритезации адрес по умолчанию тоже боевой. Флаг закрывает ЗАПИСЬ на уровне транспорта каждого
клиента — DSP, приоритезация, Weborama, — раньше любого HTTP. Чтение остаётся: стенду нужна статистика и состояние.

Без флага поведение прежнее: прод работает как работал. ОРД не охвачен намеренно — у него свой контур (песочница /
боевой), а поиск там идёт и POST-запросами."""
import os

OFF = ("off", "0", "no", "false")
REFUSAL = "внешние записи выключены на этом сервере (EXTERNAL_WRITES=off)"


def allowed() -> bool:
    return (os.getenv("EXTERNAL_WRITES") or "on").strip().lower() not in OFF


def dsp_is_read(method: str) -> bool:
    """Методы DSP вида «Сущность.действие»: чтение — `get…` (getInfo, getPeriod, getUploadFileUrl)."""
    return method.split(".", 1)[-1].startswith("get")
