# -*- coding: utf-8 -*-
"""Время: в базе UTC, человеку — Москва.

Правило родилось из замера 14.09.2026, а не из вкуса. Измерено:

    контейнер            UTC          (TZ не задана ни у одного сервиса)
    postgres now()       UTC          `2026-09-14 19:28:06+00`
    настенные часы       UTC+3        22:28

Значит `datetime.utcnow()`, `func.now()` и всё, что лежит в колонках — UTC. Пока числа
только сравниваются между собой, это незаметно; ошибка появляется там, где время
ПОКАЗЫВАЮТ человеку или сравнивают с ЧАСОМ СУТОК.

Два уже случившихся случая:

* в шапке письма стояло `datetime.now()` — получатель в Москве видел время на три часа
  в прошлом, причём выглядело оно правдоподобно и потому не вызывало вопросов;
* тихие часы площадок (21:00–09:00) считались от UTC, то есть по факту работали с 00:00
  до 12:00 по Москве. Письмо в 23:00 уходило ночью — ровно то, ради чего тихие часы и
  заведены, — а утреннее ждало до полудня.

Здесь одна точка перевода. Обратного (Москва → UTC) намеренно нет: в базу пишется то,
что вернул `utcnow()`, и заводить второй путь значит однажды ошибиться знаком.

ДОПОЛНЕНО 23.09.2026. Замер выше остаётся верным для БАЗЫ и был верен для процесса до
этой даты. С 23.09 сам процесс бэкенда переведён в Москву (`set_process_timezone`,
зовётся первой строкой `main.py`) — потому что перевод выше чинил только те места, где
о нём вспомнили, а «сегодня» (`date.today()`) им не пользовалось нигде. База при этом
осталась в UTC намеренно, см. объяснение у самой функции.
"""
from __future__ import annotations

import os
import time
from datetime import datetime, timedelta

# Наш часовой пояс. Не `ZoneInfo('Europe/Moscow')`: у Москвы с 2014 года нет перехода на
# летнее время, смещение постоянное, а зависимость от базы часовых поясов в контейнере
# добавила бы способ сломаться там, где ломаться нечему.
MSK_OFFSET = 3


def to_msk(dt: datetime) -> datetime:
    """UTC → Москва. Наивная дата на входе, наивная на выходе — как всё в этой базе."""
    return dt + timedelta(hours=MSK_OFFSET)


def msk_now() -> datetime:
    """Сейчас по Москве. Для показа человеку: в шапке письма, в подписи документа."""
    return to_msk(datetime.utcnow())


def set_process_timezone(name: str = "Europe/Moscow") -> None:
    """Поставить процессу МОСКОВСКИЙ пояс. Зовётся первой строкой при старте.

    ЗАЧЕМ. Перевод `to_msk` чинит только те места, где о нём вспомнили. А есть третий
    вид времени, который никто не переводит, потому что он и не выглядит временем:
    `date.today()` — «сегодня». В контейнере без пояса это сегодня ПО ГРИНВИЧУ, то есть
    с 00:00 до 03:00 по Москве система считает, что ещё вчера. На 23.09.2026 таких мест
    тридцать шесть: срочность задач, просрочка бэклога, границы флайта, дата
    подтверждения приложения к договору, имя выгружаемого файла.

    Ошибка живёт ровно три часа в сутки и всегда правдоподобна: дата настоящая, просто
    вчерашняя. Днём её воспроизвести нельзя — поэтому она и не находилась.

    Сюда же попадают ЖУРНАЛЫ: `%(asctime)s` берёт местное время процесса, и строки в
    `backend.log` и в `docker logs` шли на три часа позади настенных часов.

    ЧЕГО ЭТО НЕ ТРОГАЕТ — и ради чего сделано именно так:

      · `datetime.utcnow()` пояса не знает вовсе и остаётся UTC. Значит всё, что лежит
        в колонках, как лежало в UTC, так и лежит;
      · `now()` у postgres считает СЕРВЕР БАЗЫ, а не этот процесс. Семьдесят три колонки
        заполняются им, остальные — `utcnow()`. Обе половины в UTC, и они не разъезжаются.

    Поэтому пояс базы НЕ меняется: сдвинув его, мы получили бы одну колонку, где часть
    строк московская, а часть гринвичская, — и разделить их задним числом было бы нечем.

    `datetime.now()` после этого станет московским. В коде его нет ни одного (проверено
    23.09.2026, встречается только в комментариях) — иначе он писал бы в базу московское
    время рядом с гринвичским, то есть ровно ту беду, которой здесь избегают. Прибор
    `tests/test_timez.py` держит оба утверждения.
    """
    os.environ["TZ"] = name
    # tzset есть только на Unix. Контейнеры Linux, но разработка идёт на Windows, и
    # падать при импорте из-за пояса — хуже, чем остаться в поясе машины.
    if hasattr(time, "tzset"):
        time.tzset()
