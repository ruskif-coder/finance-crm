"""Арифметика СТРОКИ медиаплана — одна на всех потребителей.

Две величины строки считаются в проекте больше чем в одном месте, и обе уже разъехались:

**Сумма.** `volume × цена × (1 − скидка)`, делённое на 1000 ТОЛЬКО для CPM. Ветка «CPM или
нет» правильно написана в конструкторе, в `_row_net`, в формуле Excel и в годовом плане —
и отсутствовала в приложении к договору (`sales/annex.py`) и в сборке рекламной кампании
(`app/ad/build.py`): там стояло безусловное `/1000`. Для строки «Polza · Фикс · 1 ед ×
80 000» это давало **80 ₽ вместо 80 000** — в документе, который подписывает клиент.

**Показы.** Весь прогнозный слой считал `показы = volume`. Для CPM это верно (объём и есть
показы), для Фикс и Пакета в этой колонке лежат ШТУКИ закупки, а для CPC — клики. Одна
строка Polza давала «1 показ», охват 0,25 и CPM 80 000 000 ₽. Годовая выгрузка про эту
двусмысленность знала и суммировала показы только по CPM (`year_mp_export`) — остальные
потребители нет.

Решение (владелец 08.09.2026): **показы — собственное поле прогноза**, а не производная от
объёма. Лежит в `forecast.imp`, вводится аккаунтом и его ответственность. Объём у Фикса
привязан к СДЕЛКЕ, а не к услуге: сумма пакета меняется от сделки к сделке, поэтому
подставлять значение из справочника нечего.

Для CPM поле не нужно и не спрашивается: там показы гарантированы договором и равны
объёму — разрешить править их отдельно значило бы разрешить им разойтись с суммой.
"""
from typing import Any, Optional


def is_cpm(model: Any) -> bool:
    """Модель закупки — CPM?

    Сравнение регистронезависимое и с обрезкой пробелов: справочник услуг заполняется
    руками, и «cpm» вместо «CPM» дало бы объём×цену вместо объём/1000×цены — ошибку
    в тысячу раз, причём молча.

    Осторожно: значение приходит из ДВУХ источников с разным написанием. Справочник услуг
    хранит `calc_form` по-русски («Фикс», «Пакет»), конструктор МП пишет в строку латиницу
    (`MODELS = ['CPM','CPC','Fix']`). Для этой функции разницы нет — не-CPM и там и там.
    """
    return (model or "").strip().upper() == "CPM"


def num(v, default=0.0):
    """Число из поля прогноза. Десятичная ЗАПЯТАЯ — обычный ввод, а не ошибка.

    Замерено 08.09.2026: из 42 строк с прогнозом запятая стоит в 19 значениях CTR и в 2
    значениях CR — конструктор пишет ровно то, что набрал человек, а `parseN` во фронте
    запятую понимает. Бэкенд не понимал: `float("0,8")` кидает ValueError, и в клиентский
    Excel и в PDF уезжали пустые CTR, клики, CPC, CR, чеки, CPO, доход и ROI — при том что
    на экране конструктора все эти числа стояли. Расхождение тихое: оба вида правдивы
    по отдельности.
    """
    if v in (None, ""):
        return default
    try:
        return float(str(v).replace(",", ".").replace(" ", "").replace(" ", ""))
    except (TypeError, ValueError):
        return default


def _f(v) -> float:
    return num(v)


def row_net(model, volume, unit_price, discount=0) -> float:
    """Бюджет строки до НДС. Единственная формула на все документы и витрины."""
    div = 1000.0 if is_cpm(model) else 1.0
    return round(_f(volume) * _f(unit_price) * (1 - _f(discount)) / div)


def row_imp(model, volume, forecast: Optional[dict] = None) -> float:
    """Прогнозные показы строки.

    Порядок: сначала ручной ввод аккаунта (`forecast.imp`), потом — объём, но ТОЛЬКО для
    CPM. Для остальных моделей без ручного ввода показов нет, и это ноль, а не объём:
    пустая ячейка честно говорит «не заполнено», а «1 показ» выглядит как расчёт.

    CPC сюда попадает вместе с Фиксом сознательно: там в объёме лежат КЛИКИ, и подстановка
    их в показы давала бы `клики = клики × CTR`. Активных CPC-услуг сегодня нет, но правило
    должно быть верным до того, как они появятся, а не после.
    """
    f = forecast or {}
    v = f.get("imp")
    if v not in (None, ""):
        return num(v)
    return num(volume) if is_cpm(model) else 0.0
