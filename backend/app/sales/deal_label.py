# -*- coding: utf-8 -*-
"""Как сделка называется в уведомлении. ОДНА функция на все места.

Разбор 14.09.2026 показал расхождение: у событий креативов в заголовке стоял только код
(«Комплект №3 · 7E2JWE»), у событий воронки — только имя («Сделка ушла в бронь:
Эспумизан 09»), у очереди сделок — имя с услугой, а у медиапланов код прятался в тексте.
Человеку нужно и то и другое: по имени он узнаёт сделку, по коду — находит её в реестре и
называет коллеге. Видел он одно из двух, и какое именно — зависело от того, какое событие
сработало.

ПОРЯДОК: код первым. Это то же правило, что владелец задал для заголовка вкладки карточки
сделки 13.09.2026 («в сделку первой ставь ID»), и второго порядка для одной и той же пары
заводить не надо.

ТОЛЬКО ВНУТРЕННИЙ КОНТУР. Наружу — в кабинет паблишера и в письма площадке — наш код
сделки не уходит (правило владельца 14.09.2026): площадка знает рекламодателя, бренд,
услугу и период, а нашим внутренним номером ей нечего делать. Представления `pub.*_v1`
кода не содержат вовсе; в письмах подстановка `{сделка}` подставляет имя, а без него —
бренд. Прибор на это стоит в `tests/test_cabinet_contract.py`.

Услуга сюда НЕ входит. Она нужна не всем событиям, и подставляет её тот, кому нужна, —
иначе каждое уведомление тащило бы третью часть ради двух правил из двадцати шести.
"""
from typing import Optional

SEP = " · "


def deal_label(deal, *, service: bool = False) -> str:
    """«7E2JWE · Эспумизан 09». С `service=True` добавляет услугу сделки.

    Замер на стенде 14.09.2026: код и имя заполнены у всех 920 сделок, то есть обычный
    случай — обе части. Запасные ветки нужны для сделок, рождённых мимо генератора кода
    (импорт, ручная вставка), и для объектов-заглушек в тестах.
    """
    code = (getattr(deal, "code", None) or "").strip()
    title = (getattr(deal, "title", None) or "").strip()
    head = code or f"#{getattr(deal, 'id', '?')}"
    parts = [head]
    if title:
        parts.append(title)
    if service:
        product = _service_name(deal)
        if product:
            parts.append(product)
    return SEP.join(parts)


def _service_name(deal) -> Optional[str]:
    """Услуга подписью — из `product`, сырой строки, а НЕ из справочника по `service_id`.

    Справочник точнее, но за именем пришлось бы ходить по связи, и на прогоне сканера это
    запрос на каждую сделку: сработок бывает больше сотни. Подпись такой цены не стоит.
    Там, где важна именно услуга как сущность, её читают через `service_id` (разметка
    требований к стадиям), а здесь нужно слово рядом с именем сделки.
    """
    return (getattr(deal, "product", None) or "").strip() or None
