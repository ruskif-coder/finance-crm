"""Цвет услуги — один источник для всех экранов.

Зачем на бэкенде, а не в JS: маркер услуги нужен дашборду аккаунта, реестру сделок и
медиаплану. Посчитай его в каждом месте по-своему — и одна услуга окажется зелёной на
одном экране и синей на другом; ровно так уже разъехались BANK_COLORS, переопределённые
в трёх файлах. Здесь цвет решается один раз и отдаётся готовым.

NULL в sales_services.color означает «авто», а не «нет цвета»: маркер должен быть
осмысленным сразу после миграции, до того как кто-то откроет справочник.
"""
import hashlib

# Палитра раздела продаж: холодные и тёплые тона из globals.css плюс несколько
# производных. Именно палитра, а не свободный hex — выбор в интерфейсе идёт из этого
# списка, иначе через год в справочнике будет сорок оттенков серого.
# Порядок важен: он же порядок в пикере.
PALETTE = [
    "#2FA37C",  # зелёный (income)
    "#4F6CE6",  # синий (accent)
    "#7B62D6",  # фиолетовый
    "#E89020",  # оранжевый
    "#C93A3E",  # красный
    "#2FB8A8",  # бирюзовый
    "#8B7BE8",  # лавандовый
    "#D9548F",  # розовый
    "#5B8C2A",  # оливковый
    "#B26A0C",  # коричнево-жёлтый
    "#3A7CA5",  # стальной
    "#8B93A6",  # серый (нейтральная услуга)
]


def auto_color(name: str) -> str:
    """Стабильный цвет по имени услуги.

    md5, а не hash(): встроенный hash в Python рандомизирован между процессами
    (PYTHONHASHSEED), и цвет менялся бы при каждом рестарте бэкенда.
    """
    if not name:
        return PALETTE[-1]
    h = hashlib.md5(name.strip().lower().encode("utf-8")).hexdigest()
    return PALETTE[int(h[:8], 16) % len(PALETTE)]


# Функции color_of(name, explicit) здесь СОЗНАТЕЛЬНО нет. Она была второй реализацией
# «итогового цвета» и считала авто-цвет хешем от имени, тогда как справочник, реестр и
# дашборд берут цвет из service_color_map (раскладка по порядку). Две реализации давали
# бы одной услуге разный цвет на разных экранах — ровно то, от чего этот модуль защищает.
# Нужен цвет — берите service_color_map(db); имени нет в справочнике — auto_color(name).


def service_color_map(db) -> dict:
    """{имя услуги: цвет} по всему справочнику.

    Ключ — ИМЯ, а не id: в сделке услуга хранится строкой (SalesDeal.product), связи со
    справочником у неё нет. Поэтому же на неизвестное имя (услуга удалена или пришла
    из Битрикса не сматченной) вызывающий код падает на auto_color — маркер должен быть
    у любой строки.

    Авто-цвета раздаются ПО ПОРЯДКУ справочника, а не хешем от имени: хеш на 12 цветов
    честно, но бесполезно — на первых же 16 услугах еФарм, Приоритезация и Клик-аут
    получили один зелёный, и маркер перестал различать. По порядку столкновение
    начинается только с 13-й услуги, и то предсказуемо.
    """
    from app.sales.models import SalesService
    rows = (db.query(SalesService.name, SalesService.color)
            .order_by(SalesService.sort_order, SalesService.name).all())
    out, i = {}, 0
    for name, explicit in rows:
        explicit = (explicit or "").strip()
        if explicit.startswith("#"):
            out[name] = explicit          # заданный руками не занимает место в раскладке
        else:
            out[name] = PALETTE[i % len(PALETTE)]
            i += 1
    return out
