"""
Хеш полезной нагрузки для append-only слоя сырья.

Слой сырья append-only: версия пишется, только если изменился хеш полезной
нагрузки. Это не микрооптимизация — суммы в сделке правятся на фактические
в момент закрытия, и без истории версий план-факт с прогнозом невозможен:
сравнивать будет не с чем.

До 03.10.2026 здесь же жили правила синхронизации с Битрикс24 (импорт сделок,
сопоставление справочников, сверка воронок). Битрикс больше не источник —
правила удалены вместе с тестами, остался только хеш.
"""
import hashlib
import json


def payload_hash(payload: dict) -> str:
    """Стабильный хеш полезной нагрузки.

    На нём держится append-only слой сырья: новая версия пишется, только когда
    хеш изменился. Порядок ключей на результат не влияет — иначе каждая
    синхронизация плодила бы версии на ровном месте.

    Переехал сюда 30.08.2026 из удалённого клиента Битрикса: хеш к транспорту
    отношения не имеет — он про правило хранения. Нужен загрузчику
    `scripts/load_sales_from_xlsm.py`.
    """
    canonical = json.dumps(payload, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()
