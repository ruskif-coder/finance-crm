# -*- coding: utf-8 -*-
"""Сумма прописью для документов.

В приложении к договору это **юридически значимый текст**: «732 000 (Семьсот тридцать две
тысячи) рублей 00 копеек, в том числе НДС 22% — 132 000 (Сто тридцать две тысячи) рублей
00 копеек». Цифра и пропись обязаны совпадать всегда, поэтому пишутся одной функцией из
одного числа, а не собираются в шаблоне.

Форма взята из живого образца (Приложение № 68 от 01.06.2026): копейки цифрами, а не
словами; пропись в скобках после числа; первая буква заглавная.

Три рода, которые здесь важны и в которых легко ошибиться:
  · тысяча — женский: «одна тысяча», «две тысячи»;
  · миллион и миллиард — мужской: «один миллион», «два миллиона»;
  · рубль — мужской, копейка — женский (в форме с копейками словами, если понадобится).
"""
from typing import Tuple

ONES_M = ("", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
ONES_F = ("", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять")
TEENS = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")
TENS = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
        "семьдесят", "восемьдесят", "девяносто")
HUNDREDS = ("", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
            "семьсот", "восемьсот", "девятьсот")

# Разряды: (формы слова, род). Род нужен только для единиц разряда: «две тысячи», но
# «два миллиона».
SCALES = (
    (("", "", ""), "m"),                                   # единицы — само число
    (("тысяча", "тысячи", "тысяч"), "f"),
    (("миллион", "миллиона", "миллионов"), "m"),
    (("миллиард", "миллиарда", "миллиардов"), "m"),
    (("триллион", "триллиона", "триллионов"), "m"),
)


def plural(n: int, forms: Tuple[str, str, str]) -> str:
    """Форма слова по числу: 1 рубль, 2 рубля, 5 рублей.

    Правило русского счёта: 11–14 всегда третья форма, дальше по последней цифре.
    """
    n = abs(n) % 100
    if 11 <= n <= 14:
        return forms[2]
    last = n % 10
    if last == 1:
        return forms[0]
    if 2 <= last <= 4:
        return forms[1]
    return forms[2]


def _triple(n: int, female: bool) -> list:
    """Одна группа из трёх цифр словами. 0 даёт пустой список — «ноль» ставит вызывающий."""
    out = []
    if n >= 100:
        out.append(HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(TEENS[n - 10])
        return out
    if n >= 20:
        out.append(TENS[n // 10])
        n %= 10
    if n:
        out.append((ONES_F if female else ONES_M)[n])
    return out


def in_words(n: int) -> str:
    """Целое число прописью, с маленькой буквы. Ноль — «ноль»."""
    n = int(n)
    if n == 0:
        return "ноль"
    sign = "минус " if n < 0 else ""
    n = abs(n)

    groups = []
    while n:
        groups.append(n % 1000)
        n //= 1000

    parts = []
    for i in range(len(groups) - 1, -1, -1):
        g = groups[i]
        if not g:
            continue
        forms, gender = SCALES[i]
        parts += _triple(g, female=(gender == "f"))
        if forms[0]:
            parts.append(plural(g, forms))
    return sign + " ".join(p for p in parts if p)


def split_kopecks(amount) -> Tuple[int, int]:
    """Сумма → (рубли, копейки). Округление банковское не нужно: в документе стоит ровно
    то, что в счёте, а счёт считается до копейки."""
    cents = int(round(float(amount) * 100))
    return cents // 100, abs(cents) % 100


def rub_phrase(amount) -> str:
    """«732 000 (Семьсот тридцать две тысячи) рублей 00 копеек» — как в образце.

    Первая буква прописи заглавная: она открывает скобку в середине предложения, и в
    договорах это устоявшаяся форма.
    """
    rub, kop = split_kopecks(amount)
    words = in_words(rub)
    words = words[:1].upper() + words[1:]
    digits = f"{rub:,}".replace(",", " ")     # неразрывный пробел: 732 000
    return (f"{digits} ({words}) {plural(rub, ('рубль', 'рубля', 'рублей'))} "
            f"{kop:02d} {plural(kop, ('копейка', 'копейки', 'копеек'))}")


def vat_of(gross, rate) -> float:
    """НДС, выделенный ИЗ суммы с налогом.

    Проверено на образце: 732 000 при ставке 22 % дают ровно 132 000 — это 22 % от
    600 000 без налога, а не 22 % от общей суммы. Формула `сумма × ставка / (100 + ставка)`
    даёт то же число и не требует знать сумму без налога.
    """
    if not gross or not rate:
        return 0.0
    return round(float(gross) * float(rate) / (100.0 + float(rate)), 2)
