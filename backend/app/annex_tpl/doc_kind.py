# -*- coding: utf-8 -*-
"""Каким словом документ себя называет: «Приложение» или «Доп. соглашение».

Решения владельца 31.10.2026.

**Тумблер у ДОГОВОРА** (`contracts.annex_word`), а не у контрагента: историческое название
тянется за договором, а у контрагента договоров может быть несколько, и у них бывают
разные названия. Пусто = «приложение» — так печатаются все 185 договоров сегодня, и
выкладка не должна молча их переименовать.

**В интерфейсе «ДС», в тексте документа «Доп. соглашение».** Поэтому форм четыре, а не
три: `ui` — для наших экранов (кнопка «ДС договора», окно «Шаблон ДС» уже так и названы),
остальные три — для документа. Номер печатается ВНУТРИ документа, значит он идёт полной
формой: «Доп. соглашение № 68», сокращения в документе нет.

**Формы заданы явно, склонения на ходу нет.** Слово стоит в трёх падежах («Приложение
№ 68», «настоящего Приложения», «согласно Доп. соглашению»), вариантов всего два, и
`rugram.py` незнакомое намеренно не угадывает. Шесть строк здесь надёжнее угадывания, и
их видно глазами.

**Формы НЕ выносятся в настройки** (владелец: «чтобы ещё и за этим не следить»). Тумблер
переключает их сам.

Почему слово стало подстановкой, а не осталось флагом: до этой правки оно было вшито в
тексты по умолчанию, причём непоследовательно — пункт 1 называл документ «Приложением», а
основание закрывающих в том же документе «Доп.соглашению». Флаг не изменил бы ни одной
такой строки, и тумблер выглядел бы сломанным.
"""
import re
from typing import Optional

DEFAULT = "приложение"

KINDS = {
    "приложение": {"ui": "Приложение",
                   "nom": "Приложение", "gen": "Приложения", "dat": "Приложению",
                   "ins": "Приложением", "pl_ins": "Приложениями"},
    "дс":         {"ui": "ДС",
                   "nom": "Доп. соглашение", "gen": "Доп. соглашения", "dat": "Доп. соглашению",
                   "ins": "Доп. соглашением", "pl_ins": "Доп. соглашениями"},
}
# `ins` / `pl_ins` (творительный) нужны странице печати PDF: «руководствуются … настоящим
# Приложением», «отдельными Доп. соглашениями к Договору» (ревью 31.10.2026).

# Что показывать в тумблере на экране договора. Порядок — как у владельца в задаче.
CHOICES = [{"value": k, "label": v["ui"]} for k, v in KINDS.items()]


def kind_of(value: Optional[str]) -> str:
    """Значение колонки → вид. Пусто и незнакомое → умолчание.

    Колонка текстовая, и опечатка в неё когда-нибудь попадёт. Падать здесь нельзя:
    документ нужен как раз в плохую минуту.
    """
    v = (value or "").strip().lower()
    return v if v in KINDS else DEFAULT


def forms(kind: Optional[str]) -> dict:
    return KINDS[kind_of(kind)]


def number_text(kind: Optional[str], no_text) -> str:
    """Как печатается номер В ДОКУМЕНТЕ: «Доп. соглашение № 68» / «Приложение № 68».

    Сокращение «ДС» сюда не попадает намеренно — оно только для наших экранов.
    """
    return f"{forms(kind)['nom']} № {no_text}"


def values(kind: Optional[str]) -> dict:
    """Подстановки вида документа для сборки текста пунктов."""
    f = forms(kind)
    return {"вид_документа": f["nom"], "вид_документа_род": f["gen"], "вид_документа_дат": f["dat"]}


# ── «Синхронизировать» (владелец 31.10.2026): одно слово на весь документ ────────
#
# В образце владельца 14.10 заголовок был «Приложение № 68», а основание УПД — «согласно
# Доп.соглашению»: один документ называл себя двумя словами. Владелец: «синхронизировать
# надо». Документ называет себя в ПЯТИ местах, и все пять берут слово отсюда:
#   * номер и тексты пунктов конструктора (`assemble.py`);
#   * файл DOCX (`sales/annex_docx.py`), включая страницу основания;
#   * номер, записанный при подтверждении ДС (`routers/annexes.py`);
#   * номер в предпросмотре (`sales/annex.py`).

# Так слово стоит в старых текстах — шаблонах и пунктах, вшитых в код.
SOURCE_STEM = "Приложени"
STEMS = {"приложение": "Приложени", "дс": "Доп. соглашени"}


def resolve(explicit: Optional[str] = None, contract_word: Optional[str] = None,
            is_master: bool = False) -> str:
    """Вид документа: зафиксированный при выпуске → тумблер договора → у мастер-сделки «дс» →
    «приложение».

    Мастер-сделка по умолчанию — доп. соглашение: решение владельца 15.10.2026 («ДС
    мастер-сделки называются ДС») не отменено, его просто перестали писать сокращением.
    Тумблер договора, если задан, важнее. Незнакомое значение — как не заданное.
    """
    for v in (explicit, contract_word):
        v = (v or "").strip().lower()
        if v in KINDS:
            return v
    return "дс" if is_master else DEFAULT


def rebrand(text: Optional[str], kind: Optional[str]) -> Optional[str]:
    """Слово документа в старом тексте — в вид документа, в том же падеже и числе.

    Работает ОСНОВОЙ: «Приложение» и «Доп. соглашение» — оба среднего рода на -ение и
    склоняются одинаково («настоящего Приложения» → «настоящего Доп. соглашения»,
    «отдельными Приложениями» → «отдельными Доп. соглашениями»). Допущение держит прибор
    `test_every_case_of_the_old_word_follows_the_kind`.

    Только с ЗАГЛАВНОЙ: документ в текстах пишется с заглавной, а «мобильное приложение»
    (услуга еФарм · APP) — со строчной. Переписать название услуги в договоре было бы
    хуже, чем не переписать слово документа.
    """
    k = kind_of(kind)
    if not text or k == DEFAULT:
        return text
    return text.replace(SOURCE_STEM, STEMS[k])


_NUMBER_WORD = re.compile(r"^\s*(?:Доп\.\s*соглашение|Приложение|ДС)(?=\s*№)")


def renumber(number_text: Optional[str], kind: Optional[str]) -> Optional[str]:
    """Слово перед номером — по виду документа: «Доп. соглашение № 12» → «Приложение № 12».

    Номер один и от вида не зависит (владелец 31.10.2026); меняется только слово. Нужно потому, что
    номер в печати собирается заново по ТЕКУЩЕМУ тумблеру договора, а вид подписанного документа
    зафиксирован (ревью 31.10.2026). Старая сокращённая форма «ДС № 7» мастер-сделок — туда же.
    Текст без слова документа впереди не трогается.
    """
    if not number_text:
        return number_text
    return _NUMBER_WORD.sub(forms(kind)["nom"], number_text, count=1)


def to_dative(number_text: Optional[str], kind: Optional[str]) -> str:
    """«Доп. соглашение № 7» → «Доп. соглашению № 7» — для «К … к Договору».

    Прежде дательный получали заменой строки «Приложение» → «Приложению». С полной формой
    «Доп. соглашение» это давало «К Доп. соглашение № 7» — неверный падеж.
    """
    f = forms(kind)
    s = number_text or f["nom"]
    return s.replace(f["nom"], f["dat"], 1)


# ── Выбор вида по договору: ОДИН раз, дальше — только администратор (владелец 31.10.2026) ──
#
# «Фиксировать в базе — правки только для меня»: вид выбирается при первой сборке ДС, вместе со стартовым номером, и
# дальше меняется только администратором (администратор в системе один — владелец). Правило ОДНО на все места, откуда
# вид можно поменять: панель сборки мастер-сделки, тумблер в карточке договора, правка договора. Иначе запрет в одном
# месте обходился бы через другое.

def normalize_word(word: Optional[str]) -> Optional[str]:
    """Пусто → None (не выбран), иначе вид из KINDS. Незнакомое — ValueError: молча свести к умолчанию было бы удобно, но
    тогда опечатка выглядела бы как сохранённый выбор."""
    v = (word or "").strip().lower()
    if not v:
        return None
    if v not in KINDS:
        raise ValueError("Вид ДС: «приложение» или «дс»")
    return v


def _is_admin(user) -> bool:
    return getattr(getattr(user, "role", None), "key", None) == "admin"


def check_change(old: Optional[str], new: Optional[str], user) -> None:
    """Можно ли сменить вид. Не выбран — может тот, кто собирает (это и есть первичный выбор). Выбран — только
    администратор; тот же вид ещё раз изменением не считается (сохранение панели со стартовым номером не падает)."""
    if old and new != old and not _is_admin(user):
        raise PermissionError("Вид документа по договору уже выбран — изменить может только администратор")


def assign(contract, word: Optional[str], user) -> Optional[str]:
    """Проверить и записать вид договора. Ошибки — `ValueError` (незнакомый вид) и `PermissionError` (запрет);
    в HTTP их переводит ручка. Значение не меняется, пока проверка не прошла."""
    new = normalize_word(word)
    check_change(getattr(contract, "annex_word", None), new, user)
    contract.annex_word = new
    return new
