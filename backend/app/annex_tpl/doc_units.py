"""Подстановка `{единицы_сделки}` — единицы закупки и объёмы строк документа (владелец 26.11.2026).

Владелец: «нужна новая переменная — единицы сделки — по ним подставляем объёмы закупки». Форма — «показы —
1 361 948», несколько единиц через «; ». Решения того же дня: в основании УПД печатается объём СВОЕЙ УПД, у
доп. услуги штуки считаются как сумма ÷ цена, бонусная услуга в фразу не попадает и выгрузку не блокирует.

Источник — строки самого документа, те же, что в таблице МП: число берётся тем же форматом, что колонка
«Объём» (`table_cols._int`), а слово единицы — тем же правилом, что колонка «Единица измерения»
(`table_cols.unit_of`). Поэтому текст и таблица разойтись не могут, и второй копии правил здесь нет.
"""
from app.annex_tpl import table_cols as TC

# Порядок единиц постоянный, а не «как строки легли в документ»: иначе у двух ДС одного состава фраза читалась
# бы по-разному, а разница в ней — только числа.
ORDER = ("показы", "клики", "штуки")


def volume_of(r: dict):
    """Объём строки в её единице. У доп. услуги в старых снимках ДС объёма нет — он равен сумме ÷ цене
    (30 000 ₽ по 30 000 ₽ — одна штука); у бонуса объёма нет вовсе. Нет объёма — None."""
    vol = r.get("volume")
    if vol not in (None, ""):
        return float(vol)
    if r.get("kind") == "extra" and not r.get("bonus"):
        price = float(r.get("unit_price") or 0)
        amount = float(r.get("amount") or 0)
        if price and amount:
            return round(amount / price)
    return None


def phrase(rows) -> str:
    """«показы — 1 361 948; штуки — 1». Скидка объёма не несёт; бонус — тоже (прочерк в таблице). Пусто —
    пустая строка: тег объявлен необязательным (`subs.SUBS["единицы_сделки"]["optional"]`), печать не запирает."""
    acc = {}
    for r in rows or []:
        if r.get("kind") == "discount" or r.get("bonus"):
            continue
        vol = volume_of(r)
        if not vol:
            continue
        unit = TC.unit_of(r)
        acc[unit] = acc.get(unit, 0) + vol
    parts = [f"{u} — {TC._int(acc[u])}" for u in ORDER if acc.get(u)]
    # Единица, которой нет в списке (справочник услуг завёл новую), — в конце как есть: потерять её молча хуже,
    # чем показать не в привычном порядке.
    parts += [f"{u} — {TC._int(acc[u])}" for u in acc if u not in ORDER and acc[u]]
    return "; ".join(parts)
