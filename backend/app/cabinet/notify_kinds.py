# -*- coding: utf-8 -*-
"""Виды уведомлений, которые получает площадка. Справочник живёт в КОДЕ.

Не таблицей и не внешним ключом: набор меняется вместе с экранами кабинета, а не с
данными, и справочник в базе пришлось бы синхронизировать миграцией при каждом новом
экране. Опечатку ловит прибор (`tests/test_cabinet_mute.py`), а не констрейнт.

Профиль рассылки паблишера ЖЁСТКО ЗАДАН — набор один на всех, бот наш. Площадка не
собирает подписку с нуля, она только выключает лишнее: строка в `cabinet_account_mute`
означает «выключено», её отсутствие — «включено».

`can_mute=False` — вид, который выключить нельзя. Такой ровно один, и это осознанное
исключение, а не забытая настройка: молчание перед стартом стоит сорванного запуска, а
цена лишнего сообщения — раздражение. Разменивать одно на другое площадка не должна.
"""
from dataclasses import dataclass
from typing import Tuple


@dataclass(frozen=True)
class NotifyKind:
    key: str
    label: str
    hint: str
    can_mute: bool = True


KINDS: Tuple[NotifyKind, ...] = (
    NotifyKind(
        key="новый креатив",
        label="Новый креатив на согласование",
        hint="Материал прошёл нашу проверку и ждёт вашего ответа.",
    ),
    NotifyKind(
        key="запрос ссылки",
        label="Запрос посадочной страницы",
        hint="Мы просим ссылку, на которую поведёт баннер. Без неё согласовать нельзя.",
    ),
    NotifyKind(
        key="сверка",
        label="Сверка объёма за месяц",
        hint="Итоги месяца: сколько показов мы насчитали и совпадает ли с вашими.",
    ),
    NotifyKind(
        key="продление",
        label="Запрос на продление кампании",
        hint="Кампания заканчивается, спрашиваем, продолжаем ли.",
    ),
    NotifyKind(
        key="старт близко",
        label="Старт близко, ответа нет",
        hint="Размещение вот-вот должно идти, а решения по креативу ещё нет. "
             "Выключить нельзя: пропущенное здесь означает сорванный запуск.",
        can_mute=False,
    ),
)

KIND_KEYS = tuple(k.key for k in KINDS)
MUTABLE_KEYS = tuple(k.key for k in KINDS if k.can_mute)
