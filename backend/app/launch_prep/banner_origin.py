"""Кто сделал баннер (владелец 27.09.2026) — одно правило на карточку сделки и конвейер.

«наш» — баннер собрали мы, он изначально подогнан под наш код и адаптацию.
«рекламодатель» — баннер прислал клиент: может быть кривым и с ошибками, поэтому трафик
видит на креативе плашку «проверьте внимательнее». Шага подтверждения нет — только плашка.

Поле живёт у файла (`LaunchPrepCreativeFile.origin`), признак креатива выводится здесь:
креатив от рекламодателя, если ХОТЬ ОДИН его файл от рекламодателя. Две копии этого
условия в двух роутерах однажды показали бы трафику и аккаунту разное.
"""
OURS = "наш"
ADVERTISER = "рекламодатель"
ORIGINS = (OURS, ADVERTISER)


def from_advertiser(files) -> bool:
    return any(getattr(f, "origin", None) == ADVERTISER for f in files)
