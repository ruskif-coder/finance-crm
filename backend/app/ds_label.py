# -*- coding: utf-8 -*-
"""Короткий номер ДС / приложения в СИСТЕМЕ: «ДС № 12», «ПР № 64» — ПРАВИЛО (владелец 18.11.2026: «в документах пишем полностью,
в системе экономим место»; «надо как правило ввести»). Формат — решение 09.11.2026 («ДС №, ПР №»).

Одна формула на сервер; её двойник на экранах — `frontend/lib/annexNumber.js` (одни и те же примеры в
tests/test_ds_label.py и lib/annexNumber.test.mjs — разойдутся, упадёт один из них).

Где применяется:
  · `Operation.ds_num` хранится коротким (валидатор модели): форма, массовая правка, импорт и мост мастер-сделки пишут его
    в любом написании — `доп.12`, «Дополнительное соглашение № 12», `прил 64` — а в базе одно `ДС № 12` / `ПР № 64`;
  · импорт приводит номер из файла ДО сверки — иначе `доп.12` в файле не нашёл бы `ДС № 12` в базе;
  · выгрузки и имена файлов.
Где НЕ применяется: сам документ (ворд/PDF ДС, УПД, письма) — там вид документа словом, как его печатает `annex_tpl/doc_kind`.

Сокращается, только если после слова идёт номер (цифра): «доплата июль», «заявка 3», «пени», голое число — как есть,
вид документа из такой записи не понять.
"""
import re
from typing import Optional

_DS = re.compile(r"^\s*(?:дополнительное\s+соглашение|доп\.?\s*соглашение|доп\.?\s*согл\.?|доп\.?|д/?с)\s*[.№#]*\s*(?=\d)", re.I)
_PR = re.compile(r"^\s*(?:приложение|прилож\.?|прил\.?|пр\.?)\s*[.№#]*\s*(?=\d)", re.I)


def short(number: Optional[str]) -> Optional[str]:
    """«доп.12» / «Дополнительное соглашение №12» → «ДС № 12»; «прил 64» / «Приложение № 64» → «ПР № 64»."""
    if not number:
        return number
    s = number.strip()
    for rx, word in ((_DS, "ДС № "), (_PR, "ПР № ")):
        m = rx.match(s)
        if m:
            return word + s[m.end():].strip()
    return s
