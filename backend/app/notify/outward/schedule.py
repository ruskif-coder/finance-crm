# -*- coding: utf-8 -*-
"""Когда письмо площадке уходит: тихие часы и дайджест.

Умолчания для паблишеров (владелец 14.09.2026):

    дайджест     09:00 по времени ПЛОЩАДКИ
    тихие часы   21:00 — 09:00

Это умолчания, а не жёсткое правило: у площадки может появиться свой час, и тогда
значения переедут в её карточку. Пока они здесь — в одном месте, а не в каждом
отправителе.

## Почему по времени площадки, а не по нашему

Письмо в 09:00 МСК приходит в Иркутске в 14:00, а в Калининграде в 08:00. Для внутреннего
контура это неважно — все в одном часовом поясе; для внешнего это разница между «письмо к
началу рабочего дня» и «письмо в обед». Смещение живёт в карточке площадки
(`sales_publishers.timezone_offset`).

**Замер 14.09.2026: смещение равно нулю у всех 41 площадки.** То есть сегодня «по времени
площадки» и «по Москве» — одно и то же, и различие начнёт работать, когда поле заполнят.
Писать код так, будто его нет, значило бы переделывать всё, как только появится первая
площадка за Уралом.

## Срочное сквозь тихие часы не идёт

И это отличие от внутреннего контура, где три события помечены `locked` и будят человека
ночью. Снаружи будить нельзя: площадка — не наш сотрудник, и ночное письмо от подрядчика
про чужую кампанию читается как невежливость, а не как забота. Срочное ждёт девяти утра —
но уходит ПЕРВЫМ, отдельным письмом, а не в общей пачке.
"""
from __future__ import annotations

from datetime import datetime, timedelta
from typing import Optional

from app.timez import MSK_OFFSET

# Умолчания. Меняются здесь, а не в отправителях.
DIGEST_HOUR = 9          # час дайджеста по времени площадки
QUIET_FROM = 21          # с 21:00
QUIET_TO = 9             # до 09:00

def publisher_now(now_utc: datetime, tz_offset: Optional[int]) -> datetime:
    """UTC → время площадки. `tz_offset` — смещение ОТ МОСКВЫ, как в карточке площадки.

    ДВА слагаемых, а не одно. До 14.09.2026 здесь стояло только смещение площадки, а в
    шапке файла было написано «время в базе московское» — утверждение неверное: и
    контейнер, и postgres живут в UTC (замер в `app/timez.py`). Для московской площадки
    это означало, что тихие часы 21:00–09:00 работали с 00:00 до 12:00: письмо в 23:00
    уходило ночью, а утреннее в 09:30 ждало до полудня.
    """
    return now_utc + timedelta(hours=MSK_OFFSET + int(tz_offset or 0))


def in_quiet_hours(local: datetime) -> bool:
    """Тихие часы 21:00–09:00 — интервал ЧЕРЕЗ ПОЛНОЧЬ, и сравнение здесь не такое, как
    у обычного диапазона: час 23 больше начала, час 3 меньше конца, и оба тихие."""
    h = local.hour
    return h >= QUIET_FROM or h < QUIET_TO


def due_at(now: datetime, tz_offset: Optional[int], *, immediate: bool) -> Optional[datetime]:
    """Когда отправлять. `None` — прямо сейчас.

    `immediate` — вид, объявленный срочным (`schedule='сразу'`). Он всё равно ждёт конца
    тихих часов, но не ждёт общего дайджеста: разница между «в 9 утра отдельным письмом»
    и «в 9 утра в общей пачке».

    Возвращается время В НАШЕЙ шкале — то, по которому живёт база и сравнивает досылка.
    Переводить туда-обратно в момент отправки значило бы делать это дважды и однажды
    ошибиться знаком.
    """
    local = publisher_now(now, tz_offset)
    if not in_quiet_hours(local):
        return None if immediate else None

    # Ближайшие DIGEST_HOUR по времени площадки: сегодня, если ещё не наступили, иначе
    # завтра. Час 23 → завтра, час 3 → сегодня утром: у интервала через полночь это
    # разные дни, и перепутать их значит задержать письмо на сутки.
    target = local.replace(hour=DIGEST_HOUR, minute=0, second=0, microsecond=0)
    if local.hour >= QUIET_FROM:
        target += timedelta(days=1)
    return target - timedelta(hours=MSK_OFFSET + int(tz_offset or 0))
