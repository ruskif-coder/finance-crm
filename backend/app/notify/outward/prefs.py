# -*- coding: utf-8 -*-
"""Что человек выбрал: матрица «событие × канал» и режим почты.

Отдельный модуль, потому что читателей у этих настроек ТРИ — отправка письма, отправка в
бот и экран кабинета, — и разойтись им нельзя. Пока правило «выключено ли» жило внутри
отправителя письма, бот отвечал на тот же вопрос своим запросом, а экран третьим.

## Умолчание — это ОТСУТСТВИЕ строки

Матрица хранит отклонения: нет строки — «как решили мы». Отсюда «Вернуть по умолчанию» на
экране — это удаление строк, а не проставление галочек, и новый вид уведомления
включается сам, не требуя бэкфилла всем учёткам.

Умолчание при этом НЕ ОДНО НА ВСЕ КЛЕТКИ: бот включён всегда, а из двух почтовых колонок
включена та, которую объявил каталог (`kind.schedule`) — срочный вид письмом сразу,
обычный в пачке. Поэтому читать матрицу голым словарём нельзя, только через `cell()`.

## Настройка на УЧЁТКЕ, а письмо КОНТАКТУ

Это не небрежность, а устройство контура: письма уходят контактам площадки с галочкой
«получает уведомления» (их 25 из 45), а настраивать может только тот, кто вошёл в
кабинет. Связь между ними прямая и единственная — `cabinet_account.contact_id`: учётка
растёт из контакта, это один человек с двух сторон.

Контакт БЕЗ учётки получает умолчания и получает их молча: настраивать ему негде, и
отказывать в письме на этом основании было бы худшим из решений — до 15.09.2026 именно
такие контакты и были единственными получателями.

**До 15.09.2026 правило было другим**: выключенным считалось то, что выключили ВСЕ учётки
кабинета сразу. Оно возникло из невозможности связать учётку с адресатом и давало
странность — один человек снимал галочку и не влиял ни на что. Теперь связь есть, и
правило стало прямым: каждый отвечает за свою почту.
"""
from __future__ import annotations

from typing import Dict, Tuple

from sqlalchemy import text
from sqlalchemy.orm import Session

# ТРИ СПОСОБА ДОСТАВКИ, и два из них — почта (владелец 15.09.2026, правка макета).
# «Почта» — письмо сразу, «дайджест» — то же письмо в утренней пачке. Панели в этом
# списке нет: у паблишера панели уведомлений не существует, лента кабинета — журнал
# действий, а не канал.
BOT, MAIL, DIGEST = 'бот', 'почта', 'дайджест'
CHANNELS = (BOT, MAIL, DIGEST)
MAIL_WAYS = (MAIL, DIGEST)          # взаимоисключающая пара

# ЧАСА ЗДЕСЬ НЕТ. Дайджест уходит в 09:00 по времени площадки, и час — константа
# `schedule.DIGEST_HOUR`, а не настройка человека (владелец 15.09.2026). Повторять её
# здесь значило бы завести второй ответ на тот же вопрос.


def off_accounts(db: Session, kind: str, channel: str) -> set:
    """Учётки, выключившие этот вид на этом канале."""
    rows = db.execute(text(
        "SELECT account_id FROM cabinet_account_notify "
        " WHERE kind = :k AND channel = :c AND NOT enabled"),
        {"k": kind, "c": channel}).fetchall()
    return {r[0] for r in rows}


def accounts_by_contact(db: Session, publisher_id: int) -> Dict[int, int]:
    """Контакт → учётка кабинета. Только активные: отключённая учётка не должна
    распоряжаться почтой человека, который ею больше не пользуется.

    Связь идёт ОТ КОНТАКТА, а не через `cabinet_publisher`. Разница не косметическая:
    служебный кабинет («все площадки») связей с площадками не хранит вовсе — видимость у
    него считается правилом, а не строками, — и join по ним терял его учётки молча.
    Замер 15.09.2026: на стенде это давало «настройки не применились» при верно
    заполненной таблице.

    Здесь этой связи и не нужно: контакт принадлежит площадке по построению, а настройки
    — свойство ЧЕЛОВЕКА, а не пары «человек × площадка».
    """
    rows = db.execute(text("""
        SELECT a.contact_id, a.id
          FROM cabinet_account a
          JOIN sales_publisher_contacts c ON c.id = a.contact_id
         WHERE c.publisher_id = :p AND a.is_active"""),
        {"p": publisher_id}).fetchall()
    return {r[0]: r[1] for r in rows}


def default_on(kind, channel: str) -> bool:
    """Умолчание клетки: что придёт человеку, который ничего не настраивал.

    У БОТА оно одно — «да». У почты умолчаний ДВА, и они противоположны: срочный вид
    приходит письмом сразу, обычный — пачкой. Берётся это не из отдельного списка, а из
    самого каталога (`kind.schedule`), где расписание объявлено вместе с видом: второй
    список умолчаний разошёлся бы с первым, и разошёлся бы молча.

    Из-за разных умолчаний в двух колонках хранить «отклонения» можно только вместе с
    этой функцией: пустая клетка означает не «выключено» и не «включено», а «как решили
    мы».
    """
    if channel == BOT:
        return True
    urgent = getattr(kind, 'schedule', 'дайджест') == 'сразу'
    return urgent if channel == MAIL else not urgent


def cell(db_matrix: Dict[Tuple[str, str], bool], kind, channel: str) -> bool:
    """Состояние клетки с учётом умолчания. `db_matrix` — то, что вернул `matrix`."""
    v = db_matrix.get((kind.key, channel))
    return default_on(kind, channel) if v is None else v


def matrix(db: Session, account_id: int) -> Dict[Tuple[str, str], bool]:
    """Все отклонения учётки — для экрана. Ключ `(вид, канал)`."""
    rows = db.execute(text(
        "SELECT kind, channel, enabled FROM cabinet_account_notify WHERE account_id = :a"),
        {"a": account_id}).fetchall()
    return {(r.kind, r.channel): r.enabled for r in rows}
