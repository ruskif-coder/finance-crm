# -*- coding: utf-8 -*-
"""Тон уведомления — один словарь на всю систему.

Слов было ДВА. Реестр событий говорил `danger | warning | success | info`, а сканер,
каталог рассылки площадкам, письмо и панель — `bad | warn | ok | info`. Совпадал только
`info`, и потому расхождение не бросалось в глаза: оно проявлялось тихо и только на
событиях, чей тон приходит из реестра, а не из ступени сработки.

Как это выглядело у человека (замер 14.09.2026):

* в письме событие `invoice_overdue` с реестровым `danger` не находило себя в таблице
  пилюль и уезжало по умолчанию в «к сведению» — то есть просроченный счёт выглядел
  справкой;
* в счётчиках дайджеста такой тон не попадал ни в одну колонку: письмо из пяти событий
  показывало «срочно 3», а про оставшиеся два молчало;
* в панели `TONE_ORDER['danger']` не существует, сортировка давала ему вес 9, и строка
  падала в самый низ — ниже «готово».

Поэтому здесь одно место, где слово приводится к канону, и один канон:

    bad   блокирует работу        срочно
    warn  требует решения         нужно решение
    ok    подтверждение           готово
    info  к сведению              к сведению

Старые слова остаются понимаемыми навсегда: они записаны в `notifications.tone` у уже
созданных строк, и переписывать историю ради словаря незачем.
"""
from __future__ import annotations

from typing import Optional

# Порядок — это ТЯЖЕСТЬ, а не алфавит: по нему сортируется панель и раскладывается
# дайджест. «К сведению» стоит выше «готово», потому что готовое уже не требует
# внимания вовсе.
TONES = ("bad", "warn", "info", "ok")

# Прежние имена → канон. Односторонний: обратно не переводим нигде.
ALIASES = {"danger": "bad", "warning": "warn", "success": "ok",
           "error": "bad", "critical": "bad", "good": "ok"}

DEFAULT = "info"


def norm(value: Optional[str]) -> str:
    """Привести тон к канону. Пустое и незнакомое — «к сведению».

    Незнакомое НЕ падает исключением намеренно: тон приезжает из базы, где лежат строки
    трёхлетней давности, и уведомление важнее строгости словаря. Ловит опечатки прибор
    `test_tone_vocabulary`, а не отправка письма.
    """
    v = (value or "").strip().lower()
    v = ALIASES.get(v, v)
    return v if v in TONES else DEFAULT


def worse(a: Optional[str], b: Optional[str]) -> bool:
    """Тон `a` тяжелее `b`. Ухудшение — единственная причина снова зажечь строку
    непрочитанной, поэтому сравнение живёт рядом со словарём, а не в шине."""
    return TONES.index(norm(a)) < TONES.index(norm(b))
