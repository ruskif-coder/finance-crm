# -*- coding: utf-8 -*-
"""Один запуск на объект: необратимые вызовы наружу не идут параллельно.

Кнопки «DSP» и «ПИКСЕЛЬ WR» — обычные `def`, FastAPI исполняет их в пуле потоков, и
двойной клик означает два одновременных прохода по одной РК. Проверка «уже заведено?»
в каждом из них видит пустоту, и в чужом кабинете появляются две кампании и два
креатива на площадку, которые по API не удалить (аудит 23.09.2026, 4.H2).

ПОЧЕМУ ОТДЕЛЬНОЕ СОЕДИНЕНИЕ. Выгрузка коммитит после каждого креатива, а сессия при
`commit` возвращает соединение в пул — блокировка уровня сессии Postgres уехала бы
вместе с ним и осталась бы висеть на чужом запросе. Поэтому замок держит своё
соединение от входа до выхода и снимается ЯВНО: `close()` отдаёт соединение в пул
живым, а не закрывает его.

ПОЧЕМУ `try`, А НЕ ОЖИДАНИЕ. Второй клик не должен ждать минуту, пока первый заведёт
девятнадцать креативов, а потом пройти по уже заведённому: ему честнее сразу сказать
«идёт», и человек обновит экран.
"""
from contextlib import contextmanager

from sqlalchemy import text

# Первый ключ блокировки — вид операции. 7301 конвейер годового плана, 7302 дайджест.
DSP_PROVISION = 7303
WEBORAMA_PROVISION = 7304
MAIL_FLUSH = 7305          # досылка писем — один прогон за раз
OUTWARD_DIGEST = 7306      # дайджест площадкам — один прогон за раз
STAFF_DISPATCH = 7307      # досылка уведомлений сотрудникам — один прогон за раз
WEBORAMA_DEMO = 7308       # демо Weborama: создание объекта — по одному (аудит 01.10.2026, С-7)
DSP_TARGETING_COPY = 7309  # копия нацеливания — один проход на комплект (02.10.2026)
CAMPAIGN_SHARES = 7310     # статусы площадок и доли РК — по одному изменению за раз (07.10.2026)


class CampaignBusy(RuntimeError):
    """Другой запрос сейчас меняет доли этой РК и не отпускает замок дольше предела ожидания."""


def lock_campaign_shares(db, campaign_id: int, wait_seconds: int = 60) -> None:
    """Блокирующий замок ТРАНЗАКЦИИ на доли и статусы площадок РК. Снимается на commit/rollback.

    ЗАЧЕМ (07.10.2026, LBS2QH). Смена статуса площадки сразу пересчитывает доли всей РК по статусам.
    Четыре запроса «запустить площадку» шли параллельно, и неподтверждённых статусов соседей ни один не
    видел: каждый считал «три прежние + я = четыре запущенных», при четырёх площадках потолок доли
    невыполним и поднимается до равной доли — в строки легло 0,25 / 125 000 при сумме долей 1,75.

    ПОЧЕМУ ЭТОТ ЗАМОК. Отдельный от `only_one`: тот неблокирующий и живёт на отдельном соединении, а
    здесь нужно ровно обратное — второй ЖДЁТ первого и после его commit читает уже подтверждённые статусы
    (READ COMMITTED видит их со следующего запроса), а замок отпускается тем же commit, которым изменения
    становятся видны соседям. Поэтому он на той же сессии.

    БЕРЁТСЯ ДО ПЕРВОЙ ЗАПИСИ. Запрос, уже изменивший строку площадки и только потом ставший в очередь,
    держит её, а первый хочет её обновить при пересчёте, — взаимный затор. Раньше записи ему нет.

    Ожидание ограничено (`lock_timeout`): зависший держатель не должен вешать остальных, человек получает
    понятный отказ. Свои несохранённые правки сбрасываются на сервер, затем сессия перечитывается — всё,
    что она успела прочитать до замка, могло устареть.
    """
    from sqlalchemy.exc import OperationalError
    db.flush()
    db.execute(text(f"SET LOCAL lock_timeout = '{int(wait_seconds)}s'"))
    try:
        db.execute(text("SELECT pg_advisory_xact_lock(:a, :b)"),
                   {"a": CAMPAIGN_SHARES, "b": int(campaign_id)})
    except OperationalError as e:
        db.rollback()
        raise CampaignBusy("РК сейчас пересчитывается другим запросом — повторите через минуту") from e
    db.expire_all()


@contextmanager
def only_one(kind: int, obj_id: int, busy_error, what: str, where: str = "по этой РК"):
    """Пропустить внутрь один проход на `(kind, obj_id)`; второму — `busy_error`."""
    from app.database import engine

    conn = engine.connect()
    try:
        got = conn.execute(text("SELECT pg_try_advisory_lock(:a, :b)"),
                           {"a": kind, "b": int(obj_id)}).scalar()
        conn.commit()
        if not got:
            raise busy_error(f"{what} {where} уже идёт — дождитесь окончания "
                             f"и обновите экран")
        try:
            yield
        finally:
            try:
                conn.execute(text("SELECT pg_advisory_unlock(:a, :b)"),
                             {"a": kind, "b": int(obj_id)})
                conn.commit()
            except Exception:  # noqa: BLE001
                # Не снялась — соединение в пул НЕ возвращаем: с висящим замком оно
                # отвечало бы «уже идёт» каждому следующему нажатию. `invalidate`
                # закрывает его по-настоящему, и замок уходит вместе с сессией.
                conn.invalidate()
    finally:
        conn.close()


