# -*- coding: utf-8 -*-
"""Ставка НДС: текущая — для новых расчётов, по дате — для того, у чего своей нет.

ПРАВИЛО ВЛАДЕЛЬЦА 23.09.2026. Ставка НДС фиксируется НА ДАТУ РАСЧЁТА и живёт у самой
записи: у операции (`operations.vat_rate`), у версии медиаплана (`sales_media_plans.vat_rate`),
у приложения к договору (`sales_annexes.vat_rate`). До 2026 года ставка была 20 %, с 2026 —
22 %. Пересчёт уже посчитанного по новой ставке недопустим.

Отсюда две функции и ни одной константы «22» в модулях:

  · `current(db)` — для НОВОГО расчёта: ставка из карточки нашего юрлица («НДС приход»).
    Её правят в справочнике, когда меняется закон, — код не трогается;
  · `on(date)` — для записи, у которой своей ставки нет (старая сделка без медиаплана и без
    суммы с НДС): ставка по ЗАКОНУ на дату, к которой относится запись. Это не пересчёт —
    это единственный способ показать такую запись верно.
"""
from __future__ import annotations

from datetime import date
from typing import Optional

# История ставки по закону: (действует с, ставка %). Список от новых к старым; всё, что
# раньше последней границы, — по `BEFORE`.
LAW_RATES = ((date(2026, 1, 1), 22.0),)
BEFORE = 20.0

# Запас, если в карточке нашего юрлица ставка не задана: текущая по закону.
DEFAULT_PCT = LAW_RATES[0][1]


def on(d: Optional[date]) -> float:
    """Ставка по закону на дату. Нет даты — текущая по закону."""
    if d is None:
        return DEFAULT_PCT
    for since, rate in LAW_RATES:
        if d >= since:
            return rate
    return BEFORE


def current(db) -> float:
    """Ставка для НОВОГО расчёта — из карточки нашего юрлица, иначе текущая по закону."""
    from app import own_company
    cp = own_company.sole(db)
    rate = getattr(cp, "vat_rate_income", None) if cp else None
    return float(rate) if rate else DEFAULT_PCT


# Ставки, которые бывали по закону. Ставка, выведенная делением посчитанных сумм, —
# приближение: суммы округлены до копеек, у старых планов до рублей, и 100 / 121,98 даёт
# 21,98 вместо 22. Хранить такое нельзя: пересохранение пересчитает сумму по кривой ставке
# и увезёт её в сделку (ревью 23.09.2026).
KNOWN_PCTS = tuple(sorted({BEFORE, *(r for _, r in LAW_RATES)}))
SNAP_TOLERANCE = 0.5


def snap(pct: Optional[float]) -> Optional[float]:
    """Ближайшая законная ставка, если выведенная лежит к ней ближе допуска, иначе None.

    None означает «из сумм ставку не вывести» (17 %, 0 % при ошибке ввода суммы с НДС) —
    вызывающий берёт ставку по закону на дату записи, а не угаданное число."""
    if pct is None:
        return None
    best = min(KNOWN_PCTS, key=lambda k: abs(k - pct))
    return best if abs(best - pct) <= SNAP_TOLERANCE else None


def for_year(db, year: int) -> float:
    """Ставка для выгрузки ГОДА: год, целиком лежащий до последней смены закона, — по закону
    того года (годовой план 2025 — 20 %); текущий и будущие — текущая ставка юрлица.

    Годовая выгрузка не хранит расчёта, она собирается заново при каждом скачивании, и
    считать 2025 год по сегодняшней ставке значит пересчитать прошлое (ревью 23.09.2026)."""
    end = date(int(year), 12, 31)
    if end < LAW_RATES[0][0]:
        return on(end)
    return current(db)
