/**
 * Срочность задания — ОДНА функция на весь кабинет.
 *
 * До 30.08.2026 их было две, и они противоречили друг другу на одном экране: сводка
 * сверху считала просроченным всё, что висит три дня и дольше (`waiting_days >= 3`),
 * а карточка ниже — то, у чего прошёл старт. Владелец увидел это первым: «как РК со
 * стартом через 95 дней может быть статус просрочено?». Карточку тогда починили,
 * счётчик остался — потому что правило жило в двух местах, а исправили одно.
 *
 * Считаем от СТАРТА, а не от времени ожидания. Ждать решения три месяца до старта
 * нормально; ненормально молчать, когда размещение уже должно идти. Сколько задание
 * висит — отдельная подпись, ориентир, а не приговор.
 *
 * Зеркало серверной `app/traffic/urgency.py`, но НЕ её копия, и пороги намеренно свои:
 * там вопрос «когда нам садиться за проверку» (порог 2 дня, у нас есть запас на
 * пересборку), здесь — «когда площадке отвечать» (3 дня, ей ещё нужно посмотреть сайт).
 * Общим обязан остаться СПОСОБ счёта — от даты старта, — а не число.
 */

/** Дней до даты. Отрицательное — дата прошла. `null`, если считать не от чего. */
export const daysTo = (iso, today) => {
  if (!iso || !today) return null
  const d = new Date(`${String(iso).slice(0, 10)}T00:00:00`)
  if (Number.isNaN(d.getTime())) return null
  return Math.round((d - new Date(today.getFullYear(), today.getMonth(), today.getDate())) / 864e5)
}

export const SOON_DAYS = 3

/** `'overdue' | 'soon' | 'normal'` — по дате старта кампании. */
export const urgency = (periodFrom, today) => {
  const n = daysTo(periodFrom, today)
  if (n === null) return 'normal'
  if (n < 0) return 'overdue'
  return n <= SOON_DAYS ? 'soon' : 'normal'
}

/** Подпись к дате: «через 4 дн.» / «сегодня» / «7 дн. назад». */
export const startNote = (periodFrom, today) => {
  const n = daysTo(periodFrom, today)
  if (n === null) return ''
  return n < 0 ? `${-n} дн. назад` : n === 0 ? 'сегодня' : `через ${n} дн.`
}
