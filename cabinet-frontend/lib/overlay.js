/**
 * Закрытие модального окна кликом по подложке — так, чтобы выделение текста мышкой
 * не считалось кликом.
 *
 * Копия `frontend/lib/overlay.js`: у кабинета свой пакет и свой сборщик, общего слоя
 * с финмодулем нет. Копируется вместе с разбором, потому что без него правило выглядит
 * лишним и первый же «упрощающий» рефакторинг вернёт ошибку.
 *
 * ПОЧЕМУ НЕ ЛЕЧИТСЯ ПРОВЕРКОЙ `e.target === e.currentTarget`. Событие `click` рождается
 * не там, где отпустили кнопку, а на ОБЩЕМ ПРЕДКЕ места нажатия и места отпускания.
 * Человек выделяет текст внутри окна, ведёт мышь и отпускает на подложке — общий предок
 * это подложка, проверка проходит, и окно закрывается вместе с выделенным.
 *
 * Цель последнего нажатия хранится в модуле, а не в состоянии: замыкание пересоздаётся
 * при перерисовке между нажатием и отпусканием, и настоящий клик переставал бы закрывать.
 */
// Подложка помечается `data-overlay`: по метке globals.css запрещает прокрутку страницы под открытым окном
// (правило владельца 26.10.2026). Подложка, закрывающаяся не кликом, ставит `data-overlay` сама.
let lastMouseDownTarget = null

export function overlayClose(onClose) {
  return {
    'data-overlay': '',
    onMouseDown: (e) => { lastMouseDownTarget = e.target },
    onClick: (e) => {
      if (e.target === e.currentTarget && lastMouseDownTarget === e.currentTarget) {
        onClose?.(e)
      }
    },
  }
}
