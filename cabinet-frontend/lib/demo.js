/* Статус оплаты живёт на ГРУППЕ «услуга + период», никогда на РК. Ключи собираются от
   того же сдвига, что и строки: разъедься они — и группа осталась бы без статуса,
   а экран показал бы «счёт не выставлен» там, где он оплачен. */
const PAY_TPL = !SHOW_MONEY ? [] : [
  ['еФарм', 0, 'счёт не выставлен'],
  ['Альфарм-Таргет', 0, 'счёт не выставлен'],
  ['еФарм', -1, 'ждёт акта'],
  ['Альфарм-Таргет', -1, 'оплачено'],
]

/** Витрина на заданный месяц: строки, статусы оплаты и предикат закрытого месяца. */
export const buildDemo = (nowMonth) => {
  const CAMPS = CAMPS_TPL.map(t => {
    const m = shiftMonth(nowMonth, t[2])
    const end = t[5] || lastDay(m)
    const mm = m.slice(5)
    return [t[0], t[1], m, t[3], `${pad(t[4])}.${mm} — ${pad(end)}.${mm}`,
            t[6], t[7], t[8], t[9], t[10]]
  })
  const GROUP_PAY = {}
  PAY_TPL.forEach(([service, off, state]) => {
    GROUP_PAY[`${service}|${shiftMonth(nowMonth, off)}`] = state
  })
  return {
    NOW_MONTH: nowMonth, CAMPS, GROUP_PAY,
    isClosed: (period) => period < nowMonth,
  }
}

/** Витрина «на сегодня». Опорный месяц на первой отрисовке, настоящий — после
    монтирования: только так серверная разметка и клиентская совпадают. */
export function useDemoNow() {
  const [month, setMonth] = useState(SSR_ANCHOR)
  useEffect(() => { setMonth(monthKey(new Date())) }, [])
  return useMemo(() => buildDemo(month), [month])
}

