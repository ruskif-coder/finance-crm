/* Состояния, при которых месяц считается закрытым для выставления счёта. */
const CLOSED = ['окончена', 'сверка', 'ОРД', 'ожидает оплаты', 'архив']

/** Разбор строки в объект — чтобы дальше не помнить порядок полей. */
export const camp = (c) => ({
  brand: c[0], service: c[1], period: c[2], surface: c[3], flight: c[4],
  plan: c[5], fact: c[6], cpm: c[7], state: c[8], mark: c[9] || null,
})

/** Сумма строки: факт ÷ 1000 × CPM. От CPM же будем считать и на живых данных. */
export const sum = (c) => Math.round(c.fact / 1000 * c.cpm)

/** РК в архиве без открутки — отказ до старта: в счёт и в план не идёт (правило 1.3). */
export const inBill = (c) => !(c.state === 'архив' && !c.fact)

/** «Ждёт запуска» не занижает открутку месяца — иначе не начавшееся размещение даёт
    24 % вместо 63 % у закрывающегося периода (правило 1.3). */
export const inPace = (c) => inBill(c) && c.state !== 'ждёт запуска'

/** Счёт нельзя выставить, пока в срезе есть идущие РК (правило 1.4). */
export const billBlocked = (rows) => rows.some(c => !CLOSED.includes(c.state))

export const isClosed = (period) => period < NOW_MONTH
